#!/usr/bin/env bash
# Regenerate crates/saber-abi/src/bindings.rs from include/saber_abi.h.
#
# The output is COMMITTED and CI (`abi-bindgen`) reruns this script and requires an empty diff, so
# it has to be deterministic. Three things make it so:
#
#   1. the bindgen and rustfmt versions are pinned below and the script FAILS LOUD on a mismatch
#      (bindgen stamps its own version into the first line of the output, and rustfmt's line
#      breaking changes between releases);
#   2. every flag that affects naming or layout is spelled out rather than left to a default that
#      can change between bindgen releases (note what is NOT passed: `--with-derive-default` is
#      deliberately absent, because bindgen implements Default for pointer-bearing structs with an
#      `unsafe` zero-fill, and (a) `unsafe` outside saber-hip/saber-hsa is a CI failure, (b) a
#      manifest struct full of NULL string pointers is a malformed manifest, not a default);
#   3. the header is passed as a repo-relative path from the repo root and the only -I is the repo
#      root, so no absolute path from this machine can reach the output.
#
# The host has no libclang, so this normally runs inside the dev image:
#
#     tools/dev.sh crates/saber-abi/regen.sh
#
# Running it directly on a machine that does have libclang works too; set LIBCLANG_PATH if clang is
# not in a default location.
set -euo pipefail

EXPECT_BINDGEN="0.73.2"
EXPECT_RUSTFMT="1.9.0-stable"

REPO=$(cd "$(dirname "$0")/../.." && pwd)
cd "$REPO"

HEADER=include/saber_abi.h
OUT=crates/saber-abi/src/bindings.rs

command -v bindgen >/dev/null 2>&1 || {
  echo "regen: bindgen not found. Run this inside the dev image: tools/dev.sh crates/saber-abi/regen.sh" >&2
  exit 2
}

got_bindgen=$(bindgen --version | awk '{print $2}')
got_rustfmt=$(rustfmt --version | awk '{print $2}')
if [ "$got_bindgen" != "$EXPECT_BINDGEN" ]; then
  echo "regen: bindgen $got_bindgen != pinned $EXPECT_BINDGEN. Output would differ from the committed" >&2
  echo "       bindings and CI would fail. Update the dev image, or bump EXPECT_BINDGEN here and" >&2
  echo "       regenerate in the same commit." >&2
  exit 3
fi
if [ "$got_rustfmt" != "$EXPECT_RUSTFMT" ]; then
  echo "regen: rustfmt $got_rustfmt != pinned $EXPECT_RUSTFMT (same reason as above)." >&2
  exit 3
fi

bindgen "$HEADER" \
  --output "$OUT" \
  --allowlist-file '.*saber_abi\.h' \
  --default-enum-style consts \
  --no-prepend-enum-name \
  --with-derive-hash \
  --with-derive-partialeq \
  --with-derive-eq \
  --use-core \
  --sort-semantically \
  --raw-line '// @generated by crates/saber-abi/regen.sh from include/saber_abi.h -- DO NOT EDIT.' \
  --raw-line '// Regenerate with: tools/dev.sh crates/saber-abi/regen.sh' \
  --raw-line '#![allow(non_upper_case_globals, non_camel_case_types, non_snake_case)]' \
  -- \
  -I "$REPO" \
  -std=c11

echo "regen: wrote $OUT (bindgen $got_bindgen, rustfmt $got_rustfmt)"
