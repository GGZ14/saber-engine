/// The int8 twin of a had32 producer descriptor ([`crate::macaq::had_twin`]'s output): the same
/// arguments and grid, `_had32_` -> `_hadi8_`, and the A-TILED instantiation at every M (`tiled0` ->
/// `tiled1`; the row-major gdn-norm name gains `_tiled1`). Refuses, by name, a descriptor that is not a
/// had32 twin or whose twin the code objects do not carry (row 3's `arnq_had32`: an MXFP4 GEMM).
pub fn i8_twin(had: &LaunchDescriptor) -> Result<LaunchDescriptor> {
    if !crate::macaq::is_twin(had) {
        return Err(Error::Rule(format!(
            "macaq iu8: `{}` (plugin `{}`) is not a had32 producer twin; an iu8 plan quantizes only \
             through the Hadamard producers",
            had.kernel, had.plugin
        )));
    }
    let plugin = I8_PLUGINS
        .iter()
        .find(|(h, _)| *h == had.plugin)
        .map(|(_, i)| (*i).to_owned())
        .ok_or_else(|| {
            Error::Rule(format!(
                "macaq iu8: `{}` (plugin `{}`) has no int8 twin (fusion-map row 3 is an MXFP4 GEMM; \
                 an iu8 plan never folds it)",
                had.kernel, had.plugin
            ))
        })?;
    let mut kernel = had.kernel.replacen("_had32_", "_hadi8_", 1);
    if let Some(stem) = kernel.strip_suffix("_tiled0") {
        kernel = format!("{stem}_tiled1");
    } else if kernel.starts_with("gdn_norm_quant_hadi8_") && !kernel.ends_with("_tiled1") {
        kernel.push_str("_tiled1");
    }
    if !I8_SYMBOLS.iter().any(|(p, k)| *p == plugin && *k == kernel) {
        return Err(Error::Rule(format!(
            "macaq iu8: `{}` maps to `{kernel}`, which `{plugin}` does not carry",
            had.kernel
        )));
    }
    let mut t = had.clone();
    t.plugin = plugin;
    t.kernel = kernel;
    Ok(t)
}

/// Is this descriptor an int8 twin?
#[must_use]
pub fn is_i8_twin(d: &LaunchDescriptor) -> bool {
    I8_SYMBOLS
        .iter()
        .any(|(p, k)| d.plugin == *p && d.kernel == *k)
}

