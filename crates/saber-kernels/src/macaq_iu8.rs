/// The weight kind of an iu8 GEMM.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum WKind {
    /// Per-row int4 `[-8, 7]`, fragment-ordered nibbles (pack layout `LAYOUT_I4_ROW_FRAG`).
    I4,
    /// Per-row int8 `[-127, 127]`, fragment-ordered bytes (pack layout `LAYOUT_I8_ROW_FRAG`).
    I8,
}

impl WKind {
    fn tag(self) -> &'static str {
        match self {
            WKind::I4 => "w4",
            WKind::I8 => "w8",
        }
    }
    fn op(self) -> &'static str {
        match self {
            WKind::I4 => OP_W4,
            WKind::I8 => OP_W8,
        }
    }
}

/// The families an iu8 GEMM past the decode band runs (all integer-exact: the choice moves no byte).
/// `MidDec` = the decode body at M 65..[`MID_DEC_MAX_M`] (`macaq_iu8f_dec_*_tm{5..8}`, the iu8 analogue of the
/// MXFP4 small-chunk route); `Bm128` / `Bm64` = the prefill tile at a 128 / 64-row block
/// (`macaq_iu8f_pf_*_bm{128,64}`); `Bm256` = the plain `macaq_iu8` prefill tile.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum PfFamily {
    MidDec,
    Bm128,
    Bm64,
    Bm256,
    /// A parametric prefill tile (`macaq_iu8f_pf_*_t{ptm}w{pwm}n{tn}k{lbk}[p]`, generated by
    /// `tools/gen_macaq_iu8f.py` `SHIP_PFX`).
    Tile(PfTile),
}

/// One parametric prefill tile: `ptm` 16-row fragments a wave x `pwm` waves down M (BM = `pwm * ptm * 16`),
/// `tn` 16-column fragments a wave x 2 waves across N (BN = `2 * tn * 16`), K slab `lbk`, `pipe` = the next slab's W in
/// registers during this slab's WMMAs (the W stage double-buffered). `pwm * 64` threads. Integer-exact: the same
/// bytes as every other family.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct PfTile {
    pub ptm: u32,
    pub pwm: u32,
    pub tn: u32,
    pub lbk: u32,
    pub pipe: bool,
}

impl PfTile {
    /// The tile's rows.
    #[must_use]
    pub const fn bm(self) -> u32 {
        self.pwm * self.ptm * 16
    }
    /// The tile's columns.
    #[must_use]
    pub const fn bn(self) -> u32 {
        2 * self.tn * 16
    }
    /// The tile's threads.
    #[must_use]
    pub const fn threads(self) -> u32 {
        self.pwm * 64
    }
    /// The symbol at weight kind `w`.
    #[must_use]
    pub fn symbol(self, w: WKind) -> String {
        format!(
            "macaq_iu8f_pf_{}_t{}w{}n{}k{}{}",
            w.tag(),
            self.ptm,
            self.pwm,
            self.tn,
            self.lbk,
            if self.pipe { "p" } else { "" }
        )
    }
}

/// The mid decode band's last row count (DTM 8).
pub const MID_DEC_MAX_M: u32 = 128;

/// The prefill band past the decode band, SPEED DATA (measured IC-cold per launch at every TP=2 shape x the rungs
/// 96..1,024). Rows `(largest N, last M, family)`: the FIRST row with `n <=
/// largest N` and `m <= last M` names the family; no row = [`PfFamily::Bm256`]. Measured: the one-n-block ba op
/// (N 48) is fastest on BM 64 at every M (29.6 vs 50.6 us); the 5,120-column row-parallel ops (out / o / down) on
/// BM 64 to 320 rows and BM 128 to 512; the wide ops (qkvz / qkv / gate_up) on BM 128 to 128 rows, BM 64 at 192,
/// BM 128 to 384; BM 256 above. The mid decode band ([`PfFamily::MidDec`]) never won a cell (-> no row; its best
/// cells, TP=1 qkvz / qkv at M 96, sit within 7 us of BM 128). The TP=1 sweep adds one row: the 34,816-
/// column gate_up keeps BM 256 at 129..256 rows (BM 64 / 128 lose 29-57 us there); every other TP=1 cell follows
/// the TP=2 rows (the ops of N <= 17,408 are unchanged by it).
pub const PF_BAND: &[(u32, u32, PfFamily)] = &[
    (128, u32::MAX, PfFamily::Bm64),
    (5120, 320, PfFamily::Bm64),
    (5120, 512, PfFamily::Bm128),
    (u32::MAX, 128, PfFamily::Bm128),
    (17408, 192, PfFamily::Bm64),
    (17408, 384, PfFamily::Bm128),
    (u32::MAX, 256, PfFamily::Bm256),
    (u32::MAX, 384, PfFamily::Bm128),
];

/// The parametric tiles at the p192 / p256 / p320 rungs (129..320 rows), SPEED DATA (measured IC-cold per launch at
/// every TP=2 and TP=1 shape x M 128..384 over 72 candidate tiles), checked BEFORE
/// [`PF_BAND`]. Rows `(W8, first M, last M, largest N, tile)`, first match wins; no row = [`PF_BAND`]'s family. Chosen per
/// (kind, N class, rung) on the served-count-weighted sum over both TPs: the ba gate (N <= 128) on a 64-row x 64-column
/// pipelined tile (14 us vs BM 64's 29.5, = the MXFP4 pack's skinny body); the wide ops on BM 192 / 256 / 320 pipelined tiles
/// (one m-block at the rung, the W slab in flight); the 5,120-column W4 ops on BM 256 x BN 64 (p256) and BM 160 x BN 64
/// (p320); W8 at p320 on BM 64 x BN 64. Rows the sweep did not move (W4 / W8 narrow at p192, W8 at p256) keep
/// [`PF_BAND`]'s family.
///
/// The p96 (65..96), p128 (97..128) and p384 (321..384) rows below were chosen on the same served-weighted law
/// from the SHIPPED object's own timing (the sweep's winners re-timed in the build that ships; code placement moved
/// three sweep winners -- `w4_t3w2n4k64p`, `w4_t2w2n2k128p`, `w8_t3w4n2k64p` -- behind the band tiles, so they are
/// carried in the object unrouted): the ba gate on the 64 x 64 tile at all three rungs; p96 on a 96-row x BN 64
/// pipelined tile (PWM 2, LBK 128) for every W4 op but the gate, W8 on BM 64 x BN 64; p128 on BM 64 x BN 64
/// (5,120-column W4 / W8) and BM 128 x BN 128 at LBK 128 to 8,192 columns, wider ops keep BM 128; p384 on a 384-row
/// (PWM 8) x BN 128 tile for every wide op, the 5,120-column ops keep BM 128. Nothing above 384 rows is routed here.
pub const PF_TILES: &[(bool, u32, u32, u32, PfTile)] = &[
    // p96
    (false, 65, 96, 128, tile(1, 4, 2, 128, true)),
    (true, 65, 96, 5120, tile(1, 4, 2, 128, false)),
    (false, 65, 96, u32::MAX, tile(3, 2, 2, 128, true)),
    // p128
    (false, 97, 128, 128, tile(1, 4, 2, 128, true)),
    (false, 97, 128, 5120, tile(1, 4, 2, 128, true)),
    (true, 97, 128, 5120, tile(1, 4, 2, 128, false)),
    (false, 97, 128, 8192, tile(2, 4, 4, 128, true)),
    (false, 97, 128, u32::MAX, PF_KEEP),
    // p384
    (false, 321, 384, 128, tile(1, 4, 2, 128, true)),
    (false, 321, 384, 5120, PF_KEEP),
    (true, 321, 384, 5120, PF_KEEP),
    (false, 321, 384, u32::MAX, tile(3, 8, 4, 128, true)),
    // p192 / p256 / p320
    (false, 129, 320, 128, tile(1, 4, 2, 128, true)),
    (false, 193, 256, 5120, tile(4, 4, 2, 128, true)),
    (false, 257, 320, 5120, tile(5, 2, 2, 64, true)),
    (true, 257, 320, 5120, tile(1, 4, 2, 128, false)),
    (false, 129, 192, 5120, PF_KEEP),
    (true, 129, 256, 5120, PF_KEEP),
    (false, 129, 192, u32::MAX, tile(3, 4, 4, 64, true)),
    (false, 193, 256, u32::MAX, tile(4, 4, 4, 64, true)),
    (false, 257, 320, u32::MAX, tile(5, 4, 4, 64, true)),
];

/// A [`PF_TILES`] row's tile.
const fn tile(ptm: u32, pwm: u32, tn: u32, lbk: u32, pipe: bool) -> PfTile {
    PfTile {
        ptm,
        pwm,
        tn,
        lbk,
        pipe,
    }
}

/// The [`PF_TILES`] marker for "keep [`PF_BAND`]'s family" (a cell the sweep measured and left).
const PF_KEEP: PfTile = tile(0, 0, 0, 0, false);

/// The family an `m x n` GEMM of weight kind `w` past the decode band runs: a [`PF_TILES`] row, else [`pf_family`].
#[must_use]
pub fn pf_family_of(w: WKind, m: u32, n: u32) -> PfFamily {
    match PF_TILES.iter().find(|(w8, first, last, max_n, _)| {
        *w8 == (w == WKind::I8) && m >= *first && m <= *last && n <= *max_n
    }) {
        Some(&(_, _, _, _, t)) if t != PF_KEEP => PfFamily::Tile(t),
        _ => pf_family(m, n),
    }
}

/// The mid decode band's split if a row names it (speed data): `true` = [`decode_split`]'s law, `false` =
/// one split (the MXFP4 small-chunk form; no workspaces in a prefill plan).
pub const MID_DEC_SPLITS: bool = false;

/// The band family for an `m x n` GEMM past the decode band ([`PF_BAND`]; [`pf_family_of`] is the routed one).
#[must_use]
pub fn pf_family(m: u32, n: u32) -> PfFamily {
    PF_BAND
        .iter()
        .find(|(max_n, last, _)| n <= *max_n && m <= *last)
        .map_or(PfFamily::Bm256, |&(_, _, f)| f)
}

/// The chosen cell.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Cell {
    /// The code object (`macaq_iu8`, or [`FUSED_PLUGIN`] for the band families).
    pub plugin: &'static str,
    pub symbol: String,
    pub grid: [u32; 3],
    pub threads: u32,
    /// The split count (decode band; 1 at prefill).
    pub ks: u32,
}

/// The split a decode-band GEMM of `nblk` 128-column blocks and `slabs` 128-deep K slabs runs: double
/// until the grid reaches [`KS_TARGET_BLOCKS`], each split keeps >= 2 slabs, the partials fit.
#[must_use]
pub fn decode_split(m: u32, n: u32, k: u32) -> u32 {
    let nblk = n.div_ceil(BLOCK_N);
    let slabs = k / DEC_SLAB_K;
    let mut ks = 1;
    while nblk * ks < KS_TARGET_BLOCKS
        && ks < KS_MAX
        && slabs / (ks * 2) >= 2
        && u64::from(ks * 2) * u64::from(m) * u64::from(n) * 4 <= PARTIAL_CAP_BYTES
    {
        ks *= 2;
    }
    ks
}

/// The cell an iu8 GEMM of `m x n x k` runs.
///
/// # Errors
/// An empty launch; N not a multiple of 16 (whole n-fragments: the pack's fragment order); K not a
/// multiple of 128 (the decode slab; every 27B K is); a counter table past its capacity.
pub fn cell(w: WKind, m: u32, n: u32, k: u32) -> Result<Cell> {
    let op = w.op();
    if m == 0 || n == 0 || k == 0 {
        return Err(Error::Rule(format!(
            "{op}: {m} x {n} x {k} has nothing to do; an empty launch is a caller bug"
        )));
    }
    if n % 16 != 0 || k % DEC_SLAB_K != 0 {
        return Err(Error::Rule(format!(
            "{op}: N={n} must be a multiple of 16 (whole fragments) and K={k} of {DEC_SLAB_K} (the slab)"
        )));
    }
    let nblk = n.div_ceil(BLOCK_N);
    if u64::from(nblk) * 4 > COUNTER_CAP_BYTES {
        return Err(Error::Rule(format!(
            "{op}: N={n} needs {nblk} n-block counters, past the {COUNTER_CAP_BYTES} B table"
        )));
    }
    if m <= DECODE_MAX_M {
        let tm = m.div_ceil(16);
        let ks = decode_split(m, n, k);
        return Ok(Cell {
            plugin: PLUGIN,
            symbol: format!("macaq_iu8_dec_{}_tm{tm}", w.tag()),
            grid: [nblk, 1, ks],
            threads: 256,
            ks,
        });
    }
    let fam = pf_family_of(w, m, n);
    if fam == PfFamily::MidDec && m <= MID_DEC_MAX_M {
        let tm = m.div_ceil(16);
        let ks = if MID_DEC_SPLITS {
            decode_split(m, n, k)
        } else {
            1
        };
        return Ok(Cell {
            plugin: FUSED_PLUGIN,
            symbol: format!("macaq_iu8f_dec_{}_tm{tm}", w.tag()),
            grid: [nblk, 1, ks],
            threads: 256,
            ks,
        });
    }
    if let PfFamily::Tile(t) = fam {
        return Ok(Cell {
            plugin: FUSED_PLUGIN,
            symbol: t.symbol(w),
            grid: [n.div_ceil(t.bn()), m.div_ceil(t.bm()), 1],
            threads: t.threads(),
            ks: 1,
        });
    }
    let (plugin, symbol, bm) = match fam {
        PfFamily::Bm128 => (
            FUSED_PLUGIN,
            format!("macaq_iu8f_pf_{}_bm128", w.tag()),
            128,
        ),
        PfFamily::Bm64 => (FUSED_PLUGIN, format!("macaq_iu8f_pf_{}_bm64", w.tag()), 64),
        PfFamily::Bm256 | PfFamily::MidDec | PfFamily::Tile(_) => {
            (PLUGIN, format!("macaq_iu8_pf_{}_tn4_lbk64", w.tag()), PF_BM)
        }
    };
    Ok(Cell {
        plugin,
        symbol,
        grid: [nblk, m.div_ceil(bm), 1],
        threads: 256,
        ks: 1,
    })
}

/// The DFlash2 DRAFTER's own rows (`dflash_iu8::DRAFT_SHAPES`), SPEED DATA, read ONLY by [`draft_cell`] /
/// [`resolve_draft`] (the drafter plan's GEMMs): the target's [`cell`] never reads them, so no target row moves even
/// where a drafter shape equals a target shape (TP=2 down 5,120 x 8,704). Rows `(first M, last M, N, K, tile)`, the
/// weight kind W4. Measured inside the SHIPPED `macaq_iu8f` object (IC-cold, the launches back to back, every
/// candidate's bytes == the routed cell's): at M 33..64 the decode band's tm3 / tm4 cells
/// run the small-N drafter ops at 150-350 GB/s (qkv 58.1 us, o 40.3 at TP=2 M 64) and the 64 x 64 pipelined
/// tile `t1w4n2k128p` is fastest at every measured M for aux / qkv / o / down at both TPs (qkv 20.8, o 14.6, down 45.2
/// vs 72.5, aux 119.9 vs 157.1 at TP=2 M 64); the gate_up ops (17,408 / 34,816 columns) keep the decode cell (it wins
/// 81.6..91.2 vs 88.5..91.5 at TP=2). Integer-exact: the same bytes as the decode cell (the module doc's law).
pub const DRAFT_TILES: &[(u32, u32, u32, u32, PfTile)] = &[
    // both TPs: the aux projection (replicated)
    (33, 64, 5120, 25_600, DRAFT_T64),
    // TP=2: qkv, o_proj, down
    (33, 64, 3072, 5120, DRAFT_T64),
    (33, 64, 5120, 2048, DRAFT_T64),
    (33, 64, 5120, 8704, DRAFT_T64),
    // TP=1: qkv, o_proj, down
    (33, 64, 6144, 5120, DRAFT_T64),
    (33, 64, 5120, 4096, DRAFT_T64),
    (33, 64, 5120, 17_408, DRAFT_T64),
];

/// The [`DRAFT_TILES`] tile: the 64-row x 64-column pipelined tile (`macaq_iu8f_pf_w4_t1w4n2k128p`).
const DRAFT_T64: PfTile = tile(1, 4, 2, 128, true);

/// The cell a DRAFTER iu8 GEMM of `m x n x k` runs: a [`DRAFT_TILES`] row (W4 only), else [`cell`]'s.
///
/// # Errors
/// What [`cell`] refuses.
pub fn draft_cell(w: WKind, m: u32, n: u32, k: u32) -> Result<Cell> {
    let c = cell(w, m, n, k)?;
    if w != WKind::I4 {
        return Ok(c);
    }
    Ok(
        match DRAFT_TILES
            .iter()
            .find(|(first, last, rn, rk, _)| m >= *first && m <= *last && n == *rn && k == *rk)
        {
            Some(&(_, _, _, _, t)) => Cell {
                plugin: FUSED_PLUGIN,
                symbol: t.symbol(w),
                grid: [n.div_ceil(t.bn()), m.div_ceil(t.bm()), 1],
                threads: t.threads(),
                ks: 1,
            },
            None => c,
        },
    )
}

/// [`resolve`] at the drafter's cell ([`draft_cell`]).
///
/// # Errors
/// What [`cell`] refuses.
pub fn resolve_draft(w: WKind, m: u32, n: u32, k: u32) -> Result<LaunchDescriptor> {
    describe(w, draft_cell(w, m, n, k)?, m, n, k)
}

/// The descriptor of an iu8 GEMM: `C[m, n] = A[m, k] . W[n, k]^T` under the contract (module doc).
/// Buffers `a` (A-tiled int8), `w`, `as`, `ws`, `c` (+ `decode_partial` / `decode_counter` in the decode
/// band, named-null at `ks` 1); scalars `m`, `n`, `k`.
///
/// # Errors
/// What [`cell`] refuses.
pub fn resolve(w: WKind, m: u32, n: u32, k: u32) -> Result<LaunchDescriptor> {
    describe(w, cell(w, m, n, k)?, m, n, k)
}

fn describe(w: WKind, c: Cell, m: u32, n: u32, k: u32) -> Result<LaunchDescriptor> {
    let sig = abi::signature_for(&c.symbol)
        .ok_or_else(|| Error::Rule(format!("{}: no declared signature", c.symbol)))?;
    let values: [(&str, i64); 3] = [
        ("m", i64::from(m)),
        ("n", i64::from(n)),
        ("k", i64::from(k)),
    ];
    let (packed, bytes) = abi::pack(sig);
    let args = sig
        .iter()
        .zip(packed)
        .map(|(a, (offset, size))| Slot {
            name: a.name.to_owned(),
            offset,
            size,
            value: match values.iter().find(|(nm, _)| *nm == a.name) {
                Some((_, v)) => ArgValue::I32 { ival: *v },
                None if c.ks == 1 && (a.name == "decode_partial" || a.name == "decode_counter") => {
                    ArgValue::NullBuffer {
                        buffer: a.name.to_owned(),
                    }
                }
                None => ArgValue::Buffer {
                    buffer: a.name.to_owned(),
                },
            },
        })
        .collect();
    let workspaces = if c.ks > 1 {
        vec![
            WorkspaceReq {
                name: "decode_partial".into(),
                kind: WorkspaceKind::Scratch,
                bytes: u64::from(c.ks) * u64::from(m) * u64::from(n) * 4,
                zero_once: false,
            },
            WorkspaceReq {
                name: "decode_counter".into(),
                kind: WorkspaceKind::Persistent,
                bytes: u64::from(n.div_ceil(BLOCK_N)) * 4,
                zero_once: true,
            },
        ]
    } else {
        vec![]
    };
    Ok(LaunchDescriptor {
        op: w.op().into(),
        plugin: c.plugin.into(),
        kernel: c.symbol,
        grid: c.grid,
        block: [c.threads, 1, 1],
        shared_bytes: 0,
        kernarg_bytes: bytes,
        args,
        workspaces,
        // the split-K reduce is fused (the last-arriving split): one launch at any ks
        n_launches: 1,
    })
}

