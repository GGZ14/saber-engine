    /// The fused descriptors are the halves / the GEMM + `_nq` they replace, and refuse other cells.
    #[test]
    fn the_pair_and_row3_descriptors_carry_their_halves() {
        for m in [1u32, 8, 16, 40, 64] {
            let (q, b) = (
                resolve(WKind::I4, m, 8192, 5120).unwrap(),
                resolve(WKind::I4, m, 48, 5120).unwrap(),
            );
            let p = pair(&q, &b).unwrap();
            assert_eq!(p.grid[0], q.grid[0] * q.grid[2] + b.grid[0] * b.grid[2]);
            assert!(FUSED_SYMBOLS.contains(&p.kernel.as_str()), "{}", p.kernel);
            assert_eq!(p.op, OP_PAIR);
            assert_eq!(
                abi::signature_for(&p.kernel).map(<[_]>::len),
                Some(p.args.len())
            );
            let wsn: Vec<&str> = p.workspaces.iter().map(|w| w.name.as_str()).collect();
            for (d, sfx) in [(&q, ""), (&b, "_b")] {
                for n in ["decode_partial", "decode_counter"] {
                    let name = format!("{n}{sfx}");
                    assert_eq!(
                        wsn.contains(&name.as_str()),
                        d.grid[2] > 1,
                        "{m} {name}: {wsn:?}"
                    );
                    let null = matches!(p.arg(&name).unwrap().value, ArgValue::NullBuffer { .. });
                    assert_eq!(null, d.grid[2] == 1, "{name}");
                }
            }
            // a W8 half, or halves of different M / K, are refused
            let w8 = resolve(WKind::I8, m, 48, 5120).unwrap();
            assert!(pair(&q, &w8).is_err());
            let k = resolve(WKind::I4, m, 48, 3072).unwrap();
            assert!(pair(&q, &k).is_err());
        }
        // row 3 from the GEMM + the int8 `_nq` descriptor
        let nq = |m: u32, kernel: &str, op: &str| LaunchDescriptor {
            op: op.into(),
            plugin: "saber_ar_hadi8".into(),
            kernel: kernel.into(),
            grid: [m, 1, 1],
            block: [256, 1, 1],
            shared_bytes: 0,
            kernarg_bytes: 0,
            args: vec![
                Slot {
                    name: "k16".into(),
                    offset: 0,
                    size: 4,
                    value: ArgValue::I32 { ival: 640 },
                },
                Slot {
                    name: "slot_stride16".into(),
                    offset: 0,
                    size: 4,
                    value: ArgValue::I32 { ival: 8192 },
                },
                Slot {
                    name: "eps".into(),
                    offset: 0,
                    size: 4,
                    value: ArgValue::F32 { fval: 1e-6 },
                },
                Slot {
                    name: "drain".into(),
                    offset: 0,
                    size: 4,
                    value: ArgValue::I32 { ival: 3 },
                },
                Slot {
                    name: "acq".into(),
                    offset: 0,
                    size: 4,
                    value: ArgValue::I32 { ival: 0 },
                },
            ],
            workspaces: vec![WorkspaceReq {
                name: "ar_scratch".into(),
                kind: WorkspaceKind::IpcPeerVisible,
                bytes: 1 << 20,
                zero_once: true,
            }],
            n_launches: 1,
        };
        for (w, k) in [(WKind::I4, 3072u32), (WKind::I8, 8704)] {
            for m in [1u32, 5, 12, 16] {
                let g = resolve(w, m, 5120, k).unwrap();
                let d = ar_nq(&g, &nq(m, NQ_I8, "allreduce_exact_nq")).unwrap();
                assert_eq!(d.grid, g.grid);
                assert_eq!(d.op, OP_AR_NQ);
                assert!(FUSED_SYMBOLS.contains(&d.kernel.as_str()));
                assert!(d.kernel.contains(&format!("_{}_", w.tag())));
                assert_eq!(
                    abi::signature_for(&d.kernel).map(<[_]>::len),
                    Some(d.args.len())
                );
                assert!(
                    matches!(d.arg("ep_rows").unwrap().value, ArgValue::I32 { ival } if ival == i64::from(m))
                );
                assert!(d.workspaces.iter().any(|x| x.name == AR_TILES));
                assert!(d.workspaces.iter().any(|x| x.name == "ar_scratch"));
                // the e4m3 `_nq`, a wrong row count, tm2 are refused
                assert!(ar_nq(
                    &g,
                    &nq(
                        m,
                        "saber_ar_oneshot_2rank_exact_nq_ssqfma_had32_bf16",
                        "allreduce_exact_nq"
                    )
                )
                .is_err());
                assert!(ar_nq(&g, &nq(m + 1, NQ_I8, "allreduce_exact_nq")).is_err());
            }
            let g17 = resolve(w, 17, 5120, k).unwrap();
            assert!(ar_nq(&g17, &nq(17, NQ_I8, "allreduce_exact_nq")).is_err());
        }
        for s in FUSED_SYMBOLS {
            assert!(abi::signature_for(s).is_some(), "{s}");
        }
    }

    #[test]
    fn every_had32_producer_maps_to_its_tiled_int8_twin_with_the_same_arguments() {
        let r = LaunchRules::prod_mxfp4().expect("prod rules");
        for (op, shape) in [
            (Op::AddRmsQuant { eps: 1e-6 }, Shape::new(1, 0, 5120)),
            (Op::AddRmsQuant { eps: 1e-6 }, Shape::new(2048, 0, 5120)),
            (Op::SiluMulQuant, Shape::new(8, 8704, 0)),
            (Op::SiluMulQuant, Shape::new(2048, 17408, 0)),
            (
                Op::GdnNormQuant {
                    zs: 8192,
                    eps: 1e-6,
                },
                Shape::new(8, 3072, 0),
            ),
            (
                Op::GdnNormQuant {
                    zs: 8192,
                    eps: 1e-6,
                },
                Shape::new(2048, 3072, 0),
            ),
        ] {
            let parent = mx_resolve(op, shape, &r).unwrap();
            let had = crate::macaq::had_twin(&parent).unwrap();
            let i8 = i8_twin(&had).unwrap();
            assert!(
                i8.kernel.ends_with("_tiled1") && i8.kernel.contains("_hadi8_"),
                "{}",
                i8.kernel
            );
            assert_eq!(i8.args, had.args, "{}", i8.kernel);
            assert_eq!(i8.grid, had.grid);
            assert!(is_i8_twin(&i8));
            assert_eq!(
                abi::signature_for(&i8.kernel).map(<[_]>::len),
                abi::signature_for(&had.kernel).map(<[_]>::len),
                "{}",
                i8.kernel
            );
        }
        // a parent (not a had32 twin) is refused, and so is row 3's twin
        let parent = mx_resolve(Op::SiluMulQuant, Shape::new(8, 8704, 0), &r).unwrap();
        assert!(i8_twin(&parent).is_err());
        let mut arnq = parent.clone();
        arnq.plugin = "mxfp4_gemm_decode_arnq_had".into();
        arnq.kernel = "mxfp4_gemm_decode_arnq_had32_bk128_ks4_tm1_wperm1_nt1".into();
        assert!(i8_twin(&arnq).is_err());
    }
