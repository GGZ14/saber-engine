    /// Against the 129..320-row table alone, over every TP=2 / TP=1 shape at M 1..8192, the p96 / p128 / p384 rows
    /// route EXACTLY the cells at 65..128 and 321..384 and nowhere else; the routed cells listed.
    #[test]
    fn the_p96_p128_p384_rows_move_only_their_cells() {
        const M26: &[(bool, u32, u32, u32, PfTile)] = &[
            (false, 129, 320, 128, tile(1, 4, 2, 128, true)),
            (false, 193, 256, 5120, tile(4, 4, 2, 128, true)),
            (false, 257, 320, 5120, tile(5, 2, 2, 64, true)),
            (true, 257, 320, 5120, tile(1, 4, 2, 128, false)),
            (false, 129, 192, 5120, PF_KEEP),
            (true, 129, 256, 5120, PF_KEEP),
            (false, 129, 192, u32::MAX, tile(3, 4, 4, 64, true)),
            (false, 193, 256, u32::MAX, tile(4, 4, 4, 64, true)),
            (false, 257, 320, u32::MAX, tile(5, 4, 4, 64, true)),
        ];
        let m26 = |w: WKind, m: u32, n: u32| match M26.iter().find(|(w8, first, last, max_n, _)| {
            *w8 == (w == WKind::I8) && m >= *first && m <= *last && n <= *max_n
        }) {
            Some(&(_, _, _, _, t)) if t != PF_KEEP => PfFamily::Tile(t),
            _ => pf_family(m, n),
        };
        let mut changed = std::collections::BTreeSet::new();
        for w in [WKind::I4, WKind::I8] {
            for &(n, _) in TP2.iter().chain(TP1) {
                if w == WKind::I8 && n != 5120 {
                    continue; // W8 (form c) is only ever the 5,120-column out / o / down
                }
                for m in 65..=8192 {
                    let (old, new) = (m26(w, m, n), pf_family_of(w, m, n));
                    if old != new {
                        assert!(
                            (65..=128).contains(&m) || (321..=384).contains(&m),
                            "{m} x {n} moved outside the p96 / p128 / p384 rows"
                        );
                        let rung = [96, 128, 384].into_iter().find(|&r| m <= r).unwrap();
                        changed.insert((
                            w == WKind::I8,
                            rung,
                            n,
                            cell(w, m, n, 5120).unwrap().symbol,
                        ));
                    }
                }
            }
        }
        let got: Vec<String> = changed
            .iter()
            .map(|(w8, r, n, s)| format!("{} p{r} N{n} {s}", if *w8 { "w8" } else { "w4" }))
            .collect();
        let want = [
            "w4 p96 N48 macaq_iu8f_pf_w4_t1w4n2k128p",
            "w4 p96 N96 macaq_iu8f_pf_w4_t1w4n2k128p",
            "w4 p96 N5120 macaq_iu8f_pf_w4_t3w2n2k128p",
            "w4 p96 N7168 macaq_iu8f_pf_w4_t3w2n2k128p",
            "w4 p96 N8192 macaq_iu8f_pf_w4_t3w2n2k128p",
            "w4 p96 N14336 macaq_iu8f_pf_w4_t3w2n2k128p",
            "w4 p96 N16384 macaq_iu8f_pf_w4_t3w2n2k128p",
            "w4 p96 N17408 macaq_iu8f_pf_w4_t3w2n2k128p",
            "w4 p96 N34816 macaq_iu8f_pf_w4_t3w2n2k128p",
            "w4 p128 N48 macaq_iu8f_pf_w4_t1w4n2k128p",
            "w4 p128 N96 macaq_iu8f_pf_w4_t1w4n2k128p",
            "w4 p128 N5120 macaq_iu8f_pf_w4_t1w4n2k128p",
            "w4 p128 N7168 macaq_iu8f_pf_w4_t2w4n4k128p",
            "w4 p128 N8192 macaq_iu8f_pf_w4_t2w4n4k128p",
            "w4 p384 N48 macaq_iu8f_pf_w4_t1w4n2k128p",
            "w4 p384 N96 macaq_iu8f_pf_w4_t1w4n2k128p",
            "w4 p384 N7168 macaq_iu8f_pf_w4_t3w8n4k128p",
            "w4 p384 N8192 macaq_iu8f_pf_w4_t3w8n4k128p",
            "w4 p384 N14336 macaq_iu8f_pf_w4_t3w8n4k128p",
            "w4 p384 N16384 macaq_iu8f_pf_w4_t3w8n4k128p",
            "w4 p384 N17408 macaq_iu8f_pf_w4_t3w8n4k128p",
            "w4 p384 N34816 macaq_iu8f_pf_w4_t3w8n4k128p",
            "w8 p96 N5120 macaq_iu8f_pf_w8_t1w4n2k128",
            "w8 p128 N5120 macaq_iu8f_pf_w8_t1w4n2k128",
        ];
        let mut want: Vec<String> = want.iter().map(|s| (*s).to_string()).collect();
        want.sort();
        let mut got = got;
        got.sort();
        assert_eq!(got, want);
    }

