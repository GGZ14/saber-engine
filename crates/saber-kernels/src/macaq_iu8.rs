//! MACaQ (2026-11-17): the W4A8-iu8 pack's kernels (pack-driven: only an iu8 pack routes here).
//!
//! Every 27B decoder linear of an iu8 pack is an int8-WMMA GEMM: per-row int4 weights (one f32 scale an
//! output row, `KernelOp::GemmI4A8`) or, at the pack's W8 ops, per-row int8 weights (`GemmI8A8`), against
//! per-token symmetric int8 activations (absmax / 127) in the A-TILED fragment order at EVERY M. The K
//! loop is pure integer; the scales meet in the epilogue: `y = bf16((f32(acc) * as[m]) * (ws[n] * U))`
//! (`U` = 1/16 for the W4 unpack's x16, 1 for W8). Two families in ONE code object (`hip/macaq_iu8.hip`):
//! the decode band (M <= 64: 8 waves a 128-column block, split-K over z with an exact int32
//! last-arriver reduce) and the prefill tile (M > 64: BM 256 x BN 128, LBK 64). **The split count is not numerics** (int32 adds are associative): any `ks`, any M band edge,
//! any tile order gives the same bytes for the same rows -- the band below is speed data only.
//!
//! The activation side is the had32 producers' per-token INT8 twins (`*_hadi8_*`, generated by
//! `tools/gen_macaq_iu8.py`): [`i8_twin`] maps a had32 producer descriptor to its twin (same
//! arguments, the A-tiled instantiation at every M). The MXFP4 row 3 (`arnq_had32`) has no int8 twin; an iu8
//! plan folds its decode GEMMs on the fused iu8 bodies instead ([`pair`], [`ar_nq`]: `hip/macaq_iu8f.hip`).

