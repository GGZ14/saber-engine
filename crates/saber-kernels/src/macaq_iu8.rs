/// The pair's block order by `tm` (speed data; both orders give the same bytes):
/// `true` = the ba half's blocks first (`macaq_iu8f_pairb_*`), `false` = problem 0 first (`macaq_iu8f_pair_*`).
/// Measured (TP=2, IC-cold): the same within +-0.25 us at M 1..40, -0.68 / -2.07 us at M 48 / 64; both 7..36 us
/// under the two launches.
pub const PAIR_BA_FIRST: [bool; 4] = [true, true, true, true];

/// `(kind, tm, ks)` of an unpaired iu8 decode descriptor, or a refusal naming it.
fn dec_cell(d: &LaunchDescriptor) -> Result<(WKind, u32, u32)> {
    let bad = || {
        Error::Rule(format!(
            "macaq iu8 fusion: `{}` is not an iu8 decode cell",
            d.kernel
        ))
    };
    if d.plugin != PLUGIN {
        return Err(bad());
    }
    let rest = d.kernel.strip_prefix("macaq_iu8_dec_").ok_or_else(bad)?;
    let (w, tm) = match rest.split_once("_tm") {
        Some(("w4", t)) => (WKind::I4, t),
        Some(("w8", t)) => (WKind::I8, t),
        _ => return Err(bad()),
    };
    let tm: u32 = tm.parse().map_err(|_| bad())?;
    if !(1..=4).contains(&tm) || d.grid[1] != 1 || d.grid[2] == 0 {
        return Err(bad());
    }
    Ok((w, tm, d.grid[2]))
}

fn int_arg(d: &LaunchDescriptor, name: &str) -> Result<i64> {
    match d.arg(name).map(|s| &s.value) {
        Some(ArgValue::I32 { ival } | ArgValue::I64 { ival }) => Ok(*ival),
        _ => Err(Error::Rule(format!(
            "macaq iu8 fusion: `{}` has no integer `{name}`",
            d.kernel
        ))),
    }
}

/// Pack `values` (one per signature argument, in order) into slots.
fn build(sig: &'static [abi::SigArg], values: Vec<ArgValue>) -> Result<(Vec<Slot>, u32)> {
    if sig.len() != values.len() {
        return Err(Error::Rule(format!(
            "macaq iu8 fusion: {} values for a {}-argument signature",
            values.len(),
            sig.len()
        )));
    }
    let (packed, bytes) = abi::pack(sig);
    Ok((
        sig.iter()
            .zip(packed)
            .zip(values)
            .map(|((a, (offset, size)), value)| Slot {
                name: a.name.to_owned(),
                offset,
                size,
                value,
            })
            .collect(),
        bytes,
    ))
}

fn buf(n: &str) -> ArgValue {
    ArgValue::Buffer { buffer: n.into() }
}
fn null(n: &str) -> ArgValue {
    ArgValue::NullBuffer { buffer: n.into() }
}
fn i32v(v: i64) -> ArgValue {
    ArgValue::I32 { ival: v }
}

/// The iu8 decode PAIR -- two W4 decode GEMMs that read ONE A edge (gdn in_proj_qkvz + in_proj_ba) in
/// one dispatch. Each half is exactly the descriptor [`resolve`] gave it alone (its split count, its partial
/// slab and counters), the two grids end to end (problem 0 first). Refused unless both halves are W4 decode
/// cells at the same `tm`, `M` and `K`. Bindings: the first half's `a`, `as`, `w`, `ws`, `c` and the second's
/// `w_b`, `ws_b`, `c_b`; workspaces `decode_partial` / `decode_counter` (+ `_b`) per half that splits.
///
/// # Errors
/// Anything but two W4 decode cells of one M and K.
pub fn pair(first: &LaunchDescriptor, second: &LaunchDescriptor) -> Result<LaunchDescriptor> {
    let (w0, tm0, ks0) = dec_cell(first)?;
    let (w1, tm1, ks1) = dec_cell(second)?;
    let (m0, k0, n0) = (
        int_arg(first, "m")?,
        int_arg(first, "k")?,
        int_arg(first, "n")?,
    );
    let (m1, k1, n1) = (
        int_arg(second, "m")?,
        int_arg(second, "k")?,
        int_arg(second, "n")?,
    );
    if w0 != WKind::I4 || w1 != WKind::I4 || tm0 != tm1 || m0 != m1 || k0 != k1 {
        return Err(Error::Rule(format!(
            "macaq iu8 pair: halves `{}` M {m0} K {k0} and `{}` M {m1} K {k1} are not two W4 cells of one M, K",
            first.kernel, second.kernel
        )));
    }
    let (nb0, nb1) = (first.grid[0], second.grid[0]);
    let form = if PAIR_BA_FIRST[(tm0 - 1) as usize] {
        "pairb"
    } else {
        "pair"
    };
    let kernel = format!("macaq_iu8f_{form}_w4_tm{tm0}");
    let sig = abi::signature_for(&kernel)
        .ok_or_else(|| Error::Rule(format!("{kernel}: no declared signature")))?;
    let ws = |ks: u32, n: &str| if ks > 1 { buf(n) } else { null(n) };
    let values = vec![
        buf("a"),
        buf("as"),
        buf("w"),
        buf("ws"),
        ws(ks0, "decode_partial"),
        ws(ks0, "decode_counter"),
        buf("c"),
        buf("w_b"),
        buf("ws_b"),
        ws(ks1, "decode_partial_b"),
        ws(ks1, "decode_counter_b"),
        buf("c_b"),
        i32v(m0),
        i32v(k0),
        i32v(n0),
        i32v(i64::from(ks0)),
        i32v(i64::from(nb0)),
        i32v(n1),
        i32v(i64::from(ks1)),
        i32v(i64::from(nb1)),
    ];
    let (args, bytes) = build(sig, values)?;
    let mut workspaces = Vec::new();
    for (d, sfx) in [(first, ""), (second, "_b")] {
        for w in &d.workspaces {
            let mut w = w.clone();
            w.name = format!("{}{sfx}", w.name);
            workspaces.push(w);
        }
    }
    Ok(LaunchDescriptor {
        op: OP_PAIR.into(),
        plugin: FUSED_PLUGIN.into(),
        kernel,
        grid: [nb0 * ks0 + nb1 * ks1, 1, 1],
        block: [256, 1, 1],
        shared_bytes: 0,
        kernarg_bytes: bytes,
        args,
        workspaces,
        n_launches: 1,
    })
}

/// Fusion-map ROW 3 for iu8 -- a row-parallel decode GEMM (W4 or W8, `tm1`) whose last-arriving split
/// block per n-block also runs the exact two-rank all-reduce and the int8 `_nq` epilogue (residual add, Gemma
/// RMS norm, had32, per-token int8, A-tiled store). Built from the GEMM's [`resolve`] descriptor and the
/// planner's `_nq` descriptor ([`NQ_I8`]); refused unless: the GEMM is a `tm1` decode cell whose N is whole
/// 128-column n-blocks, the epilogue is the int8 exact `_nq` over the GEMM's own `M x N` output with one 256-
/// thread block a row, and `M <= n-blocks` (the row owners are the last M arrivals) with `M * 16 <= 256` push
/// lanes. Kernarg image: the GEMM's ten, the reduce's regions and buffers, `ar_tiles`, the epilogue's scalars
/// from `nq` (`k16`, `slot_stride16`, `eps`, `drain`, `acq`), `ep_rows = M`, `had_t`. Workspaces: the GEMM's
/// (split-K partials + counters, none at ks 1), the reduce's five, [`AR_TILES`].
///
/// # Errors
/// Anything outside that shape.
pub fn ar_nq(gemm: &LaunchDescriptor, nq: &LaunchDescriptor) -> Result<LaunchDescriptor> {
    let refuse = |why: String| Error::Rule(format!("macaq iu8 row 3: {why}"));
    let (w, tm, ks) = dec_cell(gemm)?;
    let (m, n) = (int_arg(gemm, "m")?, int_arg(gemm, "n")?);
    let ntiles = i64::from(gemm.grid[0]);
    if tm != 1 || n % i64::from(BLOCK_N) != 0 || ntiles * i64::from(BLOCK_N) != n {
        return Err(refuse(format!(
            "`{}` N {n} is not a tm1 cell of whole {BLOCK_N}-column n-blocks",
            gemm.kernel
        )));
    }
    if nq.op != "allreduce_exact_nq" || nq.kernel != NQ_I8 {
        return Err(refuse(format!(
            "the epilogue is `{}` (`{}`), not the int8 exact `_nq` {NQ_I8}",
            nq.kernel, nq.op
        )));
    }
    let k16 = int_arg(nq, "k16")?;
    if k16 * 8 != n || i64::from(nq.grid[0]) != m || nq.block[0] != 256 {
        return Err(refuse(format!(
            "the epilogue is {} x {} at {} threads and the GEMM writes {m} x {n}",
            nq.grid[0],
            k16 * 8,
            nq.block[0]
        )));
    }
    if m <= 0 || ntiles < m || m * 16 > 256 {
        return Err(refuse(format!(
            "M {m} rows need M row owners among {ntiles} n-blocks and M * 16 <= 256 push lanes"
        )));
    }
    let eps = match nq.arg("eps").map(|x| &x.value) {
        Some(ArgValue::F32 { fval }) => *fval,
        _ => return Err(refuse("the epilogue has no `eps`".into())),
    };
    let kernel = format!("macaq_iu8f_arnq_hadi8_{}_tm1", w.tag());
    let sig = abi::signature_for(&kernel)
        .ok_or_else(|| Error::Rule(format!("{kernel}: no declared signature")))?;
    let ws = |n: &str| if ks > 1 { buf(n) } else { null(n) };
    let values = vec![
        buf("a"),
        buf("w"),
        buf("as"),
        buf("ws"),
        ws("decode_partial"),
        ws("decode_counter"),
        buf("c"),
        i32v(m),
        i32v(n),
        i32v(int_arg(gemm, "k")?),
        buf("ar_peer_scratch"),
        buf("ar_scratch"),
        buf("residual"),
        buf("norm_w"),
        buf("q_out"),
        buf("scale_out"),
        buf("res_out"),
        buf("ar_peer_flags"),
        buf("ar_flags"),
        buf("ar_seq"),
        buf(AR_TILES),
        i32v(k16),
        i32v(int_arg(nq, "slot_stride16")?),
        ArgValue::F32 { fval: eps },
        i32v(int_arg(nq, "drain")?),
        i32v(int_arg(nq, "acq")?),
        i32v(m),
        buf(crate::macaq::HAD_T),
    ];
    let (args, bytes) = build(sig, values)?;
    let mut workspaces = gemm.workspaces.clone();
    for w in &nq.workspaces {
        if !w.name.starts_with("ar_") {
            return Err(refuse(format!(
                "the epilogue declares `{}`, which row 3 does not carry",
                w.name
            )));
        }
        workspaces.push(w.clone());
    }
    workspaces.push(WorkspaceReq {
        name: AR_TILES.into(),
        kind: WorkspaceKind::Persistent,
        bytes: 8,
        zero_once: true,
    });
    Ok(LaunchDescriptor {
        op: OP_AR_NQ.into(),
        plugin: FUSED_PLUGIN.into(),
        kernel,
        grid: gemm.grid,
        block: gemm.block,
        shared_bytes: 0,
        kernarg_bytes: bytes,
        args,
        workspaces,
        n_launches: 1,
    })
}

