#!/usr/bin/env python3
"""FN141: derive the GDN decode updates with the step's x rows PRE-LOADED (the decode preload band
raised 1 -> 4 rows):

  crates/saber-kernels/hip/flashnext_conv141.hip  from saber_gdn_conv.hip   (CU_MAXT 1 -> 4)
      fn141_conv_update_w4_h128_hpb8               = saber_gdn_conv_update_w4_h128_hpb8 (b >= 2 pair)
  crates/saber-kernels/hip/flashnext_gdn141.hip   from flashnext_gdn_fc.hip (FU_MAXT 1 -> 4)
      fn141_gdn_fused_update_nq8_fc_f16s_w4k128v128_ab1 = fn86_gdn_fused_update_nq8_fc_... (b1)

At a verify step slen = w > 1 rows, so the parents' band of 1 never pre-loads: each row's x is a
memory round trip inside the token loop and the conv-state rewrite re-reads x element by element
(18 / 38 serial load rounds in the ISA census). With the band at 4 every row of the served widths
(<= 4) is issued before the first is waited on and the rewrite takes them from registers. Same
values, same arithmetic: byte-equal (card-1 oracle, fn141_gdn_probe.py). Each derived file is the
parent VERBATIM with that one constant changed, every other `extern "C"` symbol removed and the
kept one renamed. Built with the parents' flags (-ffp-contract=off) and image.

  tools/gen_fn141_gdn141.py [--check]
"""
import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HIP = os.path.join(ROOT, "crates/saber-kernels/hip")
JOBS = [
    ("saber_gdn_conv.hip", "flashnext_conv141.hip", "#ifndef CU_MAXT\n#define CU_MAXT 1\n",
     "#ifndef CU_MAXT\n#define CU_MAXT 4\n",
     "saber_gdn_conv_update_w4_h128_hpb8", "fn141_conv_update_w4_h128_hpb8"),
    ("flashnext_gdn_fc.hip", "flashnext_gdn141.hip", "#define FU_MAXT    1 ", "#define FU_MAXT    4 ",
     "fn86_gdn_fused_update_nq8_fc_f16s_w4k128v128_ab1", "fn141_gdn_fused_update_nq8_fc_f16s_w4k128v128_ab1"),
]


def blocks(s):
    """[(start, end, symbol)] of every extern "C" block"""
    out, i = [], 0
    while True:
        mm = re.compile(r'^extern "C"', re.M).search(s, i)   # a line start: never a comment's mention
        if not mm:
            return out
        j = mm.start()
        k = s.index("{", j)
        name = re.search(r"void\s+(\w+)\s*\(", s[j:k]).group(1)
        depth = 0
        while True:
            if s[k] == "{":
                depth += 1
            elif s[k] == "}":
                depth -= 1
                if depth == 0:
                    break
            k += 1
        out.append((j, k + 1, name))
        i = k + 1


def derive(src, old, new, keep, rename):
    s = open(os.path.join(HIP, src)).read()
    assert s.count(old) == 1, (src, old)
    s = s.replace(old, new)
    parts, i, kept = [], 0, 0
    for a, b, name in blocks(s):
        parts.append(s[i:a])
        if name == keep:
            parts.append(s[a:b].replace(keep + "(", rename + "(", 1))
            kept += 1
        i = b
    parts.append(s[i:])
    assert kept == 1, (src, keep)
    head = (f"// GENERATED by tools/gen_fn141_gdn141.py from {src} -- do not edit; re-run the script.\n"
            f"// FN141: the parent VERBATIM with `{old.strip().splitlines()[-1]}` -> `{new.strip().splitlines()[-1]}`,\n"
            f"// one symbol kept: {keep} as {rename}.\n")
    return head + "".join(parts)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--out-dir", default="", help="write here instead (the probe; include the hip dir)")
    a = ap.parse_args()
    rc = 0
    for src, dst, old, new, keep, rename in JOBS:
        txt = derive(src, old, new, keep, rename)
        path = os.path.join(a.out_dir or HIP, dst)
        if a.check:
            ok = os.path.exists(path) and open(path).read() == txt
            print(dst, "up to date" if ok else "STALE")
            rc |= 0 if ok else 1
        else:
            open(path, "w").write(txt)
    return rc


if __name__ == "__main__":
    sys.exit(main())
