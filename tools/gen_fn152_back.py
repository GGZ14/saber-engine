#!/usr/bin/env python3
"""FN152: derive `crates/saber-kernels/hip/moe_fn152.hip` -- FN151's NVFP4 form (b) `_p1` body (`fn151_x_impl`,
the default SC 1: live-row ladder + LDS scale table) inside the FUSED BACK HALVES, a NEW object (moe_fn151 and every
shipped object stay byte-identical):
  fn152_moe_back_gu{4_dn2,1_dn1}            = `moe_back_impl` (EP whole: gate_up N 1,280 bk128, down K 640 bk128)
  fn152_moe_back_h2_gu{4_dn2,1_dn1}         = `moe_back_h2_impl` (TP=2 half: gate_up N 640, down K 320 bk64)
  fn152_moe_back_h2_far_gu{..}{,_ctl,_chk}  = `moe_back_h2_far_impl` (FN137b's fused MoE-out reduce, FMODE 0/1/2)
  fn152_delay                               = fn137_delay renamed (the far oracle's skew source)
Every launch keeps its shipped ABI (SIG_MOE_BACK / SIG_MOE_BACK_FAR): the NVFP4 record's `gsplit` is the
shape's constant (gate_up = N / 2: 640 whole, 320 half; down = N = 2,560), xptr[3e + 2] = the record's f32
globals (`gs`) instead of `wref`. Byte law: each GEMM == FN148's `fn148_w4a8b_*` cell (FN151's twins), the silu /
GEMV / combine / exchange text is the shipped back half's, verbatim.
Text order: moe_grouped_far.hip's helpers (default contraction, as shipped) + its silu row (as shipped) + the
`#pragma clang fp contract(off)` line (as shipped) + FN151's impl (built contract-off in moe_fn151) + the shipped
contract-off region (GEMV body, combine, the three back impls, the FN137 exchange) with the GEMM calls renamed.
  python3 tools/gen_fn152_back.py          # write
  python3 tools/gen_fn152_back.py --check  # the committed file == the derivation
"""
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO, "tools"))
import gen_fn151_nvfp4p1 as G  # noqa: E402

SRC = G.SRC
OUT = os.path.join(REPO, "crates/saber-kernels/hip/moe_fn152.hip")
PAIRS = ((4, 2), (1, 1))
ARGS = """    const unsigned char *__restrict__ A, const float *__restrict__ As,
    const unsigned long long *__restrict__ xgu, const unsigned long long *__restrict__ xdn,
    const int *__restrict__ tile_expert, const int *__restrict__ tile_row0,
    const int *__restrict__ tile_rows, const int *__restrict__ row_tok,
    const int *__restrict__ meta, float *__restrict__ Pgu, float *__restrict__ Pdn,
    int *__restrict__ cgu, int *__restrict__ cdn, __bf16 *__restrict__ GU,
    unsigned char *__restrict__ Q, float *__restrict__ QS, __bf16 *__restrict__ Y,
    const float *__restrict__ topk_w, const int *__restrict__ route_pos,
    const __bf16 *__restrict__ wsg, const __bf16 *__restrict__ bi, __bf16 *__restrict__ sg,
    __bf16 *__restrict__ out, int *__restrict__ sync, int T, int Pmax, int tc"""
CALL = ("A, As, xgu, xdn, tile_expert, tile_row0, tile_rows, row_tok, meta, Pgu, Pdn, cgu, cdn, GU, Q, QS, Y,\n"
        "      topk_w, route_pos, wsg, bi, sg, out, sync, T, Pmax, tc")


def derive():
    src = open(SRC).read()
    f151 = G.derive()
    # FN151's text: prefix | mid + impl | wrappers. Keep mid + impl (the cell wrappers are moe_fn151's symbols).
    m0 = f151.index("\n// ---------------------------------------------------------------- FN151\n")
    m1 = f151.index("\n// ---------------------------------------------------------------- FN151: the grouped cells\n")
    body151 = f151[m0:m1].rstrip() + "\n"
    tmpl = ("template <int DWN, int DBK, int DKS, int DTM, bool WPERM, bool GATHER, bool DIRECT, bool NT,\n"
            "          int PFD, typename WaitF>\n__device__ __forceinline__ void moe_grouped_w4a8_x_impl(")
    lo = src.index(tmpl)
    hi = src.index("// The silu-quant of ONE expert-major row with a WAVE")
    mark = "// ---- below: contraction OFF (FN5's band, moe_route's exp / sigmoid and combine are built so)\n" \
           "#pragma clang fp contract(off)\n"
    mk = src.index(mark)
    wr = src.index('extern "C" __global__ __launch_bounds__(256) void fn137_moe_back_h2_far_gu4_dn2_p1(')
    prefix, silu, rest = src[:lo], src[hi:mk], src[mk + len(mark):wr]
    # the shipped far file's own prefix is the impl-free helper text FN151 kept (its header line replaced)
    assert G.derive().startswith(f151[:200])
    prefix = G.sub(prefix, "// GENERATED by tools/gen_fn137b_far.py -- do not edit by hand, re-run the generator.\n",
                   "// GENERATED by tools/gen_fn152_back.py from moe_grouped_far.hip + tools/gen_fn151_nvfp4p1.py -- do not\n"
                   "// edit by hand. FN152: FN151's NVFP4 form (b) `_p1` body in the fused back halves (see the generator).\n"
                   "// (was) GENERATED by tools/gen_fn137b_far.py -- do not edit by hand, re-run the generator.\n")
    n = rest.count("moe_grouped_w4a8_x_impl<DEC_DWN, ")
    assert n == 6, n
    rest = rest.replace("moe_grouped_w4a8_x_impl<DEC_DWN, ", "fn151_x_impl<SC152, DEC_DWN, ")
    # the FN151 SC class of the body is a template parameter of each back impl (1 = FN151's default)
    rest = G.sub(rest, "template <int KSG, int KSD, int PFD>\n", "template <int KSG, int KSD, int PFD, int SC152 = 1>\n", 2)
    rest = G.sub(rest, "template <int KSG, int KSD, int PFD, int FMODE>\n",
                 "template <int KSG, int KSD, int PFD, int FMODE, int SC152 = 1>\n")
    # gsplit after Pmax: gate_up (GU, N) -> N / 2, down (Y, N) -> N
    pat = re.compile(r"(GU|Y), (\d+), (\d+),(\s+)Pmax,(\s+)smem,")
    def rep(mo):
        nn = int(mo.group(2))
        g = nn // 2 if mo.group(1) == "GU" else nn
        return f"{mo.group(1)}, {nn}, {mo.group(3)},{mo.group(4)}Pmax, {g},{mo.group(5)}smem,"
    rest, k = pat.subn(rep, rest)
    assert k == 6, k
    rest = G.sub(rest, 'extern "C" __global__ void fn137_delay(', 'extern "C" __global__ void fn152_delay(')
    assert "Wref" not in rest and 'extern "C"' in rest
    w = ["\n// ---------------------------------------------------------------- FN152: the back-half wrappers\n"]
    # SC suffix: "" = FN151's default (SC 1), "_lr" = FN151's `_lr` (SC 7: global loads, LDS-scope slab
    # barriers, register scales; its lowest-VGPR form) -- the attribution arm
    for sc, ss in ((1, ""), (7, "_lr")):
        for gu, dn in PAIRS:
            for nm, impl in ((f"fn152_moe_back_gu{gu}_dn{dn}{ss}", "moe_back_impl"),
                             (f"fn152_moe_back_h2_gu{gu}_dn{dn}{ss}", "moe_back_h2_impl")):
                w.append(f'extern "C" __global__ __launch_bounds__(256) void {nm}(\n{ARGS}) {{\n'
                         f'  {impl}<{gu}, {dn}, 1, {sc}>({CALL});\n}}\n\n')
            for sfx, fm in (("", 0), ("_ctl", 1), ("_chk", 2)):
                w.append(f'extern "C" __global__ __launch_bounds__(256) void '
                         f'fn152_moe_back_h2_far_gu{gu}_dn{dn}{ss}{sfx}(\n'
                         f'{ARGS}, FarArgs fa) {{\n  moe_back_h2_far_impl<{gu}, {dn}, 1, {fm}, {sc}>({CALL}, fa);\n}}\n\n')
    return prefix + silu + mark + body151 + rest.rstrip() + "\n" + "".join(w)


def main():
    text = derive()
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and open(OUT).read() == text
        print(f"gen_fn152_back: {OUT} {'== the derivation' if ok else 'DIFFERS from the derivation'}")
        return 0 if ok else 1
    open(OUT, "w").write(text)
    print(f"wrote {OUT} ({len(text)} B)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
