#!/usr/bin/env python3
"""FN131: derive crates/saber-kernels/hip/flashnext_hc131.hip (code object `flashnext_hc131`) -- the
fp8-mixer HC DOWN at the decode forms RE-TILED BY PHASE -- from the shipped object's source
crates/saber-kernels/hip/flashnext_hc8.hip (FN108's derivation) + the split body
tools/capture/fn131/body131.hip.in (the probe's body, the same file: the probe and the shipped
object can never drift).

What the derivation does (and nothing else):
  * copies flashnext_hc8.hip's helpers and bodies VERBATIM up to its symbol section (no symbol of
    the parent is re-emitted -- the shipped symbols stay in `flashnext_hc8`, byte for byte);
  * appends `fn131_down_body` (tile waves + phase waves in one workgroup: the weight ring issued
    at entry, the norm a row a wave, the whole K slice's A slab formed from the registers, one
    LDS-only barrier, a branch-free ring, the last arrival's slice sum in one round);
  * emits `fn131_down_{mix,expand,combine,final}_v2_<cfg>_h8` for the two routed DECODE cfgs with
    the PARENT's kernarg layout (`fn_hc_down_<mode>_v2_<cfg>_h8`), the parent's grid
    (4 x sps, ceil(M / 16), G) and (NW + NP) x 32 threads (`saber_kernels::flashnext::down131`).
Every rounding point is the parent's (LEDGER FN131): byte-equal to the parent by the card-1 oracle
(`tools/capture/fn131/fn131_probe.py --sections ship`), the NaN law of `fn131_rne2` stated there.
Built with -ffp-contract=off and saber-dev:rocm714 (the parent's row).

  tools/gen_fn131_hc131.py [--check]
"""
import argparse
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "crates/saber-kernels/hip/flashnext_hc8.hip")
BODY = os.path.join(ROOT, "tools/capture/fn131/body131.hip.in")
OUT = os.path.join(ROOT, "crates/saber-kernels/hip/flashnext_hc131.hip")

HEADER = """\
// GENERATED by tools/gen_fn131_hc131.py from flashnext_hc8.hip + tools/capture/fn131/body131.hip.in
// -- do not edit; re-run the script.
//
// Flash-Next (FN131): the fp8-mixer HC DOWN at the decode forms re-tiled by phase. Each
// `fn131_down_<mode>_v2_<cfg>_h8` takes `fn_hc_down_<mode>_v2_<cfg>_h8`'s arguments and grid with
// (NW + NP) x 32 threads and writes the same bytes (hid, rr, partials, lora, logits, counters).
// Built with -ffp-contract=off (the parent's row), saber-dev:rocm714.
"""

# (cfg, NW, NP, KW, PF, DPP, DL) -- MUST match saber_kernels::flashnext::down131::ROUTE
# (m1w3t1d: band M <= 1, sps 4; m1w7t1: band M 2..64, sps 2). Fixed: TS 0, LN 1, SB 1, IP 0,
# FU 1, NN 1, waves-per-EU 8 (<= 192 VGPRs: the grid stays resident). Measured (LEDGER FN131).
SHIP = [("m1w3t1d", 3, 4, 640, 10, 1, 24), ("m1w7t1", 7, 8, 1280, 10, 0, 24)]
MODES = (("mix", 0, 4), ("expand", 1, 4), ("combine", 2, 4), ("final", 2, 0))

SYMS_HEAD = """
// ============================================================================ FN131: the symbols
// The parent's kernarg layout (FN8_DOWN2); TS 0 (no stamps), LN 1, SB 1, IP 0, FU 1, NN 1.
#define FN131_SHIP(NAME, MODE, NINJ, NW, NP, KW, PF, DPP, DL)                                    \\
  extern "C" __global__ __launch_bounds__((NW + NP) * 32, 8) void NAME(                         \\
      const __bf16 *__restrict__ src, const __bf16 *__restrict__ blk,                             \\
      const __bf16 *__restrict__ inj, __bf16 *__restrict__ hid, const __bf16 *__restrict__ nw,    \\
      const unsigned char *__restrict__ wdn, const __bf16 *__restrict__ wij,                      \\
      float *__restrict__ part, float *__restrict__ rr, int *__restrict__ cnt,                    \\
      __bf16 *__restrict__ lora, __bf16 *__restrict__ inj_out, int m, int sps, float eps) {       \\
    fn131_down_body<MODE, NINJ, NW, NP, KW, PF, DPP, 0, 1, 1, 0, 1, 1, DL>(                       \\
        src, blk, inj, hid, nw, wdn, wij, part, rr, cnt, lora, inj_out, m, sps, eps, nullptr);   \\
  }
"""


def derive():
    s = open(SRC).read()
    head_end = s.index("// ============================================================================ FN108: the symbols")
    prefix = s[:head_end]
    assert 'extern "C"' not in prefix, "the parent's helpers carry a symbol"
    lines = prefix.split("\n")
    k = 0
    while lines[k].startswith("//"):
        k += 1
    prefix = "\n".join(lines[k:])
    syms = [SYMS_HEAD.rstrip("\n")]
    for cfg, nw, np_, kw, pf, dpp, dl in SHIP:
        for mode, mi, ninj in MODES:
            syms.append(f"FN131_SHIP(fn131_down_{mode}_v2_{cfg}_h8, {mi}, {ninj}, {nw}, {np_}, {kw}, {pf}, {dpp}, {dl})")
    return HEADER + prefix.rstrip() + "\n" + open(BODY).read() + "\n".join(syms) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    out = derive()
    if a.check:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        if cur != out:
            print("flashnext_hc131.hip: STALE (re-run tools/gen_fn131_hc131.py)")
            sys.exit(1)
        print("flashnext_hc131.hip: current")
        return
    open(OUT, "w").write(out)
    print(f"wrote {OUT} ({len(out)} bytes)")


if __name__ == "__main__":
    main()
