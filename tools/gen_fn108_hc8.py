#!/usr/bin/env python3
"""FN108: derive crates/saber-kernels/hip/flashnext_hc8.hip (code object `flashnext_hc8`) from the
shipped crates/saber-kernels/hip/flashnext_hc.hip -- the HC mix bodies with the MIXING MATRICES
read at the reference's hc8m law (e4m3 codes + one f32 scale per group of a row along K: 128 for the
down [320, 10240], 80 for the up [10240, 320]; `ref/kernels/ref_hc_fp8.h`), WEIGHT-ONLY.

What the derivation does (and nothing else):
  * slices the shipped helpers (constants, hexp / sigmoid, DPP, fn_x8, the norm macro), FN11's
    down v2 body (+ FN85's helpers it references), FN11's up tail + `s` body and FN21's prefill
    up body + its sigmoid table VERBATIM, by anchor, every `extern "C"` symbol left out;
  * renames the bodies `fn_hc8_*` and replaces ONLY the weight operand's load: the record is the
    e4m3 codes `[N, K]` row-major followed by the f32 scales `[N, K / G]` (one pointer, the
    shipped argument lists unchanged), and every 8-element WMMA fragment of a mixing matrix is
    `bf16(f32(code) x scale)` -- dequantized in the register and fed to the SAME bf16 WMMA chain
    in the same order. So an `_h8` symbol on a record equals its parent symbol on the bf16 matrix
    bf16(code x scale) BYTE FOR BYTE (the card gate `tools/capture/fn108/hc8_gate.py`), and the
    host reference's `trunk_quant.hc8m_value` is that matrix;
  * the inject rows (`block_inject_weight`, the down's tile 20) stay bf16 (the reference's too);
  * emits `<parent symbol>_h8` for the routed cfgs only (rules/flashnext_gfx1201.toml [[hc.band]]:
    down m1w3t1d / m1w7t1 / m2w21t1 + m1w3t1 (the rr twins' and the route control's), up s1d /
    p2s + s1); p4s spills at MF 4 with the fp8 operand, so its rows run on p2s_h8 (same bytes).

The generated file is committed; re-run only when flashnext_hc.hip moves (`--check` diffs).
Usage: tools/gen_fn108_hc8.py [--check]
"""
import argparse
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "crates/saber-kernels/hip/flashnext_hc.hip")
OUT = os.path.join(ROOT, "crates/saber-kernels/hip/flashnext_hc8.hip")


def cut(s, start, end):
    i = s.index(start)
    j = s.index(end, i)
    return s[i:j]


def sub(s, old, new, count=1):
    n = s.count(old)
    assert n == count, (old[:80], n, count)
    return s.replace(old, new)


HEADER = """\
// GENERATED by tools/gen_fn108_hc8.py from flashnext_hc.hip -- do not edit; re-run the script.
//
// Flash-Next (FN108): the HC mix with the MIXING MATRICES at fp8 (the reference's hc8m law,
// ref/kernels/ref_hc_fp8.h): a record = e4m3 codes [N, K] row-major, then f32 scales [N, K / G]
// (G = 128 for the down [320, 10240], 80 for the up [10240, 320]); weight-only. Every fragment of
// a mixing matrix is bf16(f32(code) x scale) in the register, fed to the shipped bf16 WMMA chain in
// the shipped order: `<sym>_h8` on a record == `<sym>` on that bf16 matrix, byte for byte (gated).
// The inject rows (block_inject_weight) stay bf16. Built with -ffp-contract=off (the parent's row).
"""

FN8 = """
// ============================================================================ FN108: the fp8 operand
typedef float fn8x2 __attribute__((ext_vector_type(2)));
// 8 e4m3 codes (lo: bytes 0..3, hi: 4..7) x one f32 scale -> 8 bf16: bf16(f32(code) * sc), RNE.
__device__ __forceinline__ bf16x8 fn8_deq(unsigned lo, unsigned hi, float sc) {
  FnVec8 r;
  const fn8x2 a = __builtin_amdgcn_cvt_pk_f32_fp8((int)lo, false);
  const fn8x2 b = __builtin_amdgcn_cvt_pk_f32_fp8((int)lo, true);
  const fn8x2 c = __builtin_amdgcn_cvt_pk_f32_fp8((int)hi, false);
  const fn8x2 d = __builtin_amdgcn_cvt_pk_f32_fp8((int)hi, true);
  r.h[0] = (__bf16)(a.x * sc);
  r.h[1] = (__bf16)(a.y * sc);
  r.h[2] = (__bf16)(b.x * sc);
  r.h[3] = (__bf16)(b.y * sc);
  r.h[4] = (__bf16)(c.x * sc);
  r.h[5] = (__bf16)(c.y * sc);
  r.h[6] = (__bf16)(d.x * sc);
  r.h[7] = (__bf16)(d.y * sc);
  return r.v;
}
// A ring entry: a bf16 fragment as is (t8 false: the inject rows), or the codes + the scale's bits.
template <int G>
__device__ __forceinline__ uint4 fn8_wld(bool t8, const __bf16 *bp, const unsigned char *cp,
                                         const float *sp, int kq, int st) {
  if (t8) {
    const uint2 c = *(const uint2 *)(cp + st * 16);
    return make_uint4(c.x, c.y, __float_as_uint(sp[(kq + st * 16) / G]), 0u);
  }
  return *(const uint4 *)(bp + st * 16);
}
__device__ __forceinline__ bf16x8 fn8_cv(bool t8, const uint4 &w) {
  if (t8) return fn8_deq(w.x, w.y, __uint_as_float(w.z));
  FnVec8 r;
  r.u4 = w;
  return r.v;
}
"""


def derive(src):
    helpers = src[: src.index("// ==================================================================================== DOWN")]
    assert 'extern "C"' not in helpers
    helpers = helpers[helpers.index("#include <hip/hip_runtime.h>"):]
    rp = cut(src, "#define FN_RPW (FN_H / 8)", "// ---- DOWN v2: grid")
    down = cut(src, "// ---- DOWN v2: grid", "#define FN_DOWN2(NAME")
    tail_up = cut(src, "// ---- the up's quant tail (B7)", '// ---- UP v2 "wide"')
    sig = cut(src, "#define FN_SIG_LO 0x33c0u", "// GATE ONLY: all 65,536")
    upp = cut(src, '// ---- UP v2 "p" (prefill)', "#define FN_UP2P(")
    for part in (rp, down, tail_up, sig, upp):
        assert 'extern "C"' not in part

    # ---- the down
    down = sub(down, "void fn_hc_down2_body(", "void fn_hc8_down2_body(")
    down = sub(down, "const __bf16 *__restrict__ wdn,", "const unsigned char *__restrict__ wdn,")
    down = sub(down, """  const __bf16 *bp[T];
  bool tl[T];
#pragma unroll
  for (int t = 0; t < T; ++t) {
    const int j = z + G * (wave + NW * t);
    tl[t] = j < NTILE;
    const int n = min(min(j, NTILE - 1) * 16 + row, NCOL - 1);
    bp[t] = (NINJ > 0 && n >= FN_R ? wij + (long)(n - FN_R) * FN_W : wdn + (long)n * FN_W) +
            s * FN_H + k0 + kh;
  }
  bf16x8 wr[PF][T];
#pragma unroll
  for (int p = 0; p < PF; ++p)
#pragma unroll
    for (int t = 0; t < T; ++t) wr[p][t] = *(const bf16x8 *)(bp[t] + min(p, nsteps - 1) * 16);
""", """  // FN108: tiles 0..19 read the e4m3 record (codes + per-128 scales), tile 20 the bf16 inject
  // rows; a tile is wave-uniform (j from the wave index), so t8 is a scalar branch
  const __bf16 *bp[T];
  const unsigned char *cp[T];
  const float *sp[T];
  bool tl[T], t8[T];
  const int kq = s * FN_H + k0 + kh;
  const float *wsc = (const float *)(wdn + (long)FN_R * FN_W);
#pragma unroll
  for (int t = 0; t < T; ++t) {
    const int j = __builtin_amdgcn_readfirstlane(z + G * (wave + NW * t));
    tl[t] = j < NTILE;
    const int n = min(min(j, NTILE - 1) * 16 + row, NCOL - 1);
    t8[t] = !(NINJ > 0 && min(j, NTILE - 1) * 16 >= FN_R);
    bp[t] = wij + (long)max(n - FN_R, 0) * FN_W + kq;
    cp[t] = wdn + (long)min(n, FN_R - 1) * FN_W + kq;
    sp[t] = wsc + (long)min(n, FN_R - 1) * (FN_W / 128);
  }
  uint4 wr[PF][T];
#pragma unroll
  for (int p = 0; p < PF; ++p)
#pragma unroll
    for (int t = 0; t < T; ++t)
      wr[p][t] = fn8_wld<128>(t8[t], bp[t], cp[t], sp[t], kq, min(p, nsteps - 1));
""")
    down = sub(down, """          if (!tl[t]) continue;
#pragma unroll
          for (int mf = 0; mf < MF; ++mf) acc[mf][t] = vg_wmma(af[mf], wr[p][t], acc[mf][t]);
""", """          if (!tl[t]) continue;
          const bf16x8 wb = fn8_cv(t8[t], wr[p][t]);
#pragma unroll
          for (int mf = 0; mf < MF; ++mf) acc[mf][t] = vg_wmma(af[mf], wb, acc[mf][t]);
""")
    down = sub(down, "        for (int t = 0; t < T; ++t) wr[p][t] = *(const bf16x8 *)(bp[t] + nx * 16);\n",
               "        for (int t = 0; t < T; ++t) wr[p][t] = fn8_wld<128>(t8[t], bp[t], cp[t], sp[t], kq, nx);\n")

    # ---- the up "s" (decode)
    ups = tail_up[tail_up.index('// ---- UP v2 "split"'):]
    tail = tail_up[: tail_up.index('// ---- UP v2 "split"')]
    ups = sub(ups, "void fn_hc_up2s_body(", "void fn_hc8_up2s_body(")
    ups = sub(ups, "const __bf16 *__restrict__ lora, const __bf16 *__restrict__ wup,",
              "const __bf16 *__restrict__ lora, const unsigned char *__restrict__ wup,")
    ups = sub(ups, "  const __bf16 *bp = wup + (long)(s * FN_H + c0 + row) * FN_R + kh;\n",
              "  // FN108: the up's e4m3 record (codes [W, 320] + four f32 scales a row, 80 each)\n"
              "  const long wn = (long)(s * FN_H + c0 + row);\n"
              "  const unsigned char *cp = wup + wn * FN_R + kh;\n"
              "  const float *sp = (const float *)(wup + (long)FN_W * FN_R) + wn * 4;\n")
    ups = sub(ups, "      wf[u] = *(const bf16x8 *)(bp + (h + u) * 16);\n",
              "      {\n"
              "        const uint2 c = *(const uint2 *)(cp + (h + u) * 16);\n"
              "        wf[u] = fn8_deq(c.x, c.y, sp[((h + u) * 16 + kh) / 80]);\n"
              "      }\n")

    # ---- the up "p" (prefill)
    upp = sub(upp, "void fn_hc_up2p_body(", "void fn_hc8_up2p_body(")
    upp = sub(upp, "const __bf16 *__restrict__ lora, const __bf16 *__restrict__ wup,",
              "const __bf16 *__restrict__ lora, const unsigned char *__restrict__ wup,")
    upp = sub(upp, """  const __bf16 *bp[FN_S];
#pragma unroll
  for (int s = 0; s < FN_S; ++s) bp[s] = wup + (long)(s * FN_H + c0 + row) * FN_R + kh;
""", """  // FN108: the up's e4m3 record (codes [W, 320] + four f32 scales a row, 80 each); ONE base
  // pointer per operand, stream s at a constant offset (register pressure: MF 4 x 4 streams)
  const long wn0 = (long)(c0 + row);
  const unsigned char *cp0 = wup + wn0 * FN_R + kh;
  const float *sp0 = (const float *)(wup + (long)FN_W * FN_R) + wn0 * 4;
""")
    upp = sub(upp, "  bf16x8 a0[MF], w0[FN_S], a1[MF], w1[FN_S];\n",
              "  bf16x8 a0[MF], a1[MF];\n  uint4 w0[FN_S], w1[FN_S];\n")
    upp = sub(upp, "  auto fl = [&](int ks, bf16x8 *av, bf16x8 *wv) {",
              "  auto fl = [&](int ks, bf16x8 *av, uint4 *wv) {")
    upp = sub(upp, "    for (int s = 0; s < FN_S; ++s) wv[s] = *(const bf16x8 *)(bp[s] + ks * 16);\n",
              "    for (int s = 0; s < FN_S; ++s) {\n"
              "      const uint2 c = *(const uint2 *)(cp0 + (long)s * FN_H * FN_R + ks * 16);\n"
              "      wv[s] = make_uint4(c.x, c.y,\n"
              "                         __float_as_uint(sp0[s * FN_H * 4 + (ks * 16 + kh) / 80]), 0u);\n"
              "    }\n")
    upp = sub(upp, """  auto fm = [&](const bf16x8 *av, const bf16x8 *wv) {
#pragma unroll
    for (int s = 0; s < FN_S; ++s)
#pragma unroll
      for (int mf = 0; mf < MF; ++mf)
        acc[mf][s] = SWAP ? vg_wmma(wv[s], av[mf], acc[mf][s]) : vg_wmma(av[mf], wv[s], acc[mf][s]);
  };""", """  auto fm = [&](const bf16x8 *av, const uint4 *wq) {
#pragma unroll
    for (int s = 0; s < FN_S; ++s) {
      const bf16x8 wvs = fn8_deq(wq[s].x, wq[s].y, __uint_as_float(wq[s].z));
#pragma unroll
      for (int mf = 0; mf < MF; ++mf)
        acc[mf][s] = SWAP ? vg_wmma(wvs, av[mf], acc[mf][s]) : vg_wmma(av[mf], wvs, acc[mf][s]);
    }
  };""")

    syms = """
// ============================================================================ FN108: the symbols
#define FN8_DOWN2(NAME, MODE, MF, NINJ, NW, T, KC, PF, DPP)                                       \\
  extern "C" __global__ __launch_bounds__(NW * 32) void NAME(                                    \\
      const __bf16 *__restrict__ src, const __bf16 *__restrict__ blk,                             \\
      const __bf16 *__restrict__ inj, __bf16 *__restrict__ hid, const __bf16 *__restrict__ nw,    \\
      const unsigned char *__restrict__ wdn, const __bf16 *__restrict__ wij,                      \\
      float *__restrict__ part, float *__restrict__ rr, int *__restrict__ cnt,                    \\
      __bf16 *__restrict__ lora, __bf16 *__restrict__ inj_out, int m, int sps, float eps) {       \\
    fn_hc8_down2_body<MODE, MF, NINJ, NW, T, KC, PF, DPP>(src, blk, inj, hid, nw, wdn, wij, part, \\
                                                          rr, cnt, lora, inj_out, m, sps, eps);   \\
  }
#define FN8_DOWN2_CFG(CFG, MF, NW, T, KC, PF)                                                     \\
  FN8_DOWN2(fn_hc_down_mix_v2_##CFG##_h8, 0, MF, 4, NW, T, KC, PF, 0)                               \\
  FN8_DOWN2(fn_hc_down_expand_v2_##CFG##_h8, 1, MF, 4, NW, T, KC, PF, 0)                            \\
  FN8_DOWN2(fn_hc_down_combine_v2_##CFG##_h8, 2, MF, 4, NW, T, KC, PF, 0)                           \\
  FN8_DOWN2(fn_hc_down_final_v2_##CFG##_h8, 2, MF, 0, NW, T, KC, PF, 0)                             \\
  FN8_DOWN2(fn_hc_down_combinerr_v2_##CFG##_h8, 3, MF, 4, NW, T, KC, PF, 0)                         \\
  FN8_DOWN2(fn_hc_down_finalrr_v2_##CFG##_h8, 3, MF, 0, NW, T, KC, PF, 0)
#define FN8_DOWN2D_CFG(CFG, MF, NW, T, KC, PF)                                                    \\
  FN8_DOWN2(fn_hc_down_mix_v2_##CFG##_h8, 0, MF, 4, NW, T, KC, PF, 1)                               \\
  FN8_DOWN2(fn_hc_down_expand_v2_##CFG##_h8, 1, MF, 4, NW, T, KC, PF, 1)                            \\
  FN8_DOWN2(fn_hc_down_combine_v2_##CFG##_h8, 2, MF, 4, NW, T, KC, PF, 1)                           \\
  FN8_DOWN2(fn_hc_down_final_v2_##CFG##_h8, 2, MF, 0, NW, T, KC, PF, 1)
// the parents' cfg rows (flashnext_hc.hip FN_DOWN2_CFG / FN_DOWN2D_CFG)
FN8_DOWN2_CFG(m1w7t1, 1, 7, 1, 640, 8)
FN8_DOWN2_CFG(m1w3t1, 1, 3, 1, 320, 10)
FN8_DOWN2_CFG(m2w21t1, 2, 21, 1, 320, 10)
FN8_DOWN2D_CFG(m1w3t1d, 1, 3, 1, 320, 10)

#define FN8_UP2(NAME, BODY, NTH, ...)                                                             \\
  extern "C" __global__ __launch_bounds__(NTH) void NAME(                                         \\
      const __bf16 *__restrict__ hid, const float *__restrict__ rr,                               \\
      const __bf16 *__restrict__ nw, const __bf16 *__restrict__ lora,                             \\
      const unsigned char *__restrict__ wup, __bf16 *__restrict__ bi,                             \\
      unsigned char *__restrict__ q8, float *__restrict__ scale, float *__restrict__ amax,        \\
      int *__restrict__ cnt, __bf16 *__restrict__ gdbg, int m) {                                  \\
    BODY<__VA_ARGS__>(hid, rr, nw, lora, wup, bi, q8, scale, amax, cnt, gdbg, m);                 \\
  }
#define FN8_UP2S(CFG, MF, DPP)                                                                    \\
  FN8_UP2(fn_hc_up_bf16_v2_##CFG##_h8, fn_hc8_up2s_body, 128, MF, 0, 0, DPP)                        \\
  FN8_UP2(fn_hc_up_q8_v2_##CFG##_h8, fn_hc8_up2s_body, 128, MF, 1, 0, DPP)                          \\
  FN8_UP2(fn_hc_up_q8t_v2_##CFG##_h8, fn_hc8_up2s_body, 128, MF, 2, 0, DPP)                         \\
  FN8_UP2(fn_hc_up_q8_dbg_v2_##CFG##_h8, fn_hc8_up2s_body, 128, MF, 1, 1, DPP)
#define FN8_UP2P(CFG, MF, NW, SWAP, TAB)                                                          \\
  FN8_UP2(fn_hc_up_bf16_v2_##CFG##_h8, fn_hc8_up2p_body, NW * 32, MF, NW, 0, 0, SWAP, TAB)          \\
  FN8_UP2(fn_hc_up_q8_v2_##CFG##_h8, fn_hc8_up2p_body, NW * 32, MF, NW, 1, 0, SWAP, TAB)            \\
  FN8_UP2(fn_hc_up_q8t_v2_##CFG##_h8, fn_hc8_up2p_body, NW * 32, MF, NW, 2, 0, SWAP, TAB)           \\
  FN8_UP2(fn_hc_up_q8_dbg_v2_##CFG##_h8, fn_hc8_up2p_body, NW * 32, MF, NW, 1, 1, SWAP, TAB)
FN8_UP2S(s1, 1, 0)
FN8_UP2S(s1d, 1, 1)
// p4s is NOT derived: at MF 4 the fp8 operand's registers spill (isa_census: 62 VGPRs); the
// executor runs p4s's rows on p2s_h8 (FN21: p2s and p4s are both byte-identical to FN5's up).
FN8_UP2P(p2s, 2, 8, true, true)
"""
    return "".join([HEADER, helpers, FN8, "\n// ---- (FN85's helpers, referenced by the down body)\n",
                    rp, down, tail, ups, "\n", sig, upp, syms])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    out = derive(open(SRC).read())
    if a.check:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        if cur != out:
            print(f"{OUT}: STALE (re-run tools/gen_fn108_hc8.py)")
            return 1
        print("flashnext_hc8.hip: current")
        return 0
    open(OUT, "w").write(out)
    print(f"wrote {OUT} ({len(out.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
