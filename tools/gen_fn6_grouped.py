#!/usr/bin/env python3
"""Derive `flashnext_moe.hip` (Flash-Next's grouped MTP-expert GEMMs, workstream FN6) from the
certified dense bodies they are built on.

The MTP layer's 512 routed experts are bf16 in the Quark checkpoint (the DEFAULT) and fp8
block-128 in Qwen's first-party `model-fp8-mtp-ple.safetensors` (a GATED option). Both grouped
GEMMs take FN4's grouped design unchanged -- the router/sort kernel (`moe_route`) writes the routes
expert-major in 16-row blocks, a tile of `tm` blocks owns ONE expert, a per-expert pointer table
(`xptr`, two entries per expert here: weight, block scales) names the bytes, and `row_tok` maps a
gate_up row to its token -- on the dense body whose arithmetic they must equal:

  * `fn_moe_bgemm_sk_m16_g{0,1}` <- `fn_bgemm_sk_body<16>` (flashnext_hc.hip, FN5's split-K band:
    one wave per 16 columns walks K in ascending 16-k steps, K cut into `splits` slices summed by
    the last arrival). Edits: the signature, the tile lookup (m0 = 0, M = the tile's live rows, W
    from the pointer table), the A row through the map, the output / slab / counter rows at the
    tile's `row0`. The WMMA chain, the slice partition, the slice sum's order and the one bf16
    rounding are the dense body's, character for character.
  * `fn_moe_a8w8_bs128_g{0,1}` <- `dflash_gemm_a8w8_blockscale_impl` (dflash_gemm.hip, the
    drafter's W8A8 128x128 block-scale GEMM, preshuffled B, `acc += tile * (a_scale * b_scale)`
    per 128-k tile). Edits: the signature, the tile lookup replacing the M-tile, W / Ws from the
    pointer table, the A row and the A scale row through the map, the store at `row0`.

So the byte oracle (grouped == the dense kernel called on that expert's own rows) holds by
construction and is gated anyway (tools/capture/fn6/fn6_gate.py `moe`): rows are independent in a
16x16x16 WMMA, and the k order is untouched.

Built with the DEFAULT flags (saber-kbuild): the a8w8 body contracts `acc += tile * (as * bs)` as
`dflash_gemm` does (built without -ffp-contract=off), and the bf16 band has no fp32 multiply-add
outside the WMMA for a contraction to touch (its slice sum is adds only).

  tools/gen_fn6_grouped.py [--check]
"""
import argparse
import os
import sys

HIP = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                    "..", "crates", "saber-kernels", "hip"))
HC = os.path.join(HIP, "flashnext_hc.hip")
DG = os.path.join(HIP, "dflash_gemm.hip")
OUT = os.path.join(HIP, "flashnext_moe.hip")

HEADER = '''// GENERATED by tools/gen_fn6_grouped.py -- do not edit by hand, re-run the deriver.
//
// Flash-Next's grouped MTP-expert GEMMs (workstream FN6): the MTP layer's 512 routed experts
// (gate_up N 1,280 K 2,560 merged gate-first, down N 2,560 K 640).
//   fn_moe_bgemm_sk_m16_g{1,0}   bf16 experts (Quark, the DEFAULT) on FN5's split-K band
//   fn_moe_a8w8_bs128_g{1,0}     fp8 block-128 experts (Qwen's first-party bytes, a GATED option)
//                                on the drafter's W8A8 block-scale body
// DERIVED MECHANICALLY from the dense bodies (`fn_bgemm_sk_body`, `dflash_gemm_a8w8_blockscale_impl`):
// every line that decides a byte is the dense kernel's, so a grouped row IS the dense kernel's row
// on that expert (the byte oracle, tools/capture/fn6/).
//
// The tile law is FN4's (docs/EXEC.md section 11): tile t = (tile_expert[t], tile_row0[t],
// tile_rows[t] live rows, <= 16), `meta[0]` = the live tile count (static grids, the tail exits),
// `row_tok[row]` = a gate_up row's token (g1 = GATHER) or the row itself (g0, down: the compact
// expert-major silu rows). `xptr[2e]` = expert e's weight, `xptr[2e + 1]` = its fp32 block scales
// (a8w8 only; [N/128][K/128]); the tier owns the table (a VRAM slot, a pinned-RAM UVA address).
#include <hip/hip_runtime.h>
#include <hip/hip_bf16.h>
#include <stdint.h>

typedef __bf16 bf16x8 __attribute__((ext_vector_type(8)));
typedef float floatx8 __attribute__((ext_vector_type(8)));
__device__ __forceinline__ floatx8 vg_wmma(bf16x8 a, bf16x8 b, floatx8 c) {
  return __builtin_amdgcn_wmma_f32_16x16x16_bf16_w32_gfx12(a, b, c);
}
#define FB_NW 4
#define FB_UNR 8

typedef unsigned int uint2_t __attribute__((ext_vector_type(2)));
typedef unsigned int uint4_t __attribute__((ext_vector_type(4)));
#define DG_BM   16
#define DG_BN  128
#define DG_BK  128
#define DG_NW    4
#define DG_NT  (DG_NW * 32)
__device__ __forceinline__ floatx8 dg_wmma(uint2_t a, uint2_t b, floatx8 c) {
  return __builtin_amdgcn_wmma_f32_16x16x16_fp8_fp8_w32_gfx12(a, b, c);
}
__device__ __forceinline__ int dg_acc_row(int lane, int e) { return (lane >> 4) * 8 + e; }
__device__ __forceinline__ void dg_store_acc(const floatx8 &acc, __bf16 *__restrict__ c,
                                             int n0, int m0, int M, int N, long ldc, int lane) {
  const int col = n0 + (lane & 15);
  if (col >= N) return;
#pragma unroll
  for (int e = 0; e < 8; ++e) {
    const int row = m0 + dg_acc_row(lane, e);
    if (row < M) c[(long)row * ldc + col] = (__bf16)acc[e];
  }
}

'''

SK_TILE = '''  // ---- the tile (FN6, FN4's law): which expert, which rows ------------------------------------
  // (the dense body's own `tile` below is its arrival-counter index, blockIdx.y * gridDim.x +
  // blockIdx.x -- with blockIdx.y = the route tile it is already one counter per (tile, n-block))
  const int gt = (int)blockIdx.y;
  if (gt >= meta[0]) return;
  const int texp = tile_expert[gt], row0 = tile_row0[gt], m = tile_rows[gt];
  const __bf16 *__restrict__ w = (const __bf16 *)(uintptr_t)xptr[2 * (size_t)texp];
'''

DG_TILE = '''  // ---- the tile (FN6, FN4's law): which expert, which rows ------------------------------------
  const int tile = (int)blockIdx.y;
  if (tile >= meta[0]) return;
  const int texp = tile_expert[tile], row0 = tile_row0[tile], M = tile_rows[tile];
  const unsigned char *__restrict__ W = (const unsigned char *)(uintptr_t)xptr[2 * (size_t)texp];
  const float *__restrict__ Ws = (const float *)(uintptr_t)xptr[2 * (size_t)texp + 1];
  const int m0 = 0;
'''


def cut(text, start, end, path):
    a = text.index(start)
    b = text.index(end, a)
    if text.count(start) != 1:
        sys.exit(f"gen_fn6_grouped: start anchor not unique in {path}")
    return text[a:b]


def subber(body, where):
    box = [body]

    def sub(old, new, what):
        n = box[0].count(old)
        if n != 1:
            sys.exit(f"gen_fn6_grouped: anchor `{what}` found {n}x in {where} (want 1): the dense "
                     f"body changed shape -- re-derive by hand, do not guess")
        box[0] = box[0].replace(old, new)
    return box, sub


def derive_sk():
    src = open(HC).read()
    body = cut(src, "template <int MROWS>\n__device__ __forceinline__ void fn_bgemm_sk_body(",
               "\n#define FN_BGEMM_SK(", HC)
    box, sub = subber(body, HC)
    sub("template <int MROWS>\n__device__ __forceinline__ void fn_bgemm_sk_body("
        "const __bf16 *__restrict__ a,\n"
        "                                                 const __bf16 *__restrict__ w,\n"
        "                                                 float *__restrict__ part, "
        "int *__restrict__ cnt,\n"
        "                                                 __bf16 *__restrict__ c, int m, int n, "
        "int k) {\n",
        "template <int MROWS, bool GATHER>\n__device__ __forceinline__ void fn_moe_bgemm_sk_body(\n"
        "    const __bf16 *__restrict__ a, const unsigned long long *__restrict__ xptr,\n"
        "    const int *__restrict__ tile_expert, const int *__restrict__ tile_row0,\n"
        "    const int *__restrict__ tile_rows, const int *__restrict__ row_tok,\n"
        "    const int *__restrict__ meta, float *__restrict__ part, int *__restrict__ cnt,\n"
        "    __bf16 *__restrict__ c, int n, int k, int rows_cap) {\n" + SK_TILE,
        "signature")
    sub("  const int m0 = (int)blockIdx.y * MROWS;\n", "  const int m0 = 0;\n", "m0")
    sub("ap[mf] = a + (long)min(m0 + mf * 16 + row, m - 1) * k + kb + kh;",
        "ap[mf] = a + (long)(GATHER ? row_tok[row0 + min(m0 + mf * 16 + row, m - 1)]\n"
        "                                         : row0 + min(m0 + mf * 16 + row, m - 1)) * k"
        " + kb + kh;", "A row")
    sub("if (r < m) c[(long)r * n + col] = (__bf16)acc[mf][e];",
        "if (r < m) c[(long)(row0 + r) * n + col] = (__bf16)acc[mf][e];", "direct store")
    sub("if (r < m) part[((long)sp * m + r) * n + col] = acc[mf][e];",
        "if (r < m) part[((long)sp * rows_cap + row0 + r) * n + col] = acc[mf][e];",
        "partial store")
    sub("float v = part[(long)r * n + cc];\n"
        "    for (int p = 1; p < nsp; ++p) v = v + part[((long)p * m + r) * n + cc];\n"
        "    c[(long)r * n + cc] = (__bf16)v;",
        "float v = part[(long)(row0 + r) * n + cc];\n"
        "    for (int p = 1; p < nsp; ++p) v = v + part[((long)p * rows_cap + row0 + r) * n + cc];\n"
        "    c[(long)(row0 + r) * n + cc] = (__bf16)v;", "slice sum")
    out = box[0]
    for dead in ("* m + r", "(long)r * n"):
        if dead in out:
            sys.exit(f"gen_fn6_grouped: `{dead}` survived the sk derivation")
    wr = []
    for g in (1, 0):
        wr.append(f'''extern "C" __global__ __launch_bounds__(FB_NW * 32) void fn_moe_bgemm_sk_m16_g{g}(
    const __bf16 *__restrict__ a, const unsigned long long *__restrict__ xptr,
    const int *__restrict__ tile_expert, const int *__restrict__ tile_row0,
    const int *__restrict__ tile_rows, const int *__restrict__ row_tok, const int *__restrict__ meta,
    float *__restrict__ part, int *__restrict__ cnt, __bf16 *__restrict__ c, int n, int k,
    int rows_cap) {{
  fn_moe_bgemm_sk_body<16, {"true" if g else "false"}>(a, xptr, tile_expert, tile_row0, tile_rows,
                                          row_tok, meta, part, cnt, c, n, k, rows_cap);
}}
''')
    return out + "\n" + "\n".join(wr)


def derive_dg():
    src = open(DG).read()
    body = cut(src, "template <int BM, int BN, int BK, int NW, bool MT>\n"
                    "__device__ __forceinline__ void dflash_gemm_a8w8_blockscale_impl(",
               '\nextern "C" __global__', DG)
    box, sub = subber(body, DG)
    sub("template <int BM, int BN, int BK, int NW, bool MT>\n"
        "__device__ __forceinline__ void dflash_gemm_a8w8_blockscale_impl(\n"
        "    const unsigned char *__restrict__ A,   // [M, K] e4m3, row-major\n"
        "    const unsigned char *__restrict__ W,   // [N/16, K*16] e4m3, preshuffled\n"
        "    const float *__restrict__ As,          // [M, K/128] fp32 block scales\n"
        "    const float *__restrict__ Ws,          // [N/128, K/128] fp32 block scales\n"
        "    __bf16 *__restrict__ C,                // [M, N] bf16\n"
        "    int M, int N, int K) {\n",
        "template <int BM, int BN, int BK, int NW, bool GATHER>\n"
        "__device__ __forceinline__ void fn_moe_a8w8_impl(\n"
        "    const unsigned char *__restrict__ A,   // [rows, K] e4m3 (token rows or compact rows)\n"
        "    const unsigned long long *__restrict__ xptr,\n"
        "    const int *__restrict__ tile_expert, const int *__restrict__ tile_row0,\n"
        "    const int *__restrict__ tile_rows, const int *__restrict__ row_tok,\n"
        "    const int *__restrict__ meta,\n"
        "    const float *__restrict__ As,          // [rows, K/128] fp32 block scales\n"
        "    __bf16 *__restrict__ C,                // [rows_cap, N] bf16, a tile at row0\n"
        "    int N, int K) {\n",
        "signature")
    sub("  const int m0 = MT ? (int)blockIdx.y * BM : 0;\n"
        "  if (MT && m0 >= M) return;\n", DG_TILE, "m tile")
    sub("abuf[i] = *(const uint4_t *)(A + (long)rc * K + kt * BK + c);",
        "abuf[i] = *(const uint4_t *)(A + (long)(GATHER ? row_tok[row0 + rc] : row0 + rc) * K"
        " + kt * BK + c);", "A row")
    sub("const float as = row < M ? As[(long)row * (K / 128) + kt] : 0.f;",
        "const float as = row < M ? As[(long)(GATHER ? row_tok[row0 + row] : row0 + row)"
        " * (K / 128) + kt] : 0.f;", "A scale row")
    sub("dg_store_acc(acc[i], C, n0 + (wave + i * NW) * 16, m0, M, N, N, lane);",
        "dg_store_acc(acc[i], C + (long)row0 * N, n0 + (wave + i * NW) * 16, m0, M, N, N, lane);",
        "store")
    out = box[0]
    if "MT" in out.replace("MYF", "").replace("MT ?", "??"):
        # `MT` must be gone (the comment about it may stay only as prose)
        for line in out.splitlines():
            if "MT" in line.replace("MYF", "") and not line.strip().startswith("//"):
                sys.exit(f"gen_fn6_grouped: `MT` survived the a8w8 derivation: {line!r}")
    wr = []
    for g in (1, 0):
        wr.append(f'''extern "C" __global__ __launch_bounds__(DG_NT) void fn_moe_a8w8_bs128_g{g}(
    const unsigned char *__restrict__ a, const unsigned long long *__restrict__ xptr,
    const int *__restrict__ tile_expert, const int *__restrict__ tile_row0,
    const int *__restrict__ tile_rows, const int *__restrict__ row_tok, const int *__restrict__ meta,
    const float *__restrict__ as, __bf16 *__restrict__ c, int n, int k) {{
  fn_moe_a8w8_impl<DG_BM, DG_BN, DG_BK, DG_NW, {"true" if g else "false"}>(
      a, xptr, tile_expert, tile_row0, tile_rows, row_tok, meta, as, c, n, k);
}}
''')
    return out + "\n" + "\n".join(wr)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = (HEADER + "// ============================== bf16 grouped, from fn_bgemm_sk_body\n"
            + derive_sk() + "\n// ============================== W8A8 grouped, from "
            "dflash_gemm_a8w8_blockscale_impl (GATED option)\n" + derive_dg())
    if a.check:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        if cur != text:
            print(f"DIFFERS: {OUT}")
            sys.exit(1)
        print("flashnext_moe.hip matches its derivation")
        return
    open(OUT, "w").write(text)
    print(f"wrote {OUT} ({len(text)} bytes)")


if __name__ == "__main__":
    main()
