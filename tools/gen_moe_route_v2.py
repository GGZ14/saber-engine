#!/usr/bin/env python3
"""FN26: append `moe_route_topk10_sort_e512_v2` to `moe_route.hip`, DERIVED from FN4's route kernel.

FN4's kernel maps phase 1's tokens wave-major (wave w routes tokens 4w .. 4w + 3 of its workgroup), so
a decode step of T <= 4 tokens runs every token on wave 0, one after another (T 4 costs 34 us vs 17.6
at T 1: FN26 hold 1). v2 is the kernel's text with ONE edit: token tl on wave tl % 8 (interleaved).
Each token's softmax / top-10 / renormalisation is the same wave-local arithmetic on the same lanes
whichever wave runs it, and phases 2-3 read the per-token results by token index -- the same bytes
(gated on the card: every route table equal, tools/capture/fn26/). The original kernel's text is not
touched (templating it moved its ISA -- measured), so this is a derived copy with a checked anchor.

  tools/gen_moe_route_v2.py [--check]
"""
import os
import sys

HIP = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                    "..", "crates", "saber-kernels", "hip", "moe_route.hip"))
BEGIN = "// ---- FN26 v2 (GENERATED by tools/gen_moe_route_v2.py -- do not edit) ----\n"
END = "// ---- end FN26 v2 ----\n"
HEAD = 'extern "C" __global__ __launch_bounds__(MOE_THREADS) void moe_route_topk10_sort_e512(\n'
MAP = "    const int tl = wave * (MOE_TPB / (MOE_THREADS / 32)) + i, t = t0 + tl;\n"
MAP2 = ("    const int tl = i * (MOE_THREADS / 32) + wave, t = t0 + tl;   "
        "// FN26: interleaved\n")


def derive(src):
    base = src.split(BEGIN)[0]
    a = base.index(HEAD)
    b = base.index("// The weighted combine.")
    k = base[a:b]
    if k.count(MAP) != 1:
        sys.exit("gen_moe_route_v2: the phase-1 map anchor moved -- re-derive by hand")
    k = k.replace(HEAD, HEAD.replace("e512(", "e512_v2("), 1).replace(MAP, MAP2)
    # Anything after this block (FN31's front half, tools/gen_moe_front.py) is kept as it is.
    rest = src.split(END, 1)[1] if END in src else ""
    return base.rstrip("\n") + "\n\n" + BEGIN + k.rstrip("\n") + "\n" + END + rest


def main():
    src = open(HIP).read()
    want = derive(src)
    if "--check" in sys.argv:
        if src != want:
            sys.exit("gen_moe_route_v2: moe_route.hip is not what the deriver produces")
        print("gen_moe_route_v2: moe_route.hip matches the deriver")
        return
    open(HIP, "w").write(want)
    print("gen_moe_route_v2: wrote", HIP)


if __name__ == "__main__":
    main()
