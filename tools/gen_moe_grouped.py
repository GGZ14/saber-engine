def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    for path, want in ((OUT, derive()), (TP2_OUT, derive_tp2()), (SS_OUT, derive_ss())):
        if a.check:
            have = open(path).read() if os.path.exists(path) else ""
            if have != want:
                sys.exit(f"gen_moe_grouped: {path} is not what the deriver produces; re-run it")
            print(f"gen_moe_grouped: {os.path.basename(path)} matches the deriver")
            continue
        open(path, "w").write(want)
        print(f"gen_moe_grouped: wrote {path} ({len(want.splitlines())} lines)")


