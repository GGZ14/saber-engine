# The back half's work ORDER is data: a ticket -> (gate_up | down, tile, n-block, split) map built
# on the card from the route's tile table + the RAM predicate (an expert whose gate_up `w` lies in
# the tier's pinned-RAM range [ram_lo, ram_hi) -- a hint only: a wrong range moves no byte, only the
# order). Every workgroup still computes exactly the shipped (tile, n-block, split) work with the
# shipped body; the split-K reduce sums its partials in split order, the silu runs once a tile, the
# combine sums the routes in TOP-K order -- none depends on which workgroup ran when, so every arm
# is the shipped symbol's bytes by construction (gated anyway, tools/capture/fn84/). The order law
# (deadlock-free by the ticket argument of (2) above): two lists, R = the RAM tiles' gate_up then
# down workgroups and V = the resident tiles' gate_up then down, each in tile-id order; `kint` < 0
# = the shipped id order (bench only); 0 = all of R, then V ("first"); k > 0 = one R item then k V
# items ("capped": at most ~1 / (k + 1) of the slots on the link); each list keeps its own order,
# so a down workgroup's tile has every gate_up workgroup at a smaller ticket. `moe_back_mop_*`
# (arm D) adds: a RAM tile's down workgroup streams its SECOND W slab before it waits for silu.
