#!/usr/bin/env python3
"""Derive `moe_grouped.hip` (Flash-Next's grouped MXFP4 W4A8 GEMM, workstream FN4) from the
certified bodies it is built on.

The grouped GEMM is the split-K decode GEMM (`mxfp4_gemm_decode.hip`'s own impl,
frozen by CLEANROOM-1 from a retired generator's output) with ONE thing added: each 16*DTM-row tile of
the expert-major route array reads its expert's `w/ws/wref` base from a per-expert pointer table
and its A rows through a row map (the saber `mixed_kernel` design: an aligned 16-route block owns one
expert). Everything that decides a byte -- the W staging, the MX fold (`kMag`), the WMMA loop, the
split-K slab partition, the partial store, the fused reduce and its summation order, the epilogue
`acc * rf * As` -- is the decode kernel's, character for character. So the byte oracle holds by
construction and is gated anyway: for every expert the grouped rows equal the DENSE certified
kernel called on that expert's weights and rows at the same (DBK, DKS), byte for byte
(tools/capture/fn4/). Rows are independent in a 16x16x16 WMMA, so the dense call's own DTM (a
function of its M) does not enter the answer; DKS does, and the grouped instantiation is compared
with the dense one at its own DKS.

The second derived kernel is `silu_mul_quant` (mxfp4_quant.hip's committed impl, the producer the
27B's MLP runs) with its row read through the expert-major row map: pad rows (`row_tok < 0`) and
rows past the live count are skipped, a live row is the producer's arithmetic verbatim.

  tools/gen_moe_grouped.py [--check]
"""
import argparse
import os
import sys

HIP = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                    "..", "crates", "saber-kernels", "hip"))
DEC = os.path.join(HIP, "mxfp4_gemm_decode.hip")
QNT = os.path.join(HIP, "mxfp4_quant.hip")
FMT = os.path.join(HIP, "mxfp4_folded_mt.h")
OUT = os.path.join(HIP, "moe_grouped.hip")
HCS = os.path.join(HIP, "flashnext_hc.hip")   # FN5's split-K band (the shared-gate GEMV, FN26)
RTE = os.path.join(HIP, "moe_route.hip")      # FN4's exp / sigmoid + combine (FN26)

# The symbol set: DBK 128 (both shapes are K%128: 2,560 = 20 x 128, 640 = 5 x 128), WPERM + NT
# (the pack's fragment order, the decode default), DKS 1/2/4 x DTM 1/2/4, and the A-row mode:
# gather (gate_up: row -> token through `row_tok`) or compact (down: row -> itself).
CELLS = [(ks, tm) for ks in (1, 2, 4) for tm in (1, 2, 4)]

HEADER = '''// GENERATED by tools/gen_moe_grouped.py -- do not edit by hand, re-run the deriver.
//
// Flash-Next's grouped MXFP4 W4A8 GEMM (workstream FN4) and the expert-major silu-quant producer.
// The GEMM half is DERIVED MECHANICALLY from `mxfp4_gemm_decode.hip`'s own impl (the certified
// split-K decode body): renamed, the merged-linear partition select replaced by the tile lookup,
// the A row, the output row, the partial slab and the arrival counter read through the tile.
// Every line that decides a byte -- W staging, the MX fold, the WMMA loop, the slab partition, the
// fused reduce's order, the `acc * rf * As` epilogue -- is the decode kernel's, character for
// character, so a grouped row IS the dense kernel's row on that expert (the byte oracle,
// tools/capture/fn4/). The producer half is `silu_mul_quant`'s committed impl with its row an
// argument.
//
// The tile law (docs/EXEC.md section 11): the router/sort kernel (`moe_route.hip`) writes the
// routes expert-major, each expert's segment padded to 16 rows (a 16-row block owns ONE expert),
// and cuts each segment into tiles of up to 16*DTM rows. Tile t = (tile_expert[t], tile_row0[t],
// tile_rows[t] live rows); `meta[0]` = the live tile count (a static grid, the tail exits).
// `xptr[3*e + {0,1,2}]` = expert e's `w`, `ws`, `wref` device addresses (an EP rank's local
// experts, then the shared expert; the tier owns the table and may point a slot anywhere).
#include <hip/hip_runtime.h>
#include <hip/hip_bf16.h>
#include "mxfp4_common.h"

#define DEC_DWN 8   // waves per decode block; the N tile is DEC_DWN*16 = 128 wide
#define DEC_MTILE 16
#define DEC_PAD 8
static __device__ __forceinline__ unsigned int wq_dec(uint2_t v, int q) { return q ? v[1] : v[0]; }
template <bool NT, typename T>
static __device__ __forceinline__ T ld_w(const T *p) {
  if constexpr (NT) return __builtin_nontemporal_load(p);
  else return *p;
}

'''

TILE = '''  // ---- the tile (FN4): which expert, which rows. A tile past the live count exits whole (every
  // split of it alike, so its arrival counter is never touched).
  const int tile = blockIdx.y;
  if (tile >= meta[0]) return;
  const int texp = tile_expert[tile], row0 = tile_row0[tile];
  const int M = tile_rows[tile];
  const unsigned char *__restrict__ W =
      (const unsigned char *)(uintptr_t)xptr[3 * (size_t)texp + 0];
  const unsigned char *__restrict__ Ws =
      (const unsigned char *)(uintptr_t)xptr[3 * (size_t)texp + 1];
  const unsigned char *__restrict__ Wref =
      (const unsigned char *)(uintptr_t)xptr[3 * (size_t)texp + 2];
  // The A row of tile row m: GATHER (gate_up) reads the token the route came from, compact (down)
  // reads the expert-major row itself. Clamped rows (m >= M) are never read: stage_a clamps to
  // M - 1 exactly as the dense kernel does.
  for (int r = tid; r < DEC_MTILE * DTM; r += DNTHREADS) {
    const int rr = r < M - 1 ? r : M - 1;
    s_arow[r] = GATHER ? row_tok[row0 + rr] : row0 + rr;
  }
  __syncthreads();

'''


def derive_impls():
    """FN4's grouped impl (the decode body, seven named edits), the producer's preamble and the
    expert-major silu impl -- the pieces both code objects (`moe_grouped`, FN80b-1's
    `moe_grouped_tp2`) are assembled from."""
    src = open(DEC).read()
    lines = src.splitlines(True)
    start = next(i for i, l in enumerate(lines)
                 if l.startswith("template <int DWN, int DBK, int DKS, int DTM, bool WPERM"))
    end = next(i for i, l in enumerate(lines) if l.startswith('extern "C" __global__'))
    impl = ["".join(lines[start:end])]

    def sub(old, new, what, count=1):
        n = impl[0].count(old)
        if n != count:
            sys.exit(f"gen_moe_grouped: anchor for `{what}` found {n}x in {DEC} (want {count});\n"
                     f"  the decode kernel changed shape -- re-derive by hand, do not guess")
        impl[0] = impl[0].replace(old, new)

    # 1. the signature: W/Ws/Wref/M come from the tile; the tile tables, the row map and the
    #    partial slab's row capacity are new; the partition select's operands go.
    sub('template <int DWN, int DBK, int DKS, int DTM, bool WPERM, bool DIRECT = true, '
        'bool NT = false>\n'
        '__device__ __forceinline__ void saber_mxfp4_fp8_gemm_decode_impl(\n'
        '    const unsigned char *__restrict__ A, const unsigned char *__restrict__ W,\n'
        '    const unsigned char *__restrict__ Ws, const unsigned char *__restrict__ Wref,\n'
        '    const float *__restrict__ As, float *__restrict__ P, int *__restrict__ cnt,\n'
        '    __bf16 *__restrict__ C, int M, int N, int K, int pb1, int pb2, long astride) {',
        'template <int DWN, int DBK, int DKS, int DTM, bool WPERM, bool GATHER, bool DIRECT = true,\n'
        '          bool NT = false>\n'
        '__device__ __forceinline__ void moe_grouped_w4a8_impl(\n'
        '    const unsigned char *__restrict__ A, const unsigned long long *__restrict__ xptr,\n'
        '    const int *__restrict__ tile_expert, const int *__restrict__ tile_row0,\n'
        '    const int *__restrict__ tile_rows, const int *__restrict__ row_tok,\n'
        '    const int *__restrict__ meta,\n'
        '    const float *__restrict__ As, float *__restrict__ P, int *__restrict__ cnt,\n'
        '    __bf16 *__restrict__ C, int N, int K, int Pmax) {',
        "signature")
    # 2. the row map's LDS.
    sub('  __shared__ int s_last;\n',
        '  __shared__ int s_last;\n  __shared__ int s_arow[DEC_MTILE * DTM];\n', "shared state")
    # 3. the partition select becomes the tile lookup.
    t = impl[0]
    part = t[t.index("  // Merged-linear partition select"):t.index("  const int slabs =")]
    sub(part, TILE, "partition select")
    # 4. A rows through the map, the row base HOISTED out of the slab loop: each thread's staging
    #    rows are fixed per unrolled `off` step, so their base pointers are registers computed once
    #    (reading `s_arow` inside the loop put an LDS round trip in front of every A load). Same
    #    address, same bytes.
    sub("  auto stage_a = [&](int k0) {\n",
        "  constexpr int NITA = (DEC_MTILE * DTM * DBK + DNTHREADS * 16 - 1) / (DNTHREADS * 16);\n"
        "  const unsigned char *arow_base[NITA];\n"
        "#pragma unroll\n"
        "  for (int i = 0; i < NITA; ++i) {\n"
        "    const int idx = i * DNTHREADS * 16 + tid * 16;\n"
        "    const int r = idx < DEC_MTILE * DTM * DBK ? idx / DBK : 0;\n"
        "    const int rc = r < M - 1 ? r : M - 1;                  // clamp, never predicate\n"
        "    arow_base[i] = A + (size_t)s_arow[rc] * K;\n"
        "  }\n"
        "  auto stage_a = [&](int k0) {\n", "stage_a hoist")
    sub("*(const uint4_t *)(A + (size_t)rc * K + k0 + c);",
        "*(const uint4_t *)(arow_base[off / (DNTHREADS * 16)] + k0 + c);", "stage_a row")
    # 5. the DIRECT epilogue and the reduce's store: output row row0 + m, the per-token factor of
    #    the row's own A row.
    sub("if (m < M) C[(size_t)m * N + n] = (__bf16)(acc[i][e] * rf * As[m]);",
        "if (m < M) C[(size_t)(row0 + m) * N + n] = (__bf16)(acc[i][e] * rf * As[s_arow[m]]);",
        "direct epilogue")
    sub("C[(size_t)m * N + nn] = (__bf16)(sum * rf * As[m]);",
        "C[(size_t)(row0 + m) * N + nn] = (__bf16)(sum * rf * As[s_arow[m]]);", "reduce store")
    # 6. the partial slab: one [DKS][Pmax][N] fp32 slab, a tile's rows at row0 (the dense kernel's
    #    [DKS][M][N] with M -> Pmax and m -> row0 + m; the sum over k is the same loop).
    sub("if (m < M) P[((size_t)ks * M + m) * N + n] = acc[i][e];",
        "if (m < M) P[((size_t)ks * Pmax + row0 + m) * N + n] = acc[i][e];", "partial store")
    sub("for (int k = 0; k < DKS; ++k) sum += P[((size_t)k * M + m) * N + nn];",
        "for (int k = 0; k < DKS; ++k) sum += P[((size_t)k * Pmax + row0 + m) * N + nn];",
        "reduce loop")
    # 7. one arrival counter per (tile, n-block).
    sub("s_last = (atomicAdd(&cnt[blockIdx.x], 1) == DKS - 1);",
        "s_last = (atomicAdd(&cnt[(size_t)tile * gridDim.x + blockIdx.x], 1) == DKS - 1);",
        "counter")
    sub("if (tid == 0) cnt[blockIdx.x] = 0;",
        "if (tid == 0) cnt[(size_t)tile * gridDim.x + blockIdx.x] = 0;", "counter reset")
    out = impl[0]
    for dead in ("pb1", "pb2", "astride", "As[m]", "* M + m"):
        if dead in out:
            sys.exit(f"gen_moe_grouped: `{dead}` survived the derivation")

    # The producer: silu_mul_quant's committed impl, its row an argument, TILED dropped (the down
    # GEMM reads the row-major compact rows).
    q = open(QNT).read()
    pre = q[q.index("#define ARNQ_T 256"):q.index("template <int ART, bool TILED = false>\n"
                                                    "__device__ __forceinline__ void "
                                                    "saber_add_rms_quant_impl(")]
    s0 = q.index("template <int ART, bool TILED = false>\n__device__ __forceinline__ void "
                 "saber_silu_mul_quant_impl(")
    s1 = q.index("// ---- fused per-head gated RMSNorm")
    silu = q[s0:s1].rstrip() + "\n"
    for old, new, what in (
        ("__device__ __forceinline__ void saber_silu_mul_quant_impl(\n",
         "__device__ __forceinline__ void moe_silu_mul_quant_impl(\n    const int row,\n",
         "silu impl name"),
        ("  const int row = blockIdx.x;\n", "", "silu row"),
    ):
        if silu.count(old) != 1:
            sys.exit(f"gen_moe_grouped: silu anchor `{what}` not found once in {QNT}")
        silu = silu.replace(old, new)
    return out, pre, silu


def derive():
    out, pre, silu = derive_impls()
    wr = []
    for gather in (1, 0):
        for ks, tm in CELLS:
            name = f"moe_grouped_w4a8_bk128_ks{ks}_tm{tm}_g{gather}"
            wr.append(f'''extern "C" __global__ __launch_bounds__(DEC_DWN * 32) void {name}(
    const unsigned char *__restrict__ A, const unsigned long long *__restrict__ xptr,
    const int *__restrict__ tile_expert, const int *__restrict__ tile_row0,
    const int *__restrict__ tile_rows, const int *__restrict__ row_tok,
    const int *__restrict__ meta, const float *__restrict__ As, float *__restrict__ P,
    int *__restrict__ cnt, __bf16 *__restrict__ C, int N, int K, int Pmax) {{
  moe_grouped_w4a8_impl<DEC_DWN, 128, {ks}, {tm}, true, {"true" if gather else "false"}, true, true>(
      A, xptr, tile_expert, tile_row0, tile_rows, row_tok, meta, As, P, cnt, C, N, K, Pmax);
}}
''')
    silu_wr = '''// The expert-major silu-quant: one workgroup per row of the padded route array; `meta[1]` = the
// live padded row count, `row_tok[row] < 0` = a pad row (skipped, its bytes never read: the down
// GEMM clamps to the tile's live rows). A live row is `silu_mul_quant_t256_tiled0`'s arithmetic.
extern "C" __global__ __launch_bounds__(256) void moe_silu_mul_quant_t256(
    const __bf16 *__restrict__ gu, unsigned char *__restrict__ q, float *__restrict__ scale,
    int N, const int *__restrict__ row_tok, const int *__restrict__ meta) {
  const int row = blockIdx.x;
  if (row >= meta[1] || row_tok[row] < 0) return;
  moe_silu_mul_quant_impl<256, false>(row, gu, q, scale, N);
}
'''
    return (HEADER + out + "\n\n" + "\n".join(wr) +
            "\n// ---------------------------------------------------------------- the producer\n" +
            pre + silu + "\n" + silu_wr + "\n" + derive_pf() + derive_train(out, silu) + derive_mo())


# ---------------------------------------------------------------- the PREFILL body (FN20)
# The grouped PREFILL body is derived from G5's certified mid-M folded tile (`mxfp4_folded_mt.h`,
# `saber_mxfp4_folded_mt_impl`: row-major e4m3 A staged through LDS, W in fragment order folded once
# per 64-deep slab through kMag, the WMMA chain over k ascending, the EPIFAST epilogue
# `acc * rf * As`) with FN4's per-tile indirection. Per 16x16 output tile the arithmetic is the
# folded tile's, character for character. The instantiation: TN 4 x WN 2 = the 128-wide N tile the
# MoE launch law's grid (N / 128) already names, WM 4 waves down M (256 threads, the launch law's
# block), TM 1 / 2 / 4 fragments a wave = a 64 / 128 / 256-row tile = the route's `tile_blocks`
# 4 / 8 / 16. A tile owns up to 16 * tile_blocks of ONE expert's rows and stages each 64-deep W slab
# once for all of them, so an expert with <= 16 * tile_blocks routed rows streams its weights once
# per launch (the link law, LEDGER FN8 / FN20). Operands = SIG_MOE_GROUPED (P, cnt and Pmax unused:
# the parent has no split-K), so the existing launcher launches it unchanged at ks 1.
PF_CELLS = [(1, 4), (2, 8), (4, 16)]          # (TM fragments a wave, tile_blocks)

PF_HEAD = """// ---------------------------------------------------------------- the grouped PREFILL body
// DERIVED by tools/gen_moe_grouped.py (workstream FN20) from `mxfp4_folded_mt.h`'s
// `saber_mxfp4_folded_mt_impl` (G5's certified mid-M folded tile): renamed, the merged-linear
// partition select replaced by FN4's tile lookup, the A row through the tile's row map (row bases
// hoisted to registers), the output row `row0 + m`, the per-token factor of the row's own A row.
// Every line that decides a byte -- the A / W LDS layout, the kMag fold, the WMMA chain, the
// EPIFAST epilogue -- is the folded tile's, character for character. Layout law: A is ROW-MAJOR
// e4m3 (`q8` rows of the block input for gate_up through `row_tok`; the silu-quant's compact rows
// for down) -- what FN5's HC up producer and `moe_silu_mul_quant_t256` already emit.
#include "mxfp4_folded_mt.h"

"""

PF_TILE = """  // ---- the tile (FN4's law): which expert, which rows. A tile past the live count exits whole.
  const int tile = blockIdx.y;
  if (tile >= meta[0]) return;
  const int texp = tile_expert[tile], row0 = tile_row0[tile];
  const int M = tile_rows[tile];
  const unsigned char *__restrict__ W =
      (const unsigned char *)(uintptr_t)xptr[3 * (size_t)texp + 0];
  const unsigned char *__restrict__ Ws =
      (const unsigned char *)(uintptr_t)xptr[3 * (size_t)texp + 1];
  const unsigned char *__restrict__ Wref =
      (const unsigned char *)(uintptr_t)xptr[3 * (size_t)texp + 2];
  __shared__ int s_arow[BMF_];
  for (int r = tid; r < BMF_; r += NT_) {
    const int rr = r < M - 1 ? r : M - 1;                   // clamp, never predicate
    s_arow[r] = GATHER ? row_tok[row0 + rr] : row0 + rr;
  }
  __syncthreads();
  const int m0 = 0, n0 = blockIdx.x * BNF_T;
  // Each thread's A staging rows are fixed per unrolled `off` step: their bases are registers.
  constexpr int NITA = BMF_ * BK / (NT_ * 16);
  const unsigned char *arow_base[NITA];
#pragma unroll
  for (int i = 0; i < NITA; ++i) {
    const int r = (i * NT_ * 16 + tid * 16) / BK;
    const int rc = r < M - 1 ? r : M - 1;                   // clamp, never predicate
    arow_base[i] = A + (size_t)s_arow[rc] * K;
  }
"""


def derive_pf():
    t = open(FMT).read()
    t = t[t.index("template <int TN, int TM_, int WM_, int CTRL = 0>"):]
    box = [t]

    def sub(old, new, what):
        n = box[0].count(old)
        if n != 1:
            sys.exit(f"gen_moe_grouped: prefill anchor for `{what}` found {n}x in {FMT} (want 1);\n"
                     f"  the folded tile changed shape -- re-derive by hand, do not guess")
        box[0] = box[0].replace(old, new)

    # 1. the signature: SIG_MOE_GROUPED's operands (P / cnt / Pmax stay in the wrapper, unused).
    sub("template <int TN, int TM_, int WM_, int CTRL = 0>\n"
        "__device__ __forceinline__ void saber_mxfp4_folded_mt_impl(\n"
        "    const unsigned char *__restrict__ A, const unsigned char *__restrict__ W,\n"
        "    const unsigned char *__restrict__ Ws, const unsigned char *__restrict__ Wref,\n"
        "    const float *__restrict__ As, __bf16 *__restrict__ C, int M, int N, int K,\n"
        "    int pb1, int pb2, long astride) {",
        "template <int TN, int TM_, int WM_, bool GATHER, int CTRL = 0>\n"
        "__device__ __forceinline__ void moe_grouped_pf_impl(\n"
        "    const unsigned char *__restrict__ A, const unsigned long long *__restrict__ xptr,\n"
        "    const int *__restrict__ tile_expert, const int *__restrict__ tile_row0,\n"
        "    const int *__restrict__ tile_rows, const int *__restrict__ row_tok,\n"
        "    const int *__restrict__ meta, const float *__restrict__ As, __bf16 *__restrict__ C,\n"
        "    int N, int K) {", "signature")
    # 2. the block origin + the partition select -> the tile lookup and the row map.
    sub("  const int m0 = blockIdx.y * BMF_, n0 = blockIdx.x * BNF_T;\n"
        "  {\n"
        "    const int p_ = n0 >= pb2 ? 2 : (n0 >= pb1 ? 1 : 0);\n"
        "    A += (size_t)p_ * astride;\n"
        "    As += (size_t)p_ * M;\n"
        "  }\n", PF_TILE, "tile lookup")
    # 3. the A row through the map (the hoisted base of the unrolled step's row).
    sub("    const unsigned char *__restrict__ Ab = A + (size_t)m0 * K + k0;\n", "", "A base")
    sub("      *(uint4_t *)(&sA[r * ASTR + c]) = *(const uint4_t *)(Ab + (rc * K + c));\n",
        "      (void)rc;\n"
        "      *(uint4_t *)(&sA[r * ASTR + c]) =\n"
        "          *(const uint4_t *)(arow_base[off / (NT_ * 16)] + k0 + c);\n", "A row")
    # 4. the epilogue: output row row0 + m, the per-token factor of the row's own A row.
    sub("    __bf16 *__restrict__ Cb = C + (size_t)(m0 + wm * TM_ * 16) * N;\n"
        "    const float *__restrict__ Asb = As + m0 + wm * TM_ * 16;\n",
        "    __bf16 *__restrict__ Cb = C + (size_t)(row0 + wm * TM_ * 16) * N;\n"
        "    const int *__restrict__ sab = s_arow + wm * TM_ * 16;\n", "fast epilogue base")
    sub("            Cb[r * N + n] = (__bf16)(acc[i][j][e] * rf[j] * Asb[r]);\n",
        "            Cb[r * N + n] = (__bf16)(acc[i][j][e] * rf[j] * As[sab[r]]);\n",
        "fast epilogue store")
    sub("        if (m < M && n < N) C[(size_t)m * N + n] = (__bf16)(acc[i][j][e] * rf[j] * As[m]);\n",
        "        if (m < M && n < N)\n"
        "          C[(size_t)(row0 + m) * N + n] = (__bf16)(acc[i][j][e] * rf[j] * As[s_arow[m]]);\n",
        "tail epilogue")
    out = box[0]
    for dead in ("pb1", "pb2", "astride", "As[m]", "Asb", "Ab +"):
        if dead in out:
            sys.exit(f"gen_moe_grouped: `{dead}` survived the prefill derivation")
    wr = []
    for gather in (1, 0):
        for tmf, tb in PF_CELLS:
            name = f"moe_grouped_w4a8_pf_tm{tb}_g{gather}"
            g = "true" if gather else "false"
            wr.append(f'''extern "C" __global__ __launch_bounds__(256) void {name}(
    const unsigned char *__restrict__ A, const unsigned long long *__restrict__ xptr,
    const int *__restrict__ tile_expert, const int *__restrict__ tile_row0,
    const int *__restrict__ tile_rows, const int *__restrict__ row_tok,
    const int *__restrict__ meta, const float *__restrict__ As, float *__restrict__ P,
    int *__restrict__ cnt, __bf16 *__restrict__ C, int N, int K, int Pmax) {{
  (void)P; (void)cnt; (void)Pmax;
  moe_grouped_pf_impl<4, {tmf}, 4, {g}>(A, xptr, tile_expert, tile_row0, tile_rows, row_tok,
                                         meta, As, C, N, K);
}}
''')
    return PF_HEAD + out + "\n" + "\n".join(wr)


# ---------------------------------------------------------------- the decode TRAIN (FN26)
# Two things, both BYTE-EXACT BY CONSTRUCTION and byte-gated on the card (tools/capture/fn26/):
#
#  (1) THE PREFETCH LEVER. `moe_grouped_w4a8_x_impl` is FN4's grouped impl (the text above, after
#      FN4's seven edits) with four more named edits: (8) the workgroup's (n-block, tile, split) and
#      the n-block count are ARGUMENTS (a fused launch runs several GEMMs on one 1-D grid); (9) the
#      LDS is a caller-provided arena (two instantiations in one kernel would otherwise SUM their
#      LDS -- FN23's law -- and halve the residency); (10) at PFD 1 the slab loop is DOUBLE-BUFFERED
#      IN REGISTERS: slab s + 1's W words, its E8M0 scale bytes and its A bytes are loaded before
#      slab s is folded and multiplied. The fold, the LDS images and the WMMA chain are
#      stage_w_wperm / stage_a's expressions verbatim, the slabs are the same slabs in the same
#      order, the split-K partition, the partial slab and the fused reduce are untouched -- so every
#      LDS byte, every accumulator and every output byte is the shipped cell's; (11) a `wait` hook
#      runs once, after the first slab's W words are in flight and before any A byte is read (the
#      fused down waits there for its tile's silu rows while its weights stream). PFD 0 is the
#      shipped loop with the hook in front. The n-block WIDTH (`_n64`: 4 waves, 64 columns) is the
#      other byte-exact lever: a wave's 16 columns are computed by the same chain at any width.
#
#  (2) THE FUSED BACK HALF of the MoE block, `moe_back_gu{KSG}_dn{KSD}_p{PFD}`: the shared-expert
#      gate GEMV + grouped gate_up + expert-major silu-quant + grouped down + the weighted combine as
#      ONE launch (5 of FN4's 7 launches). A 1-D grid of workgroups takes TICKETS (an atomic
#      counter: ticket order == start order, so a workgroup only ever waits on workgroups that have
#      already started -- no residency or dispatch-order assumption, no deadlock): ticket 0 = the
#      gate GEMV (FN5's split-K band at one split = the engine's `fn_bgemm_sk_m16` call, derived
#      verbatim); then every (tile, n-block, split) of gate_up; then every (tile, n-block, split) of
#      down. Device counters chain them: the LAST gate_up workgroup of a tile (10 n-blocks x KSG
#      splits arrived) runs the silu-quant for the tile's rows and releases the tile's flag; a down
#      workgroup of that tile streams its first W slab, then waits on the flag; the LAST down
#      workgroup of an n-block (every live tile x KSD splits arrived) runs the combine for those 128
#      columns of every token. Every counter is zero at allocation and zeroed by its last user (the
#      27B's split-K reset law), so a replay finds them zero. Per-row arithmetic: gate_up / down =
#      the x_impl (== the shipped cells by (1)); silu = `silu_mul_quant`'s expressions with a wave
#      per row (amax is a max: order-free, exact); combine = `moe_combine_bf16`'s sum in top-k order
#      + the shared term, contraction off, one bf16 rounding. Gated against the shipped train.
