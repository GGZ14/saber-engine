#!/usr/bin/env python3
"""FN153: derive `crates/saber-kernels/hip/moe_fn153.hip` -- FN148's FORM (b) (exact NVFP4 weights: plain e2m1
bytes, `tile = wmma(a8, e2m1, 0); acc = fma(tile, E4M3(s_g), acc)` per 16-deep k-group in k order, epilogue
x gs x As) in the shipped grouped PREFILL tile `moe_grouped_pf_impl` (FN20, `moe_grouped.hip`: 128-wide N tile x
64 / 128 / 256 rows of one expert, 8 waves, 64-deep W slab staged once per tile, no split-K).
Byte law: every output byte == FN148's ks1 cell (`fn148_w4a8b_bk{128,64}_ks1_tm*_g*`) on the same routes -- the
chain per output element is the ks1 chain (groups ascending, one fma a group, acc starts at +0).

What changes vs the shipped MXFP4 prefill tile (anchored substitutions, each asserted once):
  * the record is the xtier v2 NVFP4 one: xptr[3e + {0,1,2}] = w (permute_w e2m1), ws (E4M3 [K/16, N]), gs (f32 x 2
    split at `gsplit` for gate_up / x 1 down); the kernel signature is SIG_FN148_GROUPED (+ gsplit);
  * the W fold has NO `wref` / `ws` word loads and no kMag[d] lookup: the plain e2m1 table kMag[0] (immediates);
  * the slab's E4M3 g16 scale bytes: (SC bit 1 clear) staged by the W-staging threads as a [128 rows][4 groups]
    byte table in LDS (one u32 global load + 4 byte stores a thread a slab) and read by each WMMA lane as ONE
    ds_load_b32 per column fragment after the slab barrier; (SC bit 1 set) each lane loads its own columns'
    bytes from global before the staging (register form, the attribution arm);
  * the MMA: per 16-deep step and fragment pair, `t = wmma(a, w, 0)` then 8 `fma(t[e], s, acc[e])`;
    (SC bit 2) explicitly software-pipelined: the next pair's WMMA is issued before the previous pair's fmas;
  * (SC bit 0) dead-fragment skip: a wave's 16-row fragment whose first row is >= the tile's live rows M is
    neither loaded nor multiplied (wave-uniform branch); its rows are never stored (the tail epilogue tests m < M,
    the fast epilogue runs only on a full tile), so the live bytes are unchanged;
  * the epilogue factor is the record's gs (gate / up by gsplit) instead of 2^wref.
  python3 tools/gen_fn153_nvfp4pf.py          # write
  python3 tools/gen_fn153_nvfp4pf.py --check  # the committed file == the derivation
"""
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(REPO, "crates/saber-kernels/hip/moe_grouped.hip")
OUT = os.path.join(REPO, "crates/saber-kernels/hip/moe_fn153.hip")

# (tb = tile blocks (rows / 16), gather, SC, suffix)
# SC bit 0 = dead-fragment skip, bit 1 = register scales (else LDS), bit 2 = software-pipelined MMA
CELLS = (
    [(tb, g, 1, "") for g in (1, 0) for tb in (4, 8, 16)]
    + [(4, g, sc, sfx) for g in (1, 0) for sc, sfx in ((0, "_f"), (3, "_r"), (5, "_i"))]
    + [(tb, g, 5, "_i") for g in (1, 0) for tb in (8, 16)]
)
TMF = {4: 1, 8: 2, 16: 4}


def sub(text, old, new, count=1):
    n = text.count(old)
    if n != count:
        sys.exit(f"gen_fn153: anchor found {n}x (want {count}): {old[:100]!r}\n"
                 f"  moe_grouped_pf_impl changed shape -- re-derive by hand, do not guess")
    return text.replace(old, new)


HEAD = r'''// GENERATED by tools/gen_fn153_nvfp4pf.py -- do not edit by hand, re-run the deriver.
//
// FN153: FN148's NVFP4 FORM (b) in the shipped grouped PREFILL tile (`moe_grouped.hip`'s `moe_grouped_pf_impl`,
// FN20: 128-wide N tile x 64 / 128 / 256 rows of one expert, 8 waves, a 64-deep W slab staged once a tile).
// Record = the xtier v2 NVFP4 one (w permute_w e2m1, ws E4M3 g16 [K/16, N], gs f32); ABI SIG_FN148_GROUPED.
// Per output element: acc = fma(wmma(a8, e2m1, 0)[e], E4M3(ws[g, n]), acc) over the 16-k groups ascending,
// C = bf16(acc * gs * As) -- FN148's ks1 chain, so every byte == `fn148_w4a8b_bk*_ks1_*` on the same routes.
// Symbols: fn153_w4a8b_pf_tm{4,8,16}_g{0,1}[_sfx]; see the generator's docstring for the SC variants.
#include <hip/hip_runtime.h>
#include <hip/hip_bf16.h>
#include "mxfp4_common.h"

'''

REGSC = r'''    // FN153 SC bit 1: this lane's columns' KG scale bytes from global, before the staging (register form).
    unsigned int scw[TN];
    if constexpr ((SC & 2) != 0) {
#pragma unroll
      for (int j = 0; j < TN; ++j) {
        const int n_ = n0 + wn * TN * 16 + j * 16 + col;
        const int nc = n_ < N ? n_ : N - 1;
        unsigned int w = 0;
#pragma unroll
        for (int g = 0; g < KG; ++g) w |= (unsigned int)Ws[(size_t)(k0 / 16 + g) * N + nc] << (8 * g);
        scw[j] = w;
      }
    }
'''

MMA = r'''    // FN153: the column fragments' scale words (KG E4M3 bytes each), one ds_load_b32 a fragment.
    if constexpr ((SC & 2) == 0) {
#pragma unroll
      for (int j = 0; j < TN; ++j)
        scw[j] = *(const unsigned int *)&s_sc153[(wn * TN * 16 + j * 16 + col) * KG];
    }
#pragma unroll
    for (int step = 0; step < BK / 16; ++step) {
      const int kk = step * 16 + kb8;
      int2_t af[TM_], wf[TN];
      float sv[TN];
#pragma unroll
      for (int i = 0; i < TM_; ++i) {
        if ((SC & 1) == 0 || i < nlf) {
          const unsigned char *p = &sA[(wm * TM_ * 16 + i * 16 + col) * ASTR + kk];
          af[i][0] = *(const int *)p; af[i][1] = *(const int *)(p + 4);
        }
      }
#pragma unroll
      for (int j = 0; j < TN; ++j) {
        const unsigned char *p = &sW[(wn * TN * 16 + j * 16 + col) * WSTR + kk];
        wf[j][0] = *(const int *)p; wf[j][1] = *(const int *)(p + 4);
        sv[j] = __builtin_amdgcn_cvt_f32_fp8((int)(scw[j] >> (8 * step)), 0);   // step is unrolled
      }
      __builtin_amdgcn_sched_barrier(0);
      const floatx8 z = {0.f, 0.f, 0.f, 0.f, 0.f, 0.f, 0.f, 0.f};
      if constexpr ((SC & 4) == 0) {
#pragma unroll
        for (int i = 0; i < TM_; ++i) {
          if ((SC & 1) == 0 || i < nlf) {
#pragma unroll
            for (int j = 0; j < TN; ++j) {
              const floatx8 tt = __builtin_amdgcn_wmma_f32_16x16x16_fp8_fp8_w32_gfx12(af[i], wf[j], z);
#pragma unroll
              for (int e = 0; e < 8; ++e) acc[i][j][e] = __builtin_fmaf(tt[e], sv[j], acc[i][j][e]);
            }
          }
        }
      } else {
#pragma unroll
        for (int i = 0; i < TM_; ++i) {
          if ((SC & 1) == 0 || i < nlf) {
            floatx8 tp = __builtin_amdgcn_wmma_f32_16x16x16_fp8_fp8_w32_gfx12(af[i], wf[0], z);
#pragma unroll
            for (int j = 1; j < TN; ++j) {
              const floatx8 tn = __builtin_amdgcn_wmma_f32_16x16x16_fp8_fp8_w32_gfx12(af[i], wf[j], z);
#pragma unroll
              for (int e = 0; e < 8; ++e) acc[i][j - 1][e] = __builtin_fmaf(tp[e], sv[j - 1], acc[i][j - 1][e]);
              tp = tn;
            }
#pragma unroll
            for (int e = 0; e < 8; ++e) acc[i][TN - 1][e] = __builtin_fmaf(tp[e], sv[TN - 1], acc[i][TN - 1][e]);
          }
        }
      }
    }
'''


def derive():
    src = open(SRC).read()
    a = src.index("template <int TN, int TM_, int WM_, bool GATHER, int CTRL = 0>\n"
                  "__device__ __forceinline__ void moe_grouped_pf_impl(")
    b = src.index('extern "C" __global__ __launch_bounds__(256) void moe_grouped_w4a8_pf_tm4_g1(')
    t = src[a:b]
    # 1. the signature (+ gsplit, the SC template).
    t = sub(t, "template <int TN, int TM_, int WM_, bool GATHER, int CTRL = 0>\n"
               "__device__ __forceinline__ void moe_grouped_pf_impl(",
            "template <int TN, int TM_, int WM_, bool GATHER, int SC>\n"
            "__device__ __forceinline__ void fn153_pf_impl(")
    t = sub(t, "    const int *__restrict__ meta, const float *__restrict__ As, __bf16 *__restrict__ C,\n"
               "    int N, int K) {",
            "    const int *__restrict__ meta, const float *__restrict__ As, __bf16 *__restrict__ C,\n"
            "    int N, int K, int gsplit) {\n"
            "  static_assert(BK == 64, \"FN153: the 64-deep slab (4 NVFP4 groups)\");\n"
            "  constexpr int KG = BK / 16;   // NVFP4 16-k groups a slab")
    # 2. the record: Wref -> the f32 globals.
    t = sub(t, "  const unsigned char *__restrict__ Wref =\n"
               "      (const unsigned char *)(uintptr_t)xptr[3 * (size_t)texp + 2];\n",
            "  const float *__restrict__ Gs = (const float *)(uintptr_t)xptr[3 * (size_t)texp + 2];\n"
            "  // FN153: the slab's E4M3 g16 scale bytes, [BNF_T rows][KG groups] (SC bit 1 clear).\n"
            "  __shared__ __attribute__((aligned(16))) unsigned char s_sc153[BNF_T * KG];\n"
            "  // FN153 SC bit 0: this wave's live 16-row fragments (wave-uniform).\n"
            "  const int nlf = __builtin_amdgcn_readfirstlane(\n"
            "      min(TM_, max(0, (M - (wave / WN_) * TM_ * 16 + 15) / 16)));\n")
    # 3. the staging fold: plain e2m1 table, the scale bytes into LDS.
    t = sub(t, "        const int blk = (k0 + kst * 16) / 32;\n"
               "        unsigned int refw, wsw;\n"
               "        if constexpr (WSLOTS == 4) {\n"
               "          refw = *(const unsigned int *)(Wref + gc);\n"
               "          wsw = *(const unsigned int *)(Ws + (size_t)blk * N + gc);\n"
               "        } else {\n"
               "          refw = *(const unsigned short *)(Wref + gc);\n"
               "          wsw = *(const unsigned short *)(Ws + (size_t)blk * N + gc);\n"
               "        }\n",
            "        static_assert(WSLOTS == 4, \"FN153: four rows a W slot group\");\n"
            "        if constexpr ((SC & 2) == 0) {\n"
            "          const unsigned int sw4 = *(const unsigned int *)(Ws + (size_t)(kstep0 + kst) * N + gc);\n"
            "#pragma unroll\n"
            "          for (int q = 0; q < 4; ++q) s_sc153[(r + q) * KG + kst] = (unsigned char)(sw4 >> (8 * q));\n"
            "        }\n")
    t = sub(t, "          int d = (int)((refw >> (8 * q)) & 0xFF) - (int)((wsw >> (8 * q)) & 0xFF);\n"
               "          d = d < 0 ? 0 : (d > 15 ? 15 : d);\n"
               "          const unsigned int t0 = kMag[d][0], t1 = kMag[d][1];\n",
            "          const unsigned int t0 = 0x3c383000u, t1 = 0x4c484440u;   // kMag[0]: plain e2m1\n")
    t = sub(t, "          if constexpr (CTRL == 2) {\n"
               "            *(uint2_t *)(&sW[(r + q) * WSTR + kloc]) = uint2_t{wq[q], wq[q] ^ 0x5a5a5a5au};\n"
               "          } else {\n"
               "            *(uint2_t *)(&sW[(r + q) * WSTR + kloc]) =\n"
               "                uint2_t{__builtin_amdgcn_perm(bo, be, 0x05010400u),\n"
               "                        __builtin_amdgcn_perm(bo, be, 0x07030602u)};\n"
               "          }\n",
            "          *(uint2_t *)(&sW[(r + q) * WSTR + kloc]) =\n"
            "              uint2_t{__builtin_amdgcn_perm(bo, be, 0x05010400u),\n"
            "                      __builtin_amdgcn_perm(bo, be, 0x07030602u)};\n")
    # 4. the MMA: per-group scale fma, the skip, the pipelined arm.
    i0 = t.index("#pragma unroll\n    for (int step_ = 0; step_ < BK / 16; ++step_) {")
    i1 = t.index("    __syncthreads();\n  }\n\n  // Epilogue")
    t = t[:i0] + MMA + t[i1:]
    t = sub(t, "  for (int k0 = 0; k0 < K; k0 += BK) {\n",
            "  for (int k0 = 0; k0 < K; k0 += BK) {\n" + REGSC)
    # 5. the epilogue factor: the record's f32 global (gate / up by gsplit).
    t = sub(t, "    rf[j] = (n < N) ? __int_as_float((int)Wref[n] << 23) : 0.f;\n",
            "    rf[j] = (n < N) ? Gs[n < gsplit ? 0 : 1] : 0.f;\n")
    for dead in ("Wref", "kMag[d]", "refw", "CTRL", "blk"):
        if dead in t:
            sys.exit(f"gen_fn153: `{dead}` survived the derivation")
    wr = []
    for tb, g, sc, sfx in CELLS:
        name = f"fn153_w4a8b_pf_tm{tb}_g{g}{sfx}"
        wr.append(f'''extern "C" __global__ __launch_bounds__(256) void {name}(
    const unsigned char *__restrict__ A, const unsigned long long *__restrict__ xptr,
    const int *__restrict__ tile_expert, const int *__restrict__ tile_row0,
    const int *__restrict__ tile_rows, const int *__restrict__ row_tok,
    const int *__restrict__ meta, const float *__restrict__ As, float *__restrict__ P,
    int *__restrict__ cnt, __bf16 *__restrict__ C, int N, int K, int Pmax, int gsplit) {{
  (void)P; (void)cnt; (void)Pmax;
  fn153_pf_impl<4, {TMF[tb]}, 4, {"true" if g else "false"}, {sc}>(A, xptr, tile_expert, tile_row0, tile_rows,
                                                     row_tok, meta, As, C, N, K, gsplit);
}}
''')
    return HEAD + "// ---------------- derived from moe_grouped.hip's moe_grouped_pf_impl (FN20) ----------------\n" \
        + t + "\n" + "\n".join(wr)


def main():
    out = derive()
    if "--check" in sys.argv:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        if cur != out:
            sys.exit("gen_fn153: the committed moe_fn153.hip != the derivation (re-run the deriver)")
        print("gen_fn153: moe_fn153.hip == the derivation")
        return
    open(OUT, "w").write(out)
    print(f"gen_fn153: wrote {OUT} ({len(CELLS)} symbols)")


if __name__ == "__main__":
    main()
