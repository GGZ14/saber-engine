#!/usr/bin/env python3
"""MACFN7: derive `crates/saber-kernels/hip/moe_macfn7.hip` -- the MACaQ int4 FUSED BACK HALF (TP=2 half records,
xtier v2 tag 3, the shared expert on its MACaQ record = `--fn-macaq-shared int4`): the shared-gate GEMV, (optionally)
the MoE input's token int8 rows, gate_up, the MACaQ silu-had32-int8 down input, down and the combine as ONE
ticket-ordered launch (FN26's form), with or without FN137's fused MoE-out reduce. A NEW object: moe_macfn3 and every
shipped object stay byte-identical.

  macfn7_back_h2_gu{G}_dn{D}[_tk]       the half-width back half (SIG_MACFN7_BACK)
  macfn7_back_h2_far_gu{G}_dn{D}[_tk]   + FN137's fused reduce, FMODE 0 (SIG_MACFN7_BACK_FAR)
  `_tk` = the token rows ride the launch (tickets 1..T, `macfn3_tok_hadi8_t256`'s row body); without it the engine
  launches `macfn3_tok_hadi8_t256` first (MACFN5's producer, unchanged).

THE BYTE LAW vs MACFN5's seven-launch MACaQ train (tok, `macfn3_i4_*_g1` gate_up, `macfn3_silu_hadi8_t64`,
`macfn3_i4_*_g0` down, `moe_combine_bf16`, the router-side `fn_bgemm_sk_m16` gate GEMV):
  * the GEMMs are `macfn3_i4_impl`'s text with the workgroup's coordinates as arguments and a wait hook before the
    first A slab (anchored substitutions below). The accumulator is exact int32 over all of K, so ANY split count
    gives the same int32 sum and the same epilogue bits (MACFN3's law): the fused half may split where the
    standalone cells run ks 1.
  * the token row is `macfn3_tok_row` with its row an argument; the silu row is `macfn3_silu_impl`'s per-element
    expressions with the row's 40 groups on one wave (lane bits 0-1 = group bits 0-1, so `macaq_had32`'s quads are
    the parent's) and its 64-thread amax as a wave amax (a max: order-free, exact).
  * the gate GEMV (`moe_x_bgemm_sk_body`), the sigmoid and `mx_combine_slice`, and FN137's exchange are
    moe_grouped_far.hip's text, verbatim (that object's contract-off region; this object is built contract-off).
The whole object is built with -ffp-contract=off (saber-kbuild EXTRA_FLAGS row `moe_macfn7`), as moe_macfn3.
  python3 tools/gen_macfn7_back.py          # write
  python3 tools/gen_macfn7_back.py --check  # the committed file == the derivation
"""
