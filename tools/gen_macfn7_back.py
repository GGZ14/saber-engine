CALL = ("A, As, xgu, xdn, tile_expert, tile_row0, tile_rows, row_tok, meta, Pgu, Pdn, cgu, cdn, GU, Q, QS, Y,\n"
        "      topk_w, route_pos, wsg, bi, sg, out, sync, T, Pmax, tc, tsh")


def wrappers():
    out = ["\n// ================================================================ MACFN7: the cells\n"]
    for g, d in PAIRS:
        for tk in (False, True):
            sfx = "_tk" if tk else ""
            tkv = "true" if tk else "false"
            out.append(f'extern "C" __global__ __launch_bounds__(256) void macfn7_back_h2_gu{g}_dn{d}{sfx}(\n{ARGS}) {{\n'
                       f"  macfn7_back_impl<{g}, {d}, {tkv}, -1>({CALL}, FarArgs{{}});\n}}\n\n")
            out.append(f'extern "C" __global__ __launch_bounds__(256) void macfn7_back_h2_far_gu{g}_dn{d}{sfx}(\n{ARGS},\n'
                       f"    FarArgs fa) {{\n  macfn7_back_impl<{g}, {d}, {tkv}, 0>({CALL}, fa);\n}}\n\n")
    return "".join(out).rstrip() + "\n"


def derive():
    m3 = open(M3).read()
    far = open(FAR).read()
    helpers = span(m3, "typedef int m3_int2", 'extern "C" __global__ __launch_bounds__(256) void macfn3_tok_hadi8_t256(')
    # the token row with its row an argument (the parent reads blockIdx.x)
    helpers = sub(helpers, "static __device__ __forceinline__ void macfn3_tok_row(",
                  "static __device__ __forceinline__ void m7_tok_row(")
    helpers = sub(helpers, "float *__restrict__ sc, int K) {", "float *__restrict__ sc, int K, const int row) {")
    helpers = sub(helpers, "  const int row = blockIdx.x, tid = threadIdx.x;\n", "  const int tid = threadIdx.x;\n")
    gemm = span(m3, "// an LDS-only workgroup barrier", "#define MACFN3_I4(")
    gemm = sub(gemm, "template <int NS, int DKS, int DTM, bool GATHER, bool PF = false, bool SX = false>\n"
                     "__device__ __forceinline__ void macfn3_i4_impl(",
               "template <int NS, int DKS, int DTM, bool GATHER, bool PF, bool SX, typename WaitF>\n"
               "__device__ __forceinline__ void m7_i4_impl(")
    gemm = sub(gemm, "int *__restrict__ P, int *__restrict__ cnt, __bf16 *__restrict__ C, int N, int K, int Pmax) {",
               "int *__restrict__ P, int *__restrict__ cnt, __bf16 *__restrict__ C, int N, int K, int Pmax,\n"
               "    const int nbx, const int tile, const int ks, const int NBX, WaitF &&wait) {")
    gemm = sub(gemm, "  const int tile = blockIdx.y;\n", "")
    gemm = sub(gemm, "  const int ks = blockIdx.z;\n", "")
    gemm = sub(gemm, "blockIdx.x", "nbx", 4)
    gemm = sub(gemm, "gridDim.x", "NBX", 2)
    # the wait hook: after the first W slab is in flight (PF), before any A byte or scale is read
    gemm = sub(gemm, "    if (s_lo < s_hi) load_w(s_lo, d0);\n", "    if (s_lo < s_hi) load_w(s_lo, d0);\n    wait();\n")
    gemm = sub(gemm, "  } else {\n#pragma unroll 2\n", "  } else {\n    wait();\n#pragma unroll 2\n")
    farc = span(far, "typedef __bf16 mx_bf16x8", "// The fused back half. `sync`")
    exch = span(far, "// ---------------------------------------------------------------- FN137: the exchange",
                "template <int KSG, int KSD, int PFD, int FMODE>")
    exch = sub(exch, "// The oracle's skew source: one workgroup spins `ticks` of the 100 MHz realtime clock.\n"
                     'extern "C" __global__ void fn137_delay(unsigned long long ticks) {\n'
                     "  const unsigned long long t0 = wall_clock64();\n"
                     "  while (wall_clock64() - t0 < ticks) __builtin_amdgcn_s_sleep(1);\n}\n", "")
    return (HEAD + helpers.rstrip() + "\n\n" + gemm.rstrip() + "\n" + MID_SILU + farc.rstrip() + "\n\n"
            + exch.rstrip() + "\n" + BACK + wrappers())


def main():
    text = derive()
    if "--check" in sys.argv:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        if cur != text:
            print("moe_macfn7.hip differs from the derivation (re-run tools/gen_macfn7_back.py)")
            sys.exit(1)
        print("moe_macfn7.hip == the derivation")
        return
    open(OUT, "w").write(text)
    print(f"wrote {OUT} ({len(text)} bytes)")


if __name__ == "__main__":
    main()
