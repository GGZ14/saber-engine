BACK = r"""
// ================================================================ MACFN7: the fused MACaQ back half (TP=2 half)
// FN80b-1's `moe_back_h2_impl` / FN137's `moe_back_h2_far_impl` control flow with the MACaQ bodies. `sync` (i32, zero
// at allocation, zero again after every launch): FN26's words ([0] ticket [1] gate flag [2] combine slices done
// [3, 23) down n-block arrivals, then per tile gate_up arrivals / silu flag / down arrivals) + (TK) the token rows'
// count at [23 + 3 tc]. Grid: 1 + (TK ? T : 0) + tc * 5 * KSG + tc * 20 * KSD workgroups of 256 (1-D). T <= 64.
// A / As = the token int8 rows + scales (written by tickets 1..T under TK, read by every gate_up workgroup after its
// first W slab is in flight); Q / QS = the down input; tsh = the layer's gate_up t (TK only).
template <int KSG, int KSD, bool TK, int FMODE>
__device__ __forceinline__ void macfn7_back_impl(
    signed char *__restrict__ A, float *__restrict__ As,
    const unsigned long long *__restrict__ xgu, const unsigned long long *__restrict__ xdn,
    const int *__restrict__ tile_expert, const int *__restrict__ tile_row0,
    const int *__restrict__ tile_rows, const int *__restrict__ row_tok,
    const int *__restrict__ meta, int *__restrict__ Pgu, int *__restrict__ Pdn,
    int *__restrict__ cgu, int *__restrict__ cdn, __bf16 *__restrict__ GU,
    signed char *__restrict__ Q, float *__restrict__ QS, __bf16 *__restrict__ Y,
    const float *__restrict__ topk_w, const int *__restrict__ route_pos,
    const __bf16 *__restrict__ wsg, const __bf16 *__restrict__ bi, __bf16 *__restrict__ sg,
    __bf16 *__restrict__ out, int *__restrict__ sync, const int T, const int Pmax,
    const int tc, const float *__restrict__ tsh, const FarArgs fa) {
  constexpr int IH = 320, NBG = 2 * IH / 128, NBD = 2560 / 128, K = 2560;
  __shared__ int s_v, s_f0, s_f1, s_sl;
  const int tid = threadIdx.x;
  int *const tk = sync, *const sgf = sync + 1, *const cdone = sync + 2, *const nbc = sync + 3;
  int *const gdone = sync + 3 + NBD, *const sready = gdone + tc, *const ddone = sready + tc;
  int *const tokc = ddone + tc;
  if (tid == 0) {
    const int v = atomicAdd(tk, 1);
    if (v == (int)gridDim.x - 1) *tk = 0;   // every ticket is taken: the counter is free again
    s_v = v;
  }
  __syncthreads();
  const int v = __builtin_amdgcn_readfirstlane(s_v);
  const int ntile = meta[0];
  if (v == 0) {
    // The shared-expert gate logit: FN5's band at ONE split (the engine's `fn_bgemm_sk_m16`, M 1 =
    // the gate row, N = T = the block input's rows); waves 4..7 own columns >= 64 > T: idle.
    moe_x_bgemm_sk_body<16>(wsg, bi, nullptr, nullptr, sg, 1, T, 2560, 0, 0, 0, 1, 1, &s_sl,
                            mx_nobar{});
    __syncthreads();
    __threadfence();
    unsigned fs = 0;
    if constexpr (FMODE >= 0) fs = far_call_begin(fa);   // FN137: the call index, before `sgf`
    if (ntile == 0) {   // no expert rows on this rank: the combine is its (all-remote) zero sum
      if constexpr (TK) {   // the token rows still ran: wait them out, then free their count
        if (tid == 0) {
          while (__hip_atomic_load(tokc, __ATOMIC_ACQUIRE, __HIP_MEMORY_SCOPE_AGENT) < T)
            __builtin_amdgcn_s_sleep(2);
          *tokc = 0;
        }
        __syncthreads();
      }
      for (int nb = 0; nb < NBD; ++nb) {
        mx_combine_slice(nb, T, Y, topk_w, route_pos, sg, meta, out);
        if constexpr (FMODE >= 0) far_exchange<FMODE>(nb, T, out, fa, fs);   // FN137
      }
      return;
    }
    if (tid == 0) __hip_atomic_store(sgf, 1, __ATOMIC_RELEASE, __HIP_MEMORY_SCOPE_AGENT);
    return;
  }
  int u = v - 1;
  if constexpr (TK) {
    if (u < T) {   // one token row a ticket: `macfn3_tok_hadi8_t256`'s body
      m7_tok_row(bi, tsh, A, As, K, u);
      __syncthreads();
      if (tid == 0) {
        __threadfence();
        atomicAdd(tokc, 1);
      }
      return;
    }
    u -= T;
  }
  const int NGU = tc * NBG * KSG;
  if (u < NGU) {
    const int tile = u / (NBG * KSG), rem = u - tile * (NBG * KSG);
    const int nb = rem / KSG, ks = rem - nb * KSG;
    if (tile >= ntile) return;
    auto wait_tok = [&]() {
      if constexpr (TK) {
        if (tid == 0)
          while (__hip_atomic_load(tokc, __ATOMIC_ACQUIRE, __HIP_MEMORY_SCOPE_AGENT) < T)
            __builtin_amdgcn_s_sleep(2);
        __syncthreads();
        __threadfence();
      }
    };
    m7_i4_impl<8, KSG, 1, true, true, false>(A, xgu, tile_expert, tile_row0, tile_rows, row_tok, meta, As, Pgu,
                                             cgu, GU, 2 * IH, K, Pmax, nb, tile, ks, NBG, wait_tok);
    __syncthreads();
    if (tid == 0) {
      __threadfence();
      s_f0 = atomicAdd(&gdone[tile], 1) == NBG * KSG - 1;
    }
    __syncthreads();
    if (!s_f0) return;
    __threadfence();                                   // acquire: every n-block's gu rows
    if (tid == 0) gdone[tile] = 0;
    const int row0 = tile_row0[tile], M = tile_rows[tile];
    const float *__restrict__ tdn = (const float *)(uintptr_t)xdn[3 * (size_t)tile_expert[tile] + 2];
    for (int m = tid >> 5; m < M; m += 8) m7_silu_row_wave(row0 + m, GU, tdn, Q, QS, IH);
    __syncthreads();
    if (tid == 0) {
      __threadfence();
      __hip_atomic_store(&sready[tile], 1, __ATOMIC_RELEASE, __HIP_MEMORY_SCOPE_AGENT);
    }
    return;
  }
  u -= NGU;
  const int tile = u / (NBD * KSD), rem = u - tile * (NBD * KSD);
  const int nb = rem / KSD, ks = rem - nb * KSD;
  if (tile >= ntile) return;
  auto wait_silu = [&]() {
    if (tid == 0)
      while (__hip_atomic_load(&sready[tile], __ATOMIC_ACQUIRE, __HIP_MEMORY_SCOPE_AGENT) == 0)
        __builtin_amdgcn_s_sleep(2);
    __syncthreads();
    __threadfence();
  };
  m7_i4_impl<4, KSD, 1, false, true, false>(Q, xdn, tile_expert, tile_row0, tile_rows, row_tok, meta, QS, Pdn, cdn,
                                            Y, 2560, IH, Pmax, nb, tile, ks, NBD, wait_silu);
  __syncthreads();
  if (tid == 0) {
    __threadfence();
    s_f0 = atomicAdd(&ddone[tile], 1) == NBD * KSD - 1;
    s_f1 = atomicAdd(&nbc[nb], 1) == ntile * KSD - 1;
    if (s_f0) {                                        // every down workgroup of the tile passed
      sready[tile] = 0;
      ddone[tile] = 0;
    }
  }
  __syncthreads();
  if (!s_f1) return;
  __threadfence();                                     // acquire: every tile's Y columns of nb
  if (tid == 0) {
    nbc[nb] = 0;
    while (__hip_atomic_load(sgf, __ATOMIC_ACQUIRE, __HIP_MEMORY_SCOPE_AGENT) == 0)
      __builtin_amdgcn_s_sleep(2);
  }
  __syncthreads();
  __threadfence();
  mx_combine_slice(nb, T, Y, topk_w, route_pos, sg, meta, out);
  if constexpr (FMODE >= 0) far_exchange<FMODE>(nb, T, out, fa, far_call_read(fa));   // FN137
  if (tid == 0 && atomicAdd(cdone, 1) == NBD - 1) {    // the last slice: the gate flag (+ token count) is free
    *cdone = 0;
    if constexpr (TK) *tokc = 0;
    __hip_atomic_store(sgf, 0, __ATOMIC_RELAXED, __HIP_MEMORY_SCOPE_AGENT);
  }
}
"""

