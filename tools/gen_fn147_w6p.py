#!/usr/bin/env python3
"""FN147: the W6P (MXFP6 e2m3 g32) PREFILL tile -- FN61e's `t8p_impl` prefill cell with FN146's MXFP6
B (tools/capture/fn147/w6p.hip.in, self-contained: its helpers are FN146's ops verbatim, renamed).

  fn147_w6p_<f>_p<MF>h<MH>w<NW>u<UNP>s<SB>_ldc(a, w6, as, s6, c, m, n, k, ldc)
      = fn_t8p_a8w8_p4w8_ldc's arguments and grid (x = cdiv(m, 16 MF) row tiles FASTEST, y = n / 16 NW,
        16 NW x 32 threads) with `ws` -> the e8m0 group scales [N][K/32] and W -> W6P / E4 blocks;
      f = w6 (W6P) | e4 (the e4m3 dequant twin = the oracle) | w6x (the exchanged-rotates control)

  tools/gen_fn147_w6p.py --probe OUT.hip   (every probe arm)
  tools/gen_fn147_w6p.py [--check]         (the would-be shipped object flashnext_w6p147.hip: NOT written
                                           this round -- the phase-3 engine arm is a later round)
"""
import argparse
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BODY = os.path.join(ROOT, "tools/capture/fn147/w6p.hip.in")
FORMS = {"w6": (6, "false"), "e4": (8, "false"), "w6x": (6, "true")}
# (MF, MH, NW, UNP, SB): the shipped geometry p4w8 first, then the amortization / unpack-placement /
# group-fence arms
# (SB 0 = no group fence: every form spilled 600-2,400 B at 256 VGPRs; MF 6 / 8 spill under SB 1 too:
# 188 / 528 B -- measured at build, dropped)
PROBE = [(4, 4, 8, 1, 1), (4, 4, 8, 0, 1), (4, 4, 4, 1, 1), (2, 2, 8, 1, 1), (4, 2, 8, 1, 1)]
SHIP = [(4, 4, 8, 1, 1)]
OUT = os.path.join(ROOT, "crates/saber-kernels/hip/flashnext_w6p147.hip")

HEADER = """\
// GENERATED by tools/gen_fn147_w6p.py from tools/capture/fn147/w6p.hip.in -- do not edit; re-run the script.
"""
SYM = """
extern "C" __global__ __launch_bounds__({nt}) void fn147_w6p_{f}_p{mf}h{mh}w{nw}u{unp}s{sb}_ldc(
    const unsigned char *__restrict__ a, const unsigned char *__restrict__ w6, const float *__restrict__ as,
    const unsigned char *__restrict__ s6, __bf16 *__restrict__ c, int m, int n, int k, int ldc) {{
  fn147_w6p_impl<{form}, {mf}, {mh}, {nw}, {rotx}, {unp}, {sb}>(a, w6, as, s6, c, m, n, k, (long)ldc);
}}
"""


def derive(cells, forms):
    out = HEADER + open(BODY).read()
    for (mf, mh, nw, unp, sb) in cells:
        for f in forms:
            form, rotx = FORMS[f]
            out += SYM.format(nt=nw * 32, f=f, mf=mf, mh=mh, nw=nw, unp=unp, sb=sb, form=form, rotx=rotx)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--probe", default="")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    if a.probe:
        open(a.probe, "w").write(derive(PROBE, ("w6", "e4", "w6x")))
        return 0
    txt = derive(SHIP, ("w6",))
    if a.check:
        ok = os.path.exists(OUT) and open(OUT).read() == txt
        print("flashnext_w6p147.hip", "up to date" if ok else "STALE (not written: no engine arm yet)")
        return 0 if ok else 1
    open(OUT, "w").write(txt)
    return 0


if __name__ == "__main__":
    sys.exit(main())
