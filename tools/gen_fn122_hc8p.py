def derive(src):
    body = g108.derive(src)
    body = body[body.index("#include <hip/hip_runtime.h>"):]
    qbody = derive_q(body) + derive_x(body) + FBODY + derive_q(body, src) + DEQ
    # drop every flashnext_hc8 instantiation line (the macros stay)
    keep = []
    for ln in body.splitlines(keepends=True):
        if ln.startswith(("FN8_DOWN2_CFG(", "FN8_DOWN2D_CFG(", "FN8_UP2S(", "FN8_UP2P(")):
            continue
        keep.append(ln)
    body = "".join(keep)
    assert 'extern "C"' not in body.replace('extern "C" __global__ __launch_bounds__', ""), \
        "an instantiated symbol survived"
    rows = ["\n// ============================================================================ FN122b: the prefill tiles\n",
            "// cfg m<MF>w<NW>t<T>k<KC>: (MF, NW, T, KC, PF); G = 21 / (NW x T) column groups = 1\n"]
    for cfg, mf, nw, t, kc, pf in DOWN_CFGS:
        assert nw * t >= 21 and 2560 % kc == 0 and (kc // 16) % pf == 0, cfg
        lds = 2 * 16 * mf * (kc + 8) * 2 + 2 * 16 * mf * 4
        assert lds <= 65536, (cfg, lds)
        rows.append(f"FN8_DOWN2_CFG({cfg}, {mf}, {nw}, {t}, {kc}, {pf})\n")
    for cfg, mf, nw, t, kc, pf, pipe, xh in DOWNQ_CFGS:
        assert nw * t >= 21 and 2560 % kc == 0 and (kc // 16) % pf == 0, cfg
        rows.append(f"FN8_DOWN2Q_CFG({cfg}, {mf}, {nw}, {t}, {kc}, {pf}, {pipe}, {xh})\n")
    for cfg, mf, nw, swap, tab in UP_CFGS:
        rows.append(f"FN8_UP2P({cfg}, {mf}, {nw}, {swap}, {tab})\n")
    for cfg, mf, nw, la, ring, tab in UPX_CFGS:
        lds = (2 * 16 * mf * (320 + 8) if la else 0) + (7336 * 4 if tab == "true" else 0) + nw * 16 * mf * 4
        assert lds <= 65536, (cfg, lds)
        rows.append(f"FN8_UP2X_CFG({cfg}, {mf}, {nw}, {la}, {ring}, {tab})\n")
    for cfg, mf, nw, kc, pf in DOWNF_CFGS:
        assert nw >= 21 and 2560 % kc == 0 and (kc // 16) % pf == 0, cfg
        rows.append(f"FN8_DOWN2F_CFG({cfg}, {mf}, {nw}, {kc}, {pf})\n")
    for cfg, mf, nw, t, kc, pf, pipe, xh in DOWNQB_CFGS:
        rows.append(f"FN_DOWN2QB_CFG({cfg}, {mf}, {nw}, {t}, {kc}, {pf}, {pipe}, {xh})\n")
    return HEADER + body + qbody + QMACROS + XMACROS + FMACROS + QBMACROS + "".join(rows)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    out = derive(open(g108.SRC).read())
    if a.check:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        if cur != out:
            print(f"{OUT}: STALE (re-run tools/gen_fn122_hc8p.py)")
            return 1
        print("flashnext_hc8p.hip: current")
        return 0
    open(OUT, "w").write(out)
    print(f"wrote {OUT} ({len(out.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
