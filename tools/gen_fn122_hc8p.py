DEQ = r"""
// ---- FN122c: an hc8 record -> the bf16 matrix its `_h8` symbols multiply, bf16(f32(code) x scale)
// (fn8_deq, the same ops): record = e4m3 codes [rows, cols] then f32 scales [rows, cols / G]; one
// thread = 8 codes. A mix's dequantized matrix feeds the bf16 parent (FN108's gate: equal bytes).
extern "C" __global__ __launch_bounds__(256) void fn122_hc8_dequant(
    const unsigned char *__restrict__ rec, __bf16 *__restrict__ out, int rows, int cols, int g) {
  const long i = (long)blockIdx.x * 256 + threadIdx.x;
  const long n8 = (long)rows * cols / 8;
  if (i >= n8) return;
  const long e = i * 8, r = e / cols, c = e - r * cols;
  const uint2 v = *(const uint2 *)(rec + e);
  const float sc = ((const float *)(rec + (long)rows * cols))[r * (cols / g) + c / g];
  *(bf16x8 *)(out + e) = fn8_deq(v.x, v.y, sc);
}
"""

