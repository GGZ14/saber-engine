#!/usr/bin/env python3
"""FN141: derive crates/saber-kernels/hip/flashnext_hc141.hip (code object `flashnext_hc141`) -- the
fp8-mixer HC UP at the decode cfg s1d with every load issued at entry + the one-round q8 tail --
from the shipped `flashnext_hc8.hip`'s helpers and bodies (VERBATIM up to its symbol section; no
symbol of the parent is re-emitted) + tools/capture/fn141/up141.hip.in (the probe's body).

  fn141_up_{bf16,q8}_v2_s1d_h8  = fn_hc_up_{bf16,q8}_v2_s1d_h8's arguments, grid and block (128)
Built with -ffp-contract=off and saber-dev:rocm714 (the parent's row).

  tools/gen_fn141_hc141.py [--check] [--probe OUT.hip]   (--probe adds the TAIL=0 arm fn141_up_q8b_*)
"""
import argparse
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "crates/saber-kernels/hip/flashnext_hc8.hip")
BODY = os.path.join(ROOT, "tools/capture/fn141/up141.hip.in")
OUT = os.path.join(ROOT, "crates/saber-kernels/hip/flashnext_hc141.hip")

HEADER = """\
// GENERATED by tools/gen_fn141_hc141.py from flashnext_hc8.hip + tools/capture/fn141/up141.hip.in
// -- do not edit; re-run the script.
//
// Flash-Next (FN141): the fp8-mixer HC UP at the decode cfg s1d, every load at entry + the one-round
// q8 tail. `fn141_up_<kind>_v2_s1d_h8` takes `fn_hc_up_<kind>_v2_s1d_h8`'s arguments and grid and
// writes the same bytes. Built with -ffp-contract=off (the parent's row), saber-dev:rocm714.
"""

SYM = """
extern "C" __global__ __launch_bounds__(128) void {name}(
    const __bf16 *__restrict__ hid, const float *__restrict__ rr, const __bf16 *__restrict__ nw,
    const __bf16 *__restrict__ lora, const unsigned char *__restrict__ wup, __bf16 *__restrict__ bi,
    unsigned char *__restrict__ q8, float *__restrict__ scale, float *__restrict__ amax,
    int *__restrict__ cnt, __bf16 *__restrict__ gdbg, int m) {{
  fn141_up_body<{quant}, {tail}, {nn}, {mf}>(hid, rr, nw, lora, wup, bi, q8, scale, amax, cnt, m);
}}
"""
BG = """
extern "C" __global__ __launch_bounds__(128) void fn141_bgemm_sk_m16_d{d}{suf}(
    const __bf16 *__restrict__ a, const __bf16 *__restrict__ w, float *__restrict__ part,
    int *__restrict__ cnt, __bf16 *__restrict__ c, int m, int n, int k) {{
  fn141_bgemm_sk16_body<{d}, {k80}>(a, w, part, cnt, c, m, n, k);
}}
"""
SHIP_BG = ((16, 1),)
PROBE_BG = ((16, 0), (16, 1), (20, 1), (40, 1))
SHIP = (("fn141_up_bf16_v2_s1d_h8", 0, 1, 1, 1), ("fn141_up_q8_v2_s1d_h8", 1, 1, 1, 1))  # NN (hc8_up_scale_law.py)
PROBE = SHIP + (("fn141_up_q8b_v2_s1d_h8", 1, 0, 0, 1), ("fn141_up_bf16n_v2_s1d_h8", 0, 1, 1, 1),
                ("fn141_up_q8n_v2_s1d_h8", 1, 1, 1, 1), ("fn141_up_bf16_v2_m2d_h8", 0, 1, 0, 2),
                ("fn141_up_q8_v2_m2d_h8", 1, 1, 0, 2), ("fn141_up_bf16n_v2_m2d_h8", 0, 1, 1, 2),
                ("fn141_up_q8n_v2_m2d_h8", 1, 1, 1, 2))


def derive(syms, bgs):
    s = open(SRC).read()
    end = s.index("// ============================================================================ FN108: the symbols")
    prefix = s[:end]
    assert 'extern "C"' not in prefix, "the parent's helpers carry a symbol"
    lines = prefix.split("\n")
    k = 0
    while lines[k].startswith("//"):
        k += 1
    prefix = "\n".join(lines[k:])
    return HEADER + prefix + open(BODY).read() + "".join(SYM.format(name=n, quant=q, tail=t, nn=x, mf=f) for n, q, t, x, f in syms) + "".join(BG.format(d=d, k80=k, suf="k80" if k else "") for d, k in bgs)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--probe", default="")
    a = ap.parse_args()
    if a.probe:
        open(a.probe, "w").write(derive(PROBE, PROBE_BG))
        return 0
    txt = derive(SHIP, SHIP_BG)
    if a.check:
        ok = os.path.exists(OUT) and open(OUT).read() == txt
        print("flashnext_hc141.hip", "up to date" if ok else "STALE")
        return 0 if ok else 1
    open(OUT, "w").write(txt)
    return 0


if __name__ == "__main__":
    sys.exit(main())
