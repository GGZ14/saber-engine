#!/usr/bin/env python3
"""CMP27AE: generate `crates/saber-kernels/hip/mxfp4_gemm_decode_arw.hip` -- the N 5120 dwn4 decode
GEMM with the wht6 two-rank all-reduce as its tile epilogue (CMP27AB's probe body, engine protocol).

The GEMM is the SHIPPED prefetch decode body (`hip/mxfp4_gemm_decode_pf.hip`), copied verbatim from
the template line through the split-K election (`cnt[bx_] = 0`): same slabs, WMMA order, partials,
election. The epilogue (`tools/capture/cmp27ae/arw_epilogue.inc`) folds the two partials with the
shipped fold's expression and runs the shipped wht6 per-group arithmetic
(`tools/capture/cmp27ae/arw_helpers.inc`, `saber_ar_wht_wpar.hip`'s rotation, amax, bf16 scale, RTNE
6-bit symbols, dequant-add, inverse rotation, contraction off) on the tile's own 64-element groups.

Usage: gen_cmp27ae_arw.py [--check]   (from the repo root)"""
import sys

PF = "crates/saber-kernels/hip/mxfp4_gemm_decode_pf.hip"
OUT = "crates/saber-kernels/hip/mxfp4_gemm_decode_arw.hip"
HEADER = """// GENERATED by tools/gen_cmp27ae_arw.py from hip/mxfp4_gemm_decode_pf.hip (the shipped prefetch
// decode body through its split-K election, verbatim) + tools/capture/cmp27ae/arw_{helpers,epilogue}.inc.
// Do not edit: re-run the generator (`--check` proves this file current).
// CMP27AE: the N 5120 dwn4 decode GEMM whose last split-K arriver of every 64-column tile runs the
// rotated (wht6) two-rank all-reduce of the tile's own rotation groups (one group a row at DWN 4)
// and stores the reduced bf16 rows to `out` -- one launch for `GEMM -> allreduce_wht` (LEDGER
// CMP27AB: 0 of 360 cases differ from the shipped GEMM + wpar reduce in output, symbols and scales).
"""


def generate():
    src = open(PF).read().split("\n")
    i0 = next(i for i, l in enumerate(src) if l.startswith("template <int DWN, int DBK, int DTM, bool NT>"))
    i1 = next(i for i, l in enumerate(src) if "if (tid == 0) cnt[bx_] = 0;" in l)
    head = src[:i0]
    body = "\n".join(src[i0:i1 + 1])
    old_name = "cmp27e_decode_pf_impl("
    old_sig = "const int DKS, const int bx_, const int bz_) {"
    assert body.count(old_name) == 1 and body.count(old_sig) == 1, "anchors moved in " + PF
    body = body.replace(old_name, "cmp27ae_arw_impl(", 1)
    body = body.replace(
        old_sig,
        "const int DKS, const int bx_, const int bz_,\n"
        "    char* peer_scratch, const char* my_scratch, __hip_bfloat16* __restrict__ out,\n"
        "    unsigned int* peer_flags, unsigned int* my_flags, unsigned int* seq_ctrs,\n"
        "    long slot_stride_bytes, long fuse_off, int drain, int acq) {", 1)
    helpers = open("tools/capture/cmp27ae/arw_helpers.inc").read()
    ep = open("tools/capture/cmp27ae/arw_epilogue.inc").read()
    return HEADER + "\n".join(head) + "\n" + helpers + "\n" + body + "\n" + ep


text = generate()
if "--check" in sys.argv[1:]:
    cur = open(OUT).read()
    if cur != text:
        sys.exit(f"{OUT} is NOT current: re-run tools/gen_cmp27ae_arw.py")
    print(f"{OUT}: current")
else:
    open(OUT, "w").write(text)
    print(f"wrote {OUT}")
