import sys

HIPD = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                     "..", "crates", "saber-kernels", "hip"))
RTE = os.path.join(HIPD, "moe_route.hip")
HCS = os.path.join(HIPD, "flashnext_hc.hip")
BEGIN = "// ---- FN31 front (GENERATED by tools/gen_moe_front.py -- do not edit) ----\n"
END = "// ---- end FN31 front ----\n"
V2_END = "// ---- end FN26 v2 ----\n"
HEAD = 'extern "C" __global__ __launch_bounds__(MOE_THREADS) void moe_route_topk10_sort_e512(\n'

# (NW waves a workgroup, loop, n): "u" = the band's own loop at FB_UNR = n (u8 = the shipped band's
# schedule), any split; "s" = the slice FULLY UNROLLED at split n (K 2,560: 40 / 80 / 160 k-steps at
# splits 4 / 2 / 1), so the compiler keeps as many steps in flight as registers allow and the
# waitcnt pass counts exactly (no loop back-edge to merge at).
FRONT_CELLS = [(4, "u", 8), (4, "u", 20)] + [(nw, "s", sp) for sp in (4, 2, 1) for nw in (4, 8)]
# FN49a: the routed cells again with the route's xor butterflies on DPP / v_permlanex16 (`_dpp`).
DPP_CELLS = [(8, "s", sp) for sp in (4, 2, 1)]


def die(msg):
    sys.exit(f"gen_moe_front: {msg} -- re-derive by hand, do not guess")


def cut(text, a, b, what):
    if text.count(a) != 1:
        die(f"anchor `{what}` start found {text.count(a)}x")
    i = text.index(a)
    j = text.index(b, i) if b else len(text)
    return text[i:j]


# The fully unrolled slice (FN31): the SAME chain -- acc = wmma(a_k, w_k, acc) for k = 0, 1, ... of
# the slice, the band's operand addresses -- with the trip count a compile-time constant (the
# slice's k-steps at one split of K 2,560), so the scheduler issues loads as far ahead as registers
# allow and no loop back-edge makes the waitcnt pass drain. A launch whose slice is not KST steps
# traps.
PIPE_LOOP = """  if (live && ksteps != KST) __builtin_trap();
  if (ksteps > 0) {
#pragma unroll
    for (int ks = 0; ks < KST; ++ks) {
      mf_bf16x8 af[MF], wf;
#pragma unroll
      for (int mf = 0; mf < MF; ++mf) af[mf] = *(const mf_bf16x8 *)(ap[mf] + ks * 16);
      wf = *(const mf_bf16x8 *)(wp + ks * 16);
#pragma unroll
      for (int mf = 0; mf < MF; ++mf) acc[mf] = mf_vg_wmma(af[mf], wf, acc[mf]);
    }
  }
"""


def derive_band():
    hc = open(HCS).read()
    band = cut(hc, "template <int MROWS>\n__device__ __forceinline__ void fn_bgemm_sk_body(",
               "#define FN_BGEMM_SK(NAME, MROWS)", "fn_bgemm_sk_body")
    box = [band]

    def sub(old, new, what, count=1):
        n = box[0].count(old)
        if n != count:
            die(f"band anchor `{what}` found {n}x in {HCS} (want {count})")
        box[0] = box[0].replace(old, new)

    sub("template <int MROWS>\n__device__ __forceinline__ void fn_bgemm_sk_body(",
        "template <int MROWS, int FB_NW, int FB_UNR>\n"
        "__device__ __forceinline__ void mf_bgemm_sk_part(", "name")
    sub("                                                 float *__restrict__ part, int *__restrict__ cnt,\n"
        "                                                 __bf16 *__restrict__ c, int m, int n, int k) {",
        "                                                 float *__restrict__ part, int m, int n, int k) {",
        "signature")
    sub("  __shared__ int s_last;\n", "", "s_last")
    for old, new in (("bf16x8", "mf_bf16x8"), ("floatx8", "mf_floatx8"), ("vg_wmma(", "mf_vg_wmma(")):
        box[0] = box[0].replace(old, new)
    # The tail: the band's partial store (verbatim), for every split count -- no one-slice direct
    # store and no in-band reduce (the route's phase 1 runs the band's reduce expression).
    body = box[0]
    head = body[:body.index("  const int col = n0 + (lane & 15);\n")]
    store = cut(body, "  if (live && col < n) {\n", "  __syncthreads();\n", "partial store")
    if "part[((long)sp * m + r) * n + col] = acc[mf][e];" not in store:
        die("the partial store moved")
    reduce_ = ("    float v = part[(long)r * n + cc];\n"
               "    for (int p = 1; p < nsp; ++p) v = v + part[((long)p * m + r) * n + cc];\n"
               "    c[(long)r * n + cc] = (__bf16)v;\n")
    if reduce_ not in body:
        die("the band's slice reduce moved")
    for dead in ("__shared__", "cnt[", "s_last"):
        if dead in head + store:
            die(f"`{dead}` survived the band derivation")
    loop = cut(head, "  int ks = 0;\n", None, "the k loop")
    if not loop.startswith("  int ks = 0;\n  for (; ks + FB_UNR <= ksteps; ks += FB_UNR) {\n"):
        die("the band's k loop moved")
    for a in ("af[mf][u] = *(const mf_bf16x8 *)(ap[mf] + (ks + u) * 16);",
              "wf[u] = *(const mf_bf16x8 *)(wp + (ks + u) * 16);",
              "for (int mf = 0; mf < MF; ++mf) acc[mf] = mf_vg_wmma(af[mf][u], wf[u], acc[mf]);"):
        if a not in loop:
            die(f"the band's k loop lost `{a}`")
    tail = "  const int col = n0 + (lane & 15);\n" + store + "}\n"
    pipe = (head[:head.index("  int ks = 0;\n")]
            .replace("template <int MROWS, int FB_NW, int FB_UNR>\n__device__ __forceinline__ void mf_bgemm_sk_part(",
                     "template <int MROWS, int FB_NW, int KST>\n__device__ __forceinline__ void mf_bgemm_sk_full(")
            + PIPE_LOOP + tail)
    return head + tail, pipe


def derive_route(src):
    base = src[src.index(HEAD):src.index("// The weighted combine.")]
    exscan = cut(src, "static __device__ __forceinline__ int block_exscan(", "\nextern \"C\"", "exscan")
    ex = exscan.replace("static __device__ __forceinline__ int block_exscan(",
                        "template <int NT>\nstatic __device__ __forceinline__ int mf_exscan(")
    if ex.count("MOE_THREADS") != 1:
        die("block_exscan's thread count")
    ex = ex.replace("MOE_THREADS", "NT")
    load = cut(base, "    float p[16];\n", "    float mx = p[0];\n", "phase-1 load")
    arith = cut(base, "    float mx = p[0];\n", "  __syncthreads();\n\n  // ---- phase 2", "phase-1 arithmetic")
    if not arith.endswith("      s_ids[tl * MOE_TOPK + lane] = iv;\n    }\n  }\n"):
        die("phase-1 tail")
    arith = arith[:-len("  }\n")]     # the token loop's brace is ours
    for a in ("mx = fmaxf(mx, __shfl_xor(mx, o, 32));", "p[j] = saber_exp_nonpos(p[j] - mx); s = s + p[j];",
              "const float inv = 1.f / s;", "if (ov > bv || (ov == bv && oi < bi)) { bv = ov; bi = oi; }",
              "const float scale = 1.f / (sel > 0.f ? sel : 1.f);",
              "topk_w[(size_t)t * MOE_TOPK + lane] = wv * scale;"):
        if a not in arith:
            die(f"phase 1 lost `{a}`")
    scans = cut(base, "  // Padded rows and tiles per expert, scanned: two experts per thread (e_loc <= 512).\n",
                "  const int sh_row0 = rows_total;\n", "scans")
    for old, new, n in (("h < 2", "h < MF_EPT", 2), ("2 * tid + h", "MF_EPT * tid + h", 2),
                        ("block_exscan(", "mf_exscan<NT>(", 4),
                        ("two experts per thread (e_loc <= 512)", "MF_EPT experts per thread", 1)):
        if scans.count(old) != n:
            die(f"scan anchor `{old}` found {scans.count(old)}x (want {n})")
        scans = scans.replace(old, new)
    tail = cut(base, "  const int sh_row0 = rows_total;\n", "  // Placement:", "meta / tiles / pads")
    if tail.count("MOE_THREADS") != 3:
        die("meta / tiles / pads thread strides")
    tail = tail.replace("MOE_THREADS", "NT")
    return ex, load, arith, scans, tail


