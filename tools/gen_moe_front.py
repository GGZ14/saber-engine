#!/usr/bin/env python3
"""FN31: append the MoE block's FRONT HALF to `moe_route.hip`, DERIVED from the shipped kernels.

The shipped front half is two launches (EXEC section 11): the router GEMM (FN5's split-K band
`fn_bgemm_sk_m16`, N 512, K 2,560, split 4 / 2 / 1 by the rules `moe.router` row) and the route
(`moe_route_topk10_sort_e512`, FN4's law). This deriver writes three things after FN26's v2 block:

  moe_route_topk10_sort_e512_lds  the route with its whole step in ONE workgroup and every table it
                                  builds in LDS (T <= 64): phase 1 = FN4's per-token arithmetic
                                  verbatim on v2's interleaved map; the per-expert counts and each
                                  route's rank from a 64-bit token mask per expert (popcount below the
                                  token = the number of earlier tokens routed to that expert = FN4's
                                  (earlier workgroups' count + in-workgroup rank), integers, exact);
                                  phase 3 = FN4's scans / tiles / pads / placement verbatim with the
                                  thread stride a parameter. SIG_MOE_ROUTE (drop-in: `blk_cnt`,
                                  `rank`, `arrive` are not touched; workgroups past the first exit).
  moe_front_e512_nw{NW}_{u,s}{n}  the router GEMM and the route as ONE launch: FN5's band body
                                  (`fn_bgemm_sk_body`) derived verbatim -- the same wave per 16
                                  columns walking its K slice in ascending 16-k steps into one fp32
                                  accumulator, the same slice partition (grid z) -- either the band's
                                  own k loop at FB_UNR = n (`u`; u8 = the shipped schedule) or the
                                  slice fully unrolled at split n (`s`, PIPE_LOOP), and `NW`
                                  waves a workgroup; every workgroup stores its fp32 partial slice; the LAST
                                  arriving workgroup (one arrival counter, the split-K reduce's
                                  pattern, back to zero after every launch) runs the LDS route, and
                                  its phase 1 sums each token's slices in slice order and rounds to
                                  bf16 with the band's own reduce expression -- the logits the
                                  shipped band writes, written too -- before FN4's arithmetic.

Nothing here decides a byte the shipped kernels do not decide the same way: the WMMA chain and the
slice reduce are the band's text, the softmax / top-10 / renorm is FN4's text, and the table
arithmetic is integer. The card gate is `tools/capture/fn31/` (every table and logit byte vs the
shipped two launches on real routes, T 1..64) + `moe_ref.py check-route` on the dumps.

  tools/gen_moe_front.py [--check]
"""
