#!/usr/bin/env python3
"""FN122c lever 3: derive crates/saber-kernels/hip/flashnext_trunk8q.hip (code object
`flashnext_trunk8q`) -- the W8 PREFILL GEMM at other tiles, ADDED symbols in a NEW object (every
shipped object untouched).

The body is FN61e's `t8p_impl` from flashnext_trunk8p.hip VERBATIM (its header, helpers and the
T8P_SIG / T8P_DEF macros), with every flashnext_trunk8p instantiation and the bf16-suffix half
dropped and new rows added. A new symbol is the same template at another (MF, MH, NW): the row
tile (16 MF rows), the row fragments a register pass (MH), the waves (NW x 16 columns). Each
output element keeps the parent's arithmetic: per 128-deep k tile a fresh chain over the eight
16-k steps in order, `acc += tile * (as * bs)` in k-tile order, one bf16 round at the store; MH
only groups which row fragments share a pass (gated byte for byte on the card, not argued).

Names: `fn_t8p_a8w8_p<MF>w<NW>m<MH>q_ldc` (the executor's W8 signature rule binds `fn_t8p_a8w8_*_ldc`).
Usage: tools/gen_fn122_t8q.py [--check]
"""
import argparse
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "crates/saber-kernels/hip/flashnext_trunk8p.hip")
OUT = os.path.join(ROOT, "crates/saber-kernels/hip/flashnext_trunk8q.hip")

# (MF, MH, NW, MFAST, NT): rows 16 MF a workgroup, MH row fragments a pass, NW waves x 16 columns,
# row tiles fastest in the grid, non-temporal weight loads. FN122c's MF >= 6 tiles spilled (t3,
# kept out); FN122d sweeps the register-lean forms of the 64-row tile.
CFGS = [(4, 2, 8, True, False), (4, 4, 8, True, True), (4, 4, 8, False, False), (2, 2, 8, True, False),
        (4, 4, 16, True, False)]

HEADER = """\
// GENERATED by tools/gen_fn122_t8q.py (FN122c) from flashnext_trunk8p.hip -- do not edit; re-run.
//
// Flash-Next (FN122c): the W8 PREFILL GEMM at other tiles, ADDED symbols in a NEW object: FN61e's
// `t8p_impl` VERBATIM at other (MF, MH, NW). Every element keeps the parent's chain; the card twin
// (tools/capture/fn122/fn122_twin.py --w8) is the law.
"""


def derive(src):
    i = src.index("#include <hip/hip_runtime.h>")
    j = src.index("// decode / verify (one row tile")
    body = src[i:j]
    assert 'extern "C"' not in body.replace('extern "C" __global__ __launch_bounds__(NW * 32) void NAME T8P_SIG', "")
    rows = ["// ============================================================ FN122c: the prefill tiles\n"]
    for mf, mh, nw, mfast, nt in CFGS:
        bm, nth = 16 * mf, 32 * nw
        assert mf % mh == 0 and (bm * 8) % nth == 0 and nth >= bm, (mf, mh, nw)
        tag = f"p{mf}w{nw}m{mh}" + ("" if mfast else "c") + ("t" if nt else "") + "q"
        rows.append(f"T8P_DEF(fn_t8p_a8w8_{tag}_ldc, {mf}, {mh}, {nw}, {str(mfast).lower()}, {str(nt).lower()})\n")
    return HEADER + body + "".join(rows)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    out = derive(open(SRC).read())
    if a.check:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        if cur != out:
            print(f"{OUT}: STALE (re-run tools/gen_fn122_t8q.py)")
            return 1
        print("flashnext_trunk8q.hip: current")
        return 0
    open(OUT, "w").write(out)
    print(f"wrote {OUT} ({len(out.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
