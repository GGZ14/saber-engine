def _sub_once(text, a, b, what):
    n = text.count(a)
    if n != 1:
        raise SystemExit(f"decode_arnq: anchor {what!r} found {n} times (want exactly 1): {a!r}")
    return text.replace(a, b)


def arnq_epilogue(saber):
    """The `_nq` epilogue of `saber_ar_exact.hip`, as a device function a GEMM block can call.

    SLICED from the committed, generated `saber_ar_exact.hip` (itself `--check`ed against the reference library by
    tools/gen_saber_sources.py): the helpers it calls and `saber_ar_oneshot_2rank_exact_nq_ssqfma_
    kernel_impl`, renamed `arnq_*` so nothing collides with this translation unit, with exactly
    five mechanical edits and no arithmetic retyped:

      1. the row is an ARGUMENT `b` (the fused kernel elects row owners by arrival order, not by
         `blockIdx.x`);
      2. the push loop is gone, and with it `peer_base` / `ps`: every GEMM tile already pushed its
         own [M x 128] piece of the row to the peer's slot before its ticket;
      3. `#pragma clang fp contract(off)` opens the epilogue's body and `arnq_vadd`'s: the saber
         code object is built `-ffp-contract=off` and this one is not, so the pragma is what keeps
         the epilogue's arithmetic the saber build's (the ssq line is an explicit fma either way);
      4. the three macros it names are re-declared from the same file's values;
      5. its three column loops are unrolled over their fixed bound (see the comment there).
    """
    defs = []
    for mac in ("SABER_AR_SPIN_MAX", "SABER_ARNQ_T", "SABER_ARNQ_MAXG"):
        hits = [ln for ln in saber.splitlines() if ln.startswith(f"#define {mac} ")]
        if len(hits) != 1:
            raise SystemExit(f"decode_arnq: `#define {mac}` not found exactly once in saber_ar_exact.hip")
        defs.append(hits[0])
    h0 = saber.index("__device__ __forceinline__ void store_sys_rel(")
    h1 = saber.index("// Multi-block one-shot all-reduce.")
    helpers = saber[h0:h1].rstrip() + "\n"
    helpers = _sub_once(helpers, "  int4 r;\n", "#pragma clang fp contract(off)\n  int4 r;\n",
                        "vadd body")
    e0 = saber.index("__device__ __forceinline__ void saber_ar_oneshot_2rank_exact_nq_ssqfma_kernel_impl(")
    e1 = saber.index('extern "C" __global__ __launch_bounds__(SABER_ARNQ_T)\n'
                   'void saber_ar_oneshot_2rank_exact_nq_ssqfma_bf16(')
    ep = saber[e0:e1].rstrip() + "\n"
    ep = _sub_once(ep,
                   "void saber_ar_oneshot_2rank_exact_nq_ssqfma_kernel_impl(\n"
                   "    const int4* __restrict__ in4, int4* peer_base, const int4* my_base,",
                   "void arnq_epilogue_impl(\n"
                   "    const int b, const int4* __restrict__ in4, const int4* my_base,",
                   "signature")
    ep = _sub_once(ep, "  const int b = blockIdx.x, tid = threadIdx.x;\n",
                   "#pragma clang fp contract(off)\n  const int tid = threadIdx.x;\n", "row index")
    ep = _sub_once(ep, "  int4* ps = peer_base + (size_t)slot * slot_stride16;\n", "", "ps")
    push = ("  {\n"
            "    int k = start + tid;\n"
            "    for (; k + 3 * SABER_ARNQ_T < end; k += 4 * SABER_ARNQ_T) {\n"
            "      int4 v0 = in4[k], v1 = in4[k + SABER_ARNQ_T], v2 = in4[k + 2 * SABER_ARNQ_T],\n"
            "           v3 = in4[k + 3 * SABER_ARNQ_T];\n"
            "      ps[k] = v0; ps[k + SABER_ARNQ_T] = v1; ps[k + 2 * SABER_ARNQ_T] = v2;\n"
            "      ps[k + 3 * SABER_ARNQ_T] = v3;\n"
            "    }\n"
            "    for (; k < end; k += SABER_ARNQ_T) ps[k] = in4[k];\n"
            "  }\n")
    ep = _sub_once(ep, push,
                   "  // (the push loop: done by the GEMM tiles, one [M x 128] piece each)\n",
                   "push loop")
    # 5. The three per-thread column loops are UNROLLED over their fixed bound (SABER_ARNQ_MAXG
    #    groups, leaving at the first `k >= end`) instead of counting `ng` / `mg` at run time.
    #    Each thread still visits the same `k`s in the same order, so every sum is the same sum;
    #    what changes is that `sv[g][j]` is indexed by constants and lives in registers. The
    #    reference's run-time index puts `sv` in PRIVATE memory (its own code object carries a
    #    176 B private segment), and a private segment on the decode GEMM would ask for scratch
    #    on every one of its waves, not just on the M owners that use it.
    #    Since ws-h42 the saber generator applies this same unroll to the served `_nq_ssqfma` impl
    #    itself (`gen_saber_sources.py::static_nq_loops`, the identical text), so the slice may
    #    arrive already unrolled; then there is nothing left to do here and the epilogue is the
    #    same bytes either way.
    already = "  int ng = 0;\n" not in ep
    if already and ep.count("#pragma unroll\n  for (int ng = 0; ng < SABER_ARNQ_MAXG; ++ng) {\n") != 1:
        raise SystemExit("decode_arnq: the slice is neither the reference's loops nor the unrolled ones")
    if not already:
        ep = _sub_once(ep, "  int ng = 0;\n", "", "ng decl")
        ep = _sub_once(ep, "  int mg = 0;\n", "", "mg decl")
        ep = _sub_once(ep, "  mg = 0;\n", "", "mg reset")
    for var, n in (() if already else (("ng", 1), ("mg", 2))):
        hdr = f"  for (int k = start + tid; k < end; k += SABER_ARNQ_T, ++{var}) {{\n"
        if ep.count(hdr) != n:
            raise SystemExit(f"decode_arnq: the {var} loop header is not there {n} time(s)")
        ep = ep.replace(hdr, "#pragma unroll\n"
                        f"  for (int {var} = 0; {var} < SABER_ARNQ_MAXG; ++{var}) {{\n"
                        f"    const int k = start + tid + {var} * SABER_ARNQ_T;\n"
                        "    if (k >= end) break;\n")
    text = helpers + "\n" + ep
    for name in ("store_sys_rel", "load_sys_acq", "rd_to_f", "rd_from_f", "vadd"):
        text = re.sub(rf"\b{name}\b", f"arnq_{name}", text)
    if "blockIdx" in text or "ps[" in text or "peer_base" in text:
        raise SystemExit("decode_arnq: the epilogue still names blockIdx / ps / peer_base")
    return "\n".join(defs) + "\n\n" + text


