# Fusion-map ROW 4 (ws-h40): the cells the served gate_up reaches. gate_up (N = 17,408 at TP=2,
# 136 n-tiles) fills the machine at DKS = 1 at every decode M, so only the DIRECT path is compiled:
# bk128 at tm1..4 and the one bk64 cell (tm4, M = 49..64; `decode_bk`).
SMQ_CELLS = ((128, 1), (128, 2), (128, 3), (128, 4), (64, 4))

# The tail `decode_smq` puts in place of the DIRECT path's `return;`, right after the tile's C
# store. Every block of the grid reaches it (DKS == 1: no split-K election, no early return).
SMQ_TAIL = r"""
    // ---- fusion-map ROW 4 (ws-h40): silu(gate) * up -> per-token e4m3, in the last M arrivals --
    // GENERATED (tools/gen_hip_sources.py::decode_smq). Everything above is the decode kernel's own
    // DIRECT path; this tile has just written its [M x 128] piece of the gate_up row C.
    //
    // PROTOCOL (the H38/H39 last-arrival pattern, one rank, no peer). (1) Every thread fences its
    //   C stores at device scope, the block meets, and tid0 takes a ticket on `tiles`, a MONOTONIC
    //   64-bit counter never reset (call c holds tickets [c*nt, (c+1)*nt), nt = gridDim.x: every
    //   call of one region has the same nt because the region is keyed by the op and N). (2) The
    //   LAST `ep_rows` (= M) arrivals are the ROW OWNERS (row = ticket index - (nt - rows)); the
    //   others return. (3) An owner's tid0 acquires `tiles` (device scope, bounded spin) until it
    //   reaches the call's end, i.e. every tile has stored and fenced; every wave then acquires
    //   and runs `silu_mul_quant`'s body for its row, verbatim (`smq_silu_mul_quant_impl`, the
    //   generated slice with `blockIdx.x` replaced by the owner's row).
    //
    // RESIDENCY / NO DEADLOCK. Only the owners wait (<= M <= 64 blocks), and they wait only on
    //   tickets of blocks that have already been dispatched or will be: a waiting owner occupies
    //   one workgroup slot, and the device holds far more than M + 1 of these workgroups at once
    //   (8 waves and 19.6 KB LDS each, 12 waves/SIMD: 6 per WGP x 32 WGPs = 192 >= the 136-tile
    //   grid, so the whole grid is co-resident at gate_up's N). Every wait is bounded.
    {
      __shared__ int s_row;
      __shared__ unsigned long long s_target;
      __threadfence();
      __syncthreads();
      const int rows_ = ep_rows < M ? ep_rows : M;
      if (tid == 0) {
        const unsigned long long nt = gridDim.x;
        const unsigned long long t = atomicAdd(tiles, 1ull);
        const unsigned long long i = t % nt;
        s_row = (i + (unsigned long long)rows_ >= nt) ? (int)(i + (unsigned long long)rows_ - nt) : -1;
        s_target = (t / nt + 1ull) * nt;
      }
      __syncthreads();
      const int row = s_row;
      if (row < 0) return;
      if (tid == 0) {
        const unsigned long long tgt = s_target;
        unsigned long long z = 0;
        while (__hip_atomic_load(tiles, __ATOMIC_ACQUIRE, __HIP_MEMORY_SCOPE_AGENT) < tgt) {
          if (++z > SMQ_SPIN_MAX) break;
        }
      }
      __syncthreads();
      __threadfence();
      smq_silu_mul_quant_impl<DWN * 32, false>(row, C, q, scale, N >> 1);
    }
    return;"""


_SRL_HDR = re.compile(
    r"^(?P<ind>[ ]*)for \(int g = tid; g < (?P<n>\w+); g \+= (?P<step>\w+), \+\+(?P<c>[nm]g)\) \{\n",
    re.M)


def static_register_loops(text, who, expect=2, bound="MAXG"):
    """The producers' STACK OBJECT, removed without touching a rounding (ws-h40, R1 backlog 8;
    generalised to every producer loop by ws-h42).

    Each producer keeps each thread's values in `float sv[MAXG][8]` (`pv` in `silu_mul_quant`)
    indexed by a RUNTIME counter (`++ng` / `++mg` in a `for (g = tid; g < NV; g += ART)` loop),
    so the compiler cannot keep the array in registers and puts it in a 176-byte private segment
    (scratch loads and stores in the loop; `docs/ISA-CENSUS.md`). Each loop below visits the same
    `g` in the same order -- `g = tid + ng * ART` while `g < NV`, and `NV <= MAXG * ART` is the
    reference's own precondition -- with a compile-time trip count, so every `sv[ng]` index is a
    constant and the array is registers. Same loads, same arithmetic, same fmaxf order, same
    stores: a byte-identical change. The counters' declarations (`int ng = 0;`, `int mg = 0;`)
    and resets (`mg = 0;`) go; `expect` is how many loop headers the text must carry (silu /
    gdn: 2; add_rms: 3).
    """
    heads = list(_SRL_HDR.finditer(text))
    if len(heads) != expect:
        raise SystemExit(f"{who}: {len(heads)} producer loop headers, expected {expect}")

    def head(m):
        ind, n, step, c = m.group("ind"), m.group("n"), m.group("step"), m.group("c")
        return (f"#pragma unroll\n{ind}for (int {c} = 0; {c} < {bound}; ++{c}) {{\n"
                f"{ind}  const int g = tid + {c} * {step};\n{ind}  if (g >= {n}) break;\n")

    text = _SRL_HDR.sub(head, text)
    for decl in ("  int ng = 0;\n", "  int mg = 0;\n", "  mg = 0;\n"):
        text = text.replace(decl, "")
    if re.search(r", \+\+[nm]g\)", text) or re.search(r"\b[nm]g = 0;", text.replace(
            "int ng = 0; ng <", "").replace("int mg = 0; mg <", "")):
        raise SystemExit(f"{who}: a run-time producer counter survived the transform")
    return text


