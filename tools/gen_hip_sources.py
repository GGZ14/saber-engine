def decode_pair(src):
    """The decode GEMM with its block index and split count as RUNTIME arguments (ws-h37).

    A mechanical rewrite of the sliced `decode_kernel`, not new arithmetic: `blockIdx.x` /
    `blockIdx.z` become the arguments `bx_` / `bz_`, the split count `DKS` moves from the template
    to an argument, and its one `if constexpr` becomes a plain `if`. Every accumulation keeps its
    order (the slab loop, the WMMA chain, the reduce's `for k < DKS` sum), which is what makes a
    PAIR of problems in one dispatch bit-identical to the two dispatches it replaces -- gated on
    the card, not asserted here. The pair: two GEMMs that read the SAME activation (A, As, M, K)
    with their own weights, split counts and outputs, one flat grid of `nb0*ks0 + nb1*ks1`
    blocks, problem 0's blocks first in the order the unpaired grid would have issued them.
    """
    body = slice_lines(src, "decode_kernel")
    subs = [
        ("template <int DWN, int DBK, int DKS, int DTM, bool WPERM, bool DIRECT = true, bool NT = false>",
         "template <int DWN, int DBK, int DTM, bool WPERM, bool DIRECT = true, bool NT = false>"),
        ("__device__ __forceinline__ void ref_mxfp4_fp8_gemm_decode_impl(",
         "__device__ __forceinline__ void ref_mxfp4_fp8_gemm_decode_rt_impl("),
        ("__bf16 *__restrict__ C, int M, int N, int K, int pb1, int pb2, long astride) {",
         "__bf16 *__restrict__ C, int M, int N, int K, int pb1, int pb2, long astride,\n"
         "    const int DKS, const int bx_, const int bz_) {"),
        ("if constexpr (DKS == 1 && DIRECT)", "if (DKS == 1 && DIRECT)"),
        ("blockIdx.x", "bx_"),
        ("blockIdx.z", "bz_"),
    ]
    for a, b in subs:
        n = body.count(a)
        if n == 0:
            raise SystemExit(f"decode_pair: anchor not found: {a!r}")
        body = body.replace(a, b)
    if "blockIdx" in body:
        raise SystemExit("decode_pair: a blockIdx survived the rewrite")
    wr = []
    for bk in (64, 128):
        for tm in range(1, 9):
            name = f"mxfp4_gemm_decode_pair_bk{bk}_tm{tm}_wperm1_nt1"
            wr.append(f"""extern "C" __global__ __launch_bounds__(DEC_DWN * 32) void {name}(
    const unsigned char *__restrict__ A, const float *__restrict__ As,
    const unsigned char *__restrict__ W0, const unsigned char *__restrict__ Ws0,
    const unsigned char *__restrict__ Wref0, float *__restrict__ P0, int *__restrict__ cnt0,
    __bf16 *__restrict__ C0,
    const unsigned char *__restrict__ W1, const unsigned char *__restrict__ Ws1,
    const unsigned char *__restrict__ Wref1, float *__restrict__ P1, int *__restrict__ cnt1,
    __bf16 *__restrict__ C1,
    int M, int K, int N0, int ks0, int nb0, int N1, int ks1, int nb1) {{
  const int b = blockIdx.x, g0 = nb0 * ks0;
  if (b < g0)
    ref_mxfp4_fp8_gemm_decode_rt_impl<DEC_DWN, {bk}, {tm}, true, true, true>(
        A, W0, Ws0, Wref0, As, P0, cnt0, C0, M, N0, K, 1 << 30, 1 << 30, 0L, ks0, b % nb0, b / nb0);
  else
    ref_mxfp4_fp8_gemm_decode_rt_impl<DEC_DWN, {bk}, {tm}, true, true, true>(
        A, W1, Ws1, Wref1, As, P1, cnt1, C1, M, N1, K, 1 << 30, 1 << 30, 0L, ks1, (b - g0) % nb1,
        (b - g0) / nb1);
}}
""")
    return ("\n// ---------------------------------------------------------------- the decode PAIR (ws-h37)\n"
            "// GENERATED from the same slice by `decode_pair` in tools/gen_hip_sources.py: see there.\n" +
            body + "\n\n" + "\n".join(wr))


# The tail `decode_arnq` appends after the fused split-K reduce's C write. Only the last-arriving
# split-K block of each n-tile reaches it (the others returned at `if (!s_last) return;`).
ARNQ_TAIL = r"""
  // ---- fusion-map ROW 3 (ws-h38): the exact 2-rank all-reduce + the `_nq` epilogue ----------
  // GENERATED (tools/gen_hip_sources.py::decode_arnq). Everything above this line is the decode
  // kernel's own text; this block has just written C for its [M x 128] tile, and C stays written:
  // it IS the reduce's local input (`in4`) and, as with `_nq`, is left holding this rank's
  // PARTIAL -- the planner only fuses when the reduce is the GEMM's one reader and the norm the
  // reduce's.
  //
  // PROTOCOL. (1) The tile pushes its piece of every row to the PEER's scratch at exactly the
  //   `_nq` layout (16 B word `slot*slot_stride16 + m*k16 + n0/8 + c16`, one int4 per thread),
  //   with `slot = (seq[m] + 1) & 1` read BEFORE anyone increments it: only a row owner
  //   increments `seq[m]`, and only after every tile has taken its ticket. (2) It drains its
  //   remote stores exactly as the reference's `drain` says (3 = s_wait_storecnt 0 on every
  //   wave), then tid0 releases at device scope and takes a ticket on `tiles`, a MONOTONIC 64-bit
  //   counter that is never reset (call c holds tickets [c*nt, (c+1)*nt), nt = gridDim.x = the
  //   n-tile count; every call of one region has the same nt because the region is keyed by the
  //   op and N; re-zeroing it between calls is also consistent). (3) The LAST `ep_rows` (= M)
  //   arrivals are the ROW OWNERS (row = ticket index - (nt - M); rules need nt >= M), the
  //   others return. An owner waits (tid0, device-scope acquire, bounded by SABER_AR_SPIN_MAX)
  //   until `tiles` reaches the call's end, so every tile of this rank has written C and pushed,
  //   then runs `_nq_ssqfma`'s body from `s_seq = atomicAdd(&seq_ctrs[b], 1) + 1` on, minus the
  //   push: release the system-scope peer flag, spin on its own, reduce `in4 (local C) + ms`
  //   (local first, the reference's operand order), residual add, Gemma RMS norm, e4m3 quant.
  //
  // ORDERING. The pushes are fine-grained remote writes, drained with s_wait_storecnt before the
  //   device-scope release of the ticket; the owner acquires the counter and then releases the
  //   system-scope peer flag. That is the posted-write ordering the reference's drain=3 relies on
  //   across the WAVES of one block, now across the CUs of one grid: every push is acknowledged
  //   before its ticket, and the flag is issued after the last ticket. `drain = 1` (every thread
  //   __threadfence_system before the ticket) is the conservative arm the same argument selects.
  //
  // NO DEADLOCK. Only the M (<= 12 in the exact band) owners spin, and each spins on its OWN
  //   rank's tiles first: the tickets after an owner's are taken by blocks already past their
  //   split-K election, i.e. running, and the grid (nt x ks = 40 x 4 at N = 5120) is resident
  //   anyway. The peer's owners wait only on the peer's own tiles and then on this rank's flag,
  //   which this rank's owners release before they wait -- no cycle. Every wait is bounded.
  //
  // CONTRACTION. This translation unit is built WITH contraction and saber is not; the epilogue
  //   carries `#pragma clang fp contract(off)` in its own body, so its arithmetic is saber's.
  __shared__ int s_row;
  __shared__ unsigned long long s_target;
  __syncthreads();
  {
    const int c16 = tid & 15, m = tid >> 4;
    if (m < M) {
      const unsigned int s_ =
          __hip_atomic_load(&seq_ctrs[m], __ATOMIC_RELAXED, __HIP_MEMORY_SCOPE_AGENT) + 1u;
      const size_t w16 = (size_t)m * k16 + (n0 >> 3) + c16;
      peer_base[(size_t)(s_ & 1u) * slot_stride16 + w16] = reinterpret_cast<const int4 *>(C)[w16];
    }
  }
  if (drain == 1) __threadfence_system();
  else if (drain == 3) asm volatile("s_wait_storecnt 0x0" ::: "memory");
  __syncthreads();
  const int rows_ = ep_rows < M ? ep_rows : M;
  if (tid == 0) {
    if (drain == 2) __threadfence_system();
    __threadfence();
    const unsigned long long nt = gridDim.x;
    const unsigned long long t = atomicAdd(tiles, 1ull);
    const unsigned long long i = t % nt;
    s_row = (i + (unsigned long long)rows_ >= nt) ? (int)(i + (unsigned long long)rows_ - nt) : -1;
    s_target = (t / nt + 1ull) * nt;
  }
  __syncthreads();
  const int row = s_row;
  if (row < 0) return;
  if (tid == 0) {
    const unsigned long long tgt = s_target;
    unsigned long long z = 0;
    while (__hip_atomic_load(tiles, __ATOMIC_ACQUIRE, __HIP_MEMORY_SCOPE_AGENT) < tgt) {
      if (++z > SABER_AR_SPIN_MAX) break;
    }
  }
  __syncthreads();
  // Every wave acquires, not only tid0's: in WGP mode a workgroup's waves may sit on either CU's
  // L0, and the C tiles the owner is about to read were written by other CUs.
  __threadfence();
  arnq_epilogue_impl(row, reinterpret_cast<const int4 *>(C), my_base, res, nw, q, scale, res_out,
                     peer_flags, my_flags, seq_ctrs, k16, slot_stride16, eps, drain, acq);
"""


