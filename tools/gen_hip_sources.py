def slice_lines(src, key):
    a, b = R[key]
    out = src[a - 1:b]
    if out and out[0].lstrip().startswith(("__global__", "template")):
        pass
    # rewrite a __global__ kernel signature into a __device__ helper
    for i, ln in enumerate(out):
        for frag, rep in GLOBAL_TO_DEVICE.items():
            if ln.startswith(frag):
                out[i] = rep + ln[len(frag):]
    return "".join(out)


def decode_syms():
    """Every (bk, ks, tm, wperm, nt, direct) the prod launcher can reach.

    launch_impl picks bk in {64,128}, ks in {1,2,4} (only the five pairs the RAD_DEC_BY_KS ladder
    can emit), tm = ceil(M/16) in 1..8, wperm/nt from the loader. NT is honoured only under WPERM
    (the row-layout path ignores it), so wperm0_nt1 does not exist.
    """
    out = []
    for wperm, nt in ((1, 1), (1, 0), (0, 0)):
        for bk, ks in ((64, 1), (128, 1), (128, 2), (64, 4), (128, 4)):
            for tm in range(1, 9):
                out.append((bk, ks, tm, wperm, nt, 1))
    # DIRECT=false at DKS=1: the reference keeps this instantiation so the "DKS==1 writes C
    # directly" fast path can be TESTED against the reduce path rather than asserted.
    out.append((128, 1, 1, 1, 1, 0))
    return out


