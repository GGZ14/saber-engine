#!/usr/bin/env python3
"""FN146: derive the MXFP6 (e2m3 g32) W6A8 decode object from the shipped `flashnext_trunk8.hip`'s
helpers (VERBATIM, every `extern "C"` symbol of the parent removed) + tools/capture/fn146/w6.hip.in.

  fn146_q8w6_sfx_<f>_n<BN>_pf<PF>_ldc  = fn86_t8_q8w8_sfx_ldc's arguments and grid (the merged GDN in /
      QSA projection: act quant in the staging + the bf16 suffix workgroups) with `ws8` -> the e8m0
      group scales (`[N][K/32]` bytes); f = w6 (W6P) | e4 (the e4m3 dequant twin = the oracle) |
      w6x (W6P with the control's exchanged rotates: must differ)
  fn146_a8w6_<f>_n64_pf<PF>_ldc        = fn111_t8_a8w8_n64_ldc's arguments and grid (out / o: A e4m3 +
      As) with `ws` -> the e8m0 group scales
Built with the parent's flags (no -ffp-contract=off).

  tools/gen_fn146_w6.py --probe OUT.hip   (every probe arm)
  tools/gen_fn146_w6.py [--check]         (the would-be shipped object flashnext_w6146.hip: NOT written
                                           this round -- no engine arm, FN146's verdict)
"""
import argparse
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
from gen_fn141_t8141 import strip_symbols  # noqa: E402

SRC = os.path.join(ROOT, "crates/saber-kernels/hip/flashnext_trunk8.hip")
BODY = os.path.join(ROOT, "tools/capture/fn146/w6.hip.in")
FORMS = {"w6": (6, "false"), "e4": (8, "false"), "w6x": (6, "true")}
PROBE_SFX = [(f, bn, pf, mf) for f in ("w6", "e4", "w6x") for (bn, pf, mf) in
             ((128, 2, 1), (64, 2, 1), (64, 2, 2), (128, 2, 2), (64, 4, 1))]
PROBE_A8 = [(f, pf) for f in ("w6", "e4", "w6x") for pf in (2, 3, 4, 6)]
# the probe p1 / p3 winners (card 1, IC-cold): the merged projection at <= 16 rows (class rows <= 4),
# out / o at every decode M
SHIP_SFX = [("w6", 64, 2, 1)]
SHIP_A8 = [("w6", 2)]
OUT = os.path.join(ROOT, "crates/saber-kernels/hip/flashnext_w6146.hip")

HEADER = """\
// GENERATED by tools/gen_fn146_w6.py from flashnext_trunk8.hip + tools/capture/fn146/w6.hip.in
// -- do not edit; re-run the script.
"""
BARRIER = """
__device__ __forceinline__ void fn146_lds_barrier() {
  __builtin_amdgcn_fence(__ATOMIC_RELEASE, "workgroup", "local");
  __builtin_amdgcn_s_barrier();
  __builtin_amdgcn_fence(__ATOMIC_ACQUIRE, "workgroup", "local");
}
"""
SFX = """
extern "C" __global__ __launch_bounds__(DG_NT) void fn146_q8w6_sfx_{f}_n{bn}_pf{pf}{mfs}_ldc(
    const __bf16 *__restrict__ a, const unsigned char *__restrict__ w6,
    const unsigned char *__restrict__ s6, __bf16 *__restrict__ c, int m, int n8, int k, int ldc,
    int nbx8, const __bf16 *__restrict__ w16, __bf16 *__restrict__ cs, int ns) {{
  const int bx = (int)blockIdx.x, by = (int)blockIdx.y;
  if (bx < nbx8) {{
    fn146_q8w6_ring_impl<{form}, {bn}, {pf}, {rotx}, {mf}>(a, w6, s6, c, m, n8, k, (long)ldc, bx, by);
    return;
  }}
  for (int j = 0; j < {mf}; ++j) fn86_bgemm_m16_ldc_part(a, w16, cs, m, ns, k, ldc, bx - nbx8, by * {mf} + j);
}}
"""
A8 = """
extern "C" __global__ __launch_bounds__(DG_NT) void fn146_a8w6_{f}_n64_pf{pf}_ldc(
    const unsigned char *__restrict__ a, const unsigned char *__restrict__ w6,
    const float *__restrict__ as, const unsigned char *__restrict__ s6, __bf16 *__restrict__ c,
    int m, int n, int k, int ldc) {{
  fn146_a8w6_ring_impl<{form}, {pf}, {rotx}>(a, w6, as, s6, c, m, n, k, (long)ldc);
}}
"""


def derive(sfx, a8):
    s = strip_symbols(open(SRC).read())
    assert 'extern "C"' not in s
    lines = s.split("\n")
    k = 0
    while lines[k].startswith("//"):
        k += 1
    out = HEADER + "\n".join(lines[k:]) + BARRIER + open(BODY).read()
    for f, bn, pf, mf in sfx:
        form, rotx = FORMS[f]
        out += SFX.format(f=f, bn=bn, pf=pf, form=form, rotx=rotx, mf=mf, mfs="" if mf == 1 else f"_mf{mf}")
    for f, pf in a8:
        form, rotx = FORMS[f]
        out += A8.format(f=f, pf=pf, form=form, rotx=rotx)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--probe", default="")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    if a.probe:
        open(a.probe, "w").write(derive(PROBE_SFX, PROBE_A8))
        return 0
    txt = derive(SHIP_SFX, SHIP_A8)
    if a.check:
        ok = os.path.exists(OUT) and open(OUT).read() == txt
        print("flashnext_w6146.hip", "up to date" if ok else "STALE (not written: no engine arm yet)")
        return 0 if ok else 1
    open(OUT, "w").write(txt)
    return 0


if __name__ == "__main__":
    sys.exit(main())
