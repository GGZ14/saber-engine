#!/usr/bin/env python3
"""FN141: derive crates/saber-kernels/hip/flashnext_t8141.hip (code object `flashnext_t8141`) -- the
W8 GEMM's k-tile loop as a register ring -- from the shipped `flashnext_trunk8.hip`'s helpers
(VERBATIM, every `extern "C"` symbol of the parent removed) + the ring body
tools/capture/fn141/t8ring.hip.in (the probe's body, the same file).

  fn141_t8_a8w8_n64_pf<PF>_ldc  = fn111_t8_a8w8_n64_ldc's arguments and grid (N / 64 x ceil(M / 16),
                                  128 threads), byte-equal (card-1 oracle, fn141_probe.py t8)
  fn141_t8_q8w8_sfx_pf<PF>_ldc  = fn86_t8_q8w8_sfx_ldc's (the merged GDN in / QSA projection, act
                                  quant in the staging + the bf16 suffix workgroups), byte-equal (sfx)
Built with the parent's flags (no -ffp-contract=off: `acc += tile * (as * bs)` contracts as there).

  tools/gen_fn141_t8141.py [--check] [--probe OUT.hip]   (--probe: every PF arm of the probe)
"""
import argparse
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "crates/saber-kernels/hip/flashnext_trunk8.hip")
BODY = os.path.join(ROOT, "tools/capture/fn141/t8ring.hip.in")
OUT = os.path.join(ROOT, "crates/saber-kernels/hip/flashnext_t8141.hip")
SHIP_PF = (4,)
PROBE_PF = (2, 3, 4, 6)
SHIP_SFX = ()  # the sfx ring lost (FN141 p2)
PROBE_SFX = (2,)

HEADER = """\
// GENERATED by tools/gen_fn141_t8141.py from flashnext_trunk8.hip + tools/capture/fn141/t8ring.hip.in
// -- do not edit; re-run the script.
//
// Flash-Next (FN141): the W8 GEMM's k-tile loop as a register ring. `fn141_t8_a8w8_n64_pf<PF>_ldc`
// takes `fn111_t8_a8w8_n64_ldc`'s arguments and grid and writes the same bytes.
"""

SYM = """
extern "C" __global__ __launch_bounds__(DG_NT) void fn141_t8_a8w8_n64_pf{pf}_ldc(
    const unsigned char *__restrict__ a, const unsigned char *__restrict__ w,
    const float *__restrict__ as, const float *__restrict__ ws, __bf16 *__restrict__ c,
    int m, int n, int k, int ldc) {{
  fn141_t8_ring_impl<DG_BM, 64, DG_BK, DG_NW, {pf}>(a, w, as, ws, c, m, n, k, (long)ldc);
}}
"""
SFX = """
extern "C" __global__ __launch_bounds__(DG_NT) void fn141_t8_q8w8_sfx_pf{pf}_ldc(
    const __bf16 *__restrict__ a, const unsigned char *__restrict__ w8,
    const float *__restrict__ ws8, __bf16 *__restrict__ c, int m, int n8, int k, int ldc,
    int nbx8, const __bf16 *__restrict__ w16, __bf16 *__restrict__ cs, int ns) {{
  const int bx = (int)blockIdx.x, by = (int)blockIdx.y;
  if (bx < nbx8) {{
    fn141_q8gemm_ring_impl<DG_BM, DG_BN, DG_BK, DG_NW, {pf}>(a, w8, ws8, c, m, n8, k, (long)ldc, bx, by);
    return;
  }}
  fn86_bgemm_m16_ldc_part(a, w16, cs, m, ns, k, ldc, bx - nbx8, by);
}}
"""


def strip_symbols(s):
    """the parent's source with every `extern "C"` kernel block removed (helpers kept verbatim)"""
    out, i = [], 0
    while True:
        j = s.find('extern "C"', i)
        if j < 0:
            out.append(s[i:])
            return "".join(out)
        out.append(s[i:j])
        k = s.index("{", j)
        depth = 0
        while True:
            if s[k] == "{":
                depth += 1
            elif s[k] == "}":
                depth -= 1
                if depth == 0:
                    break
            k += 1
        i = k + 1


def derive(pfs, sfx):
    s = strip_symbols(open(SRC).read())
    assert 'extern "C"' not in s
    lines = s.split("\n")
    k = 0
    while lines[k].startswith("//"):
        k += 1
    prefix = "\n".join(lines[k:])
    body = open(BODY).read()
    return (HEADER + prefix + body + "".join(SYM.format(pf=p) for p in pfs)
            + "".join(SFX.format(pf=p) for p in sfx))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--probe", default="")
    a = ap.parse_args()
    if a.probe:
        open(a.probe, "w").write(derive(PROBE_PF, PROBE_SFX))
        return 0
    txt = derive(SHIP_PF, SHIP_SFX)
    if a.check:
        ok = os.path.exists(OUT) and open(OUT).read() == txt
        print("flashnext_t8141.hip", "up to date" if ok else "STALE")
        return 0 if ok else 1
    open(OUT, "w").write(txt)
    return 0


if __name__ == "__main__":
    sys.exit(main())
