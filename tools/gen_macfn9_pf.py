#!/usr/bin/env python3
"""MACFN9: derive `crates/saber-kernels/hip/moe_macfn9.hip` -- the MACaQ int4 grouped PREFILL tiles (TP=2 half records,
xtier v2 tag 3, the shared expert on its MACaQ record = `--fn-macaq-shared int4`), a NEW object: moe_macfn3 and every
shipped object stay byte-identical.

The bodies are `macfn3_i4_impl`'s text VERBATIM (moe_macfn3.hip, between the `the grouped GEMM` banner and the
instantiation macro) instantiated at prefill shapes moe_macfn3 does not carry:

  macfn9_i4_bk128_ks1_tm{4,8}_g1_pf   gate_up (gathered by token), K 2,560, slab 128, the register double buffer
  macfn9_i4_bk64_ks1_tm{4,8}_g0_pf    down (compact rows), K 320, slab 64, the register double buffer
  macfn9_i4_bk128_ks1_tm8_g1          gate_up 128-row tiles, no double buffer
  macfn9_i4_bk64_ks1_tm8_g0           down 128-row tiles, no double buffer

THE BYTE LAW vs MACFN5's legacy prefill cells (`macfn3_i4_bk128_ks1_tm4_g1` / `macfn3_i4_bk64_ks1_tm4_g0`, the MACaQ
prefill route above 512 rows): the accumulator is an exact int32 over ALL of K whatever the slab schedule (PF only
moves the W loads earlier) and whatever the tile height (a row's 16x16 WMMA blocks see the same A row and the same W
fragments in the same k order), and the epilogue is one expression of (acc, as[row], ws[n]) -- every output element is
the same bits by construction. The tile height (tm 8 = 128-row route tiles) changes only the route tables (FN4's
tile law: tile -> expert, first row, rows), never a row's arithmetic. Built -ffp-contract=off (saber-kbuild EXTRA_FLAGS
row `moe_macfn9`), as moe_macfn3.

  python3 tools/gen_macfn9_pf.py          # write
  python3 tools/gen_macfn9_pf.py --check  # the committed file == the derivation
"""
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HIP = os.path.join(REPO, "crates/saber-kernels/hip")
M3 = os.path.join(HIP, "moe_macfn3.hip")
OUT = os.path.join(HIP, "moe_macfn9.hip")

# (name, NS, KS, TM, GATHER, PF, NTW)  NTW = the W fragment loads nontemporal (the parent's) or cached (`_wc`: a
# route tile re-reads its expert's W once a tile, so a prefill expert of several tiles can hit L2 / MALL)
CELLS = [
    ("macfn9_i4_bk128_ks1_tm4_g1_pf", 8, 1, 4, True, True, True),
    ("macfn9_i4_bk128_ks1_tm8_g1_pf", 8, 1, 8, True, True, True),
    ("macfn9_i4_bk128_ks1_tm8_g1", 8, 1, 8, True, False, True),
    ("macfn9_i4_bk64_ks1_tm4_g0_pf", 4, 1, 4, False, True, True),
    ("macfn9_i4_bk64_ks1_tm8_g0_pf", 4, 1, 8, False, True, True),
    ("macfn9_i4_bk64_ks1_tm8_g0", 4, 1, 8, False, False, True),
    ("macfn9_i4_bk128_ks1_tm4_g1_wc", 8, 1, 4, True, False, False),
    ("macfn9_i4_bk128_ks1_tm8_g1_wc", 8, 1, 8, True, False, False),
    ("macfn9_i4_bk64_ks1_tm4_g0_wc", 4, 1, 4, False, False, False),
    ("macfn9_i4_bk64_ks1_tm8_g0_wc", 4, 1, 8, False, False, False),
]

HEAD = """// GENERATED by tools/gen_macfn9_pf.py from moe_macfn3.hip -- do not edit by hand, re-run the generator.
// MACFN9 (2026-11-22): the MACaQ int4 grouped PREFILL tiles (see the generator's docstring for the byte law).
// Saber's own arithmetic; contraction is OFF in this whole object (saber-kbuild's EXTRA_FLAGS row).
#include <hip/hip_runtime.h>
#include <hip/hip_bf16.h>

"""

WS = """
// ------------------------------------------------------------------------------------- MACFN9: W-stationary tiles
// One workgroup an (n-block, EXPERT): the workgroup of the expert's FIRST route tile loads each wave's W fragments
// for ALL of K into registers once (KC / 16 dwords a lane), then walks every route tile of that expert (tiles are
// expert-major: tile_expert[t] == expert for a run of t) staging each tile's A slabs in LDS exactly as the parent
// does; the workgroups of the expert's later tiles exit at entry. A W byte is read once an expert instead of once a
// tile. Every output element is the parent's int32 sum over the same A row and the same W fragments in the same k
// order, and the same epilogue expression: the bytes are the parent's by construction (ks 1 only; K must be KC).
template <int NS, int DTM, int KC, bool GATHER, bool NTW>
__device__ __forceinline__ void macfn9_ws_impl(
    const signed char *__restrict__ A, const unsigned long long *__restrict__ xptr,
    const int *__restrict__ tile_expert, const int *__restrict__ tile_row0, const int *__restrict__ tile_rows,
    const int *__restrict__ row_tok, const int *__restrict__ meta, const float *__restrict__ As,
    __bf16 *__restrict__ C, int N, int K) {
  constexpr int DBK = 16 * NS, DASTR = DBK + 8, NTH = 256, KST = KC / 16, SLABS = KC / DBK;
  static_assert(KC % DBK == 0, "K slabs");
  __shared__ signed char sA[16 * DTM * DASTR];
  __shared__ int s_arow[16 * DTM];
  const int ntile = meta[0];
  const int tile0 = blockIdx.y;
  if (tile0 >= ntile) return;
  const int texp = tile_expert[tile0];
  if (tile0 > 0 && tile_expert[tile0 - 1] == texp) return;
  if (K != KC) __builtin_trap();
  const int tid = threadIdx.x, lane = tid & 31, wave = tid >> 5;
  const int col = lane & 15, kb8 = (lane >> 4) * 8;
  const unsigned char *__restrict__ W = (const unsigned char *)(uintptr_t)xptr[3 * (size_t)texp + 0];
  const float *__restrict__ Ws = (const float *)(uintptr_t)xptr[3 * (size_t)texp + 1];
  const int ntiles = N >> 4;
  const int nt = blockIdx.x * 8 + wave;
  const bool live = nt < ntiles;
  const int ntl = live ? nt : ntiles - 1;
  const unsigned char *wbase = W + (size_t)ntl * KST * 128;
  unsigned w[KST];
#pragma unroll
  for (int st = 0; st < KST; ++st) w[st] = m9_wload<NTW>((const unsigned *)(wbase + ((unsigned)lane * 4 + (unsigned)(st * 128))));
  const int n = ntl * 16 + col;
  const float wsn = Ws[n];
  constexpr int ACH = 16 * DTM * DBK / 16;
  for (int tile = tile0; tile < ntile && tile_expert[tile] == texp; ++tile) {
    const int row0 = tile_row0[tile], M = tile_rows[tile];
    __syncthreads();
    for (int r = tid; r < 16 * DTM; r += NTH) {
      const int rr = r < M - 1 ? r : M - 1;
      s_arow[r] = GATHER ? row_tok[row0 + rr] : row0 + rr;
    }
    __syncthreads();
    m3_intx8 acc[DTM];
#pragma unroll
    for (int i = 0; i < DTM; ++i)
#pragma unroll
      for (int e = 0; e < 8; ++e) acc[i][e] = 0;
#pragma unroll
    for (int s = 0; s < SLABS; ++s) {
      const int kk0 = s * NS;
      for (int c = tid; c < ACH; c += NTH) {
        const int r = c / (DBK / 16), o = (c % (DBK / 16)) * 16;
        *(m3_uint4 *)&sA[r * DASTR + o] = *(const m3_uint4 *)(A + (size_t)s_arow[r] * K + kk0 * 16 + o);
      }
      __syncthreads();
#pragma unroll
      for (int st = 0; st < NS; ++st) {
        const unsigned d = w[s * NS + st];
        m3_int2 wv;
        wv[0] = (int)((d << 4) & 0xF0F0F0F0u);
        wv[1] = (int)(d & 0xF0F0F0F0u);
#pragma unroll
        for (int i = 0; i < DTM; ++i) {
          const signed char *pa = &sA[(i * 16 + col) * DASTR + st * 16 + kb8];
          m3_int2 af;
          af[0] = *(const int *)pa;
          af[1] = *(const int *)(pa + 4);
          acc[i] = m3_wmma(af, wv, acc[i]);
        }
      }
      __syncthreads();
    }
    if (live) {
#pragma unroll
      for (int i = 0; i < DTM; ++i)
#pragma unroll
        for (int e = 0; e < 8; ++e) {
          const int m = i * 16 + kb8 + e;
          if (m < M) C[(size_t)(row0 + m) * N + n] = (__bf16)m3_epi(acc[i][e], As[s_arow[m]], wsn);
        }
    }
  }
}
#define MACFN9_WS(name, NS, TM, KC, G, NTW)                                                                       \\
  extern "C" __global__ __launch_bounds__(256) void name(                                                       \\
      const signed char *__restrict__ a, const unsigned long long *__restrict__ xptr,                          \\
      const int *__restrict__ tile_expert, const int *__restrict__ tile_row0, const int *__restrict__ tile_rows, \\
      const int *__restrict__ row_tok, const int *__restrict__ meta, const float *__restrict__ as,             \\
      int *__restrict__ p, int *__restrict__ cnt, __bf16 *__restrict__ c, int n, int k, int pmax) {          \\
    macfn9_ws_impl<NS, TM, KC, G, NTW>(a, xptr, tile_expert, tile_row0, tile_rows, row_tok, meta, as, c, n, k);  \\
  }
// down (compact rows, K 320 at TP=2): 20 W dwords a lane
MACFN9_WS(macfn9_i4ws_bk64_tm4_g0, 4, 4, 320, false, true)
MACFN9_WS(macfn9_i4ws_bk64_tm4_g0_wc, 4, 4, 320, false, false)
MACFN9_WS(macfn9_i4ws_bk64_tm2_g0, 4, 2, 320, false, true)
// (gate_up's 160 W dwords a lane spill: not instantiated)
#undef MACFN9_WS
"""


def sub(s, old, new, count=1):
    n = s.count(old)
    assert n == count, (old, n, count)
    return s.replace(old, new)


def derive():
    src = open(M3).read()
    a = src.index("// ------------------------------------------------------------------------------------- the grouped GEMM")
    b = src.index("#define MACFN3_I4(name", a)
    body = src[a:b]
    h0 = src.index("typedef int m3_int2")
    h1 = src.index("static __device__ __forceinline__ float m3_bf(", h0)
    # the one anchored change: the W fragment load's cache policy is a template parameter (the parent = NTW true)
    body = sub(body, "template <int NS, int DKS, int DTM, bool GATHER, bool PF = false, bool SX = false>",
               "template <int NS, int DKS, int DTM, bool GATHER, bool PF = false, bool SX = false, bool NTW = true>")
    body = sub(body, "      d[st] = __builtin_nontemporal_load(\n          (const unsigned *)(wbase",
               "      d[st] = m9_wload<NTW>(\n          (const unsigned *)(wbase")
    wl = ("template <bool NT>\nstatic __device__ __forceinline__ unsigned m9_wload(const unsigned *p) {\n"
          "  if constexpr (NT) return __builtin_nontemporal_load(p); else return *p;\n}\n")
    out = [HEAD, src[h0:h1], "\n", wl, body]   # the types + m3_wmma / m3_epi, verbatim
    out.append(src[b:src.index("// gate_up (gathered by token)", b)].replace("MACFN3_I4", "MACFN9_I4")
               )
    b_ = lambda v: "true" if v else "false"
    for name, ns, ks, tm, g, pf, ntw in CELLS:
        tail = "" if ntw and not pf else (", true" if ntw else f", {b_(pf)}, false, false")
        out.append(f"MACFN9_I4({name}, {ns}, {ks}, {tm}, {b_(g)}{tail})\n")
    out.append("#undef MACFN9_I4\n")
    out.append(WS)
    return "".join(out)


def main():
    s = derive()
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and open(OUT).read() == s
        print("moe_macfn9.hip == the derivation" if ok else "moe_macfn9.hip DIFFERS from the derivation")
        sys.exit(0 if ok else 1)
    open(OUT, "w").write(s)
    print(f"wrote {OUT} ({len(s)} bytes, {len(CELLS)} cells)")


if __name__ == "__main__":
    main()
