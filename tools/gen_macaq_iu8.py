#!/usr/bin/env python3
"""Generate the per-token INT8 activation producers of the W4A8-iu8 pack from the MACaQ had32 producer
twins, by anchored substitution (every anchor must occur exactly once).

    tools/gen_macaq_iu8.py             write the three sources
    tools/gen_macaq_iu8.py --check     exit 1 if any committed source differs from what this would write

Each `*_hadi8_*` symbol is its `*_had32_*` parent line for line up to the transformed values x (the shipped
producer's bf16-rounded v, then `macaq_had32`: * t, the block-32 Hadamard, * 1/sqrt(32)); the ONLY change is
the tail: the e4m3 law becomes the pack's per-token symmetric int8 law:

    sc = max(amax / 127, 1e-30)            (correctly rounded f32 division, `__fdiv_rn`)
    q  = clamp(rne(x / sc), -127, 127)     (correctly rounded division, then rint = round-half-even)

stored as int8 in the A-TILED fragment order at EVERY M (the iu8 GEMMs read only that order: there is no
row-major int8 edge and no tiled0 instantiation). Kernel arguments are unchanged (the had32 twin's list,
`had_t` last), so `abi::signature_for` derives them like the had32 twins'. Contraction: each output keeps its
parent's (mxfp4_hadi8 default like mxfp4_had; attn_glue_hadi8 / saber_ar_hadi8 -ffp-contract=off by
saber-kbuild's `attn_glue` / `saber_ar_` prefix rows); the new tail has no multiply-add.
"""
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HIP = os.path.join(REPO, 'crates', 'saber-kernels', 'hip')


def sub(s, a, b, what):
    n = s.count(a)
    if n != 1:
        raise SystemExit(f'{what}: anchor occurs {n} times: {a[:90]!r}')
    return s.replace(a, b)


def cut(s, start, end, b, what):
    """replace the text from `start` (inclusive) to `end` (exclusive), both unique."""
    i, j = s.find(start), s.find(end)
    if s.count(start) != 1 or s.count(end) != 1 or j < i:
        raise SystemExit(f'{what}: cut anchors {start[:60]!r} .. {end[:60]!r}')
    return s[:i] + b + s[j:]


HEAD = ('// GENERATED by tools/gen_macaq_iu8.py from {src} -- do not edit; regenerate.\n'
        '// Saber source (2026-11-17): the W4A8-iu8 pack\'s per-token INT8 twins of the had32 producers (int8 codes +\n'
        '// one f32 scale a row, A-tiled at every M).\n')

I8_TAIL_MX = '''  const float sc = fmaxf(__fdiv_rn(lds[0], 127.f), 1e-30f);
  if (tid == 0) scale[row] = sc;
#pragma unroll
  for (int mg = 0; mg < MAXG; ++mg) {
    const int g = tid + mg * ART;
    if (g >= NV) break;
    uint32_tt lo = 0, hi = 0;
#pragma unroll
    for (int j = 0; j < 4; ++j) lo |= macaq_i8_code(sv[mg][j], sc) << (j * 8);
#pragma unroll
    for (int j = 4; j < 8; ++j) hi |= macaq_i8_code(sv[mg][j], sc) << ((j - 4) * 8);
    if (TILED) ((uint2 *)q)[(mt * kst + (g >> 1)) * 32 + lrow + 16 * (g & 1)] = make_uint2(lo, hi);
    else ((uint2 *)q)[(long)row * (NV * 8 / 8) + g] = make_uint2(lo, hi);
  }
}
'''


def gen_mx():
    s = open(os.path.join(HIP, 'mxfp4_had.hip')).read()
    s = sub(s, '#include "macaq_had.h"\n', '#include "macaq_had.h"\n#include "macaq_i8.h"\n', 'mx include')
    s = cut(s, '  const float sc = fmaxf(lds[0] * (1.f / 448.f), 1.f / (448.f * 512.f));\n',
            '// ---- add_rms_quant (parent: saber_add_rms_quant_impl)', I8_TAIL_MX + '\n', 'mx tail')
    s = sub(s, '// the parents\' amax -> scale -> e4m3 tail, shared (multiply by the reciprocal, clamp, RNE convert)\n',
            '// the int8 tail, shared (absmax / 127, divide, clamp, round-half-even)\n',
            'mx tail doc')
    s = s.replace('macaq_q8_tail', 'macaq_i8_tail')
    for a in ('ARQ(add_rms_quant_had32_t256_tiled0, 256, false)\n', 'ARQ(add_rms_quant_had32_t512_tiled0, 512, false)\n',
              'SMQ(silu_mul_quant_had32_t256_tiled0, 256, false)\n', 'SMQ(silu_mul_quant_had32_t512_tiled0, 512, false)\n',
              'GNQ(gdn_norm_quant_had32_t256, false)\n'):
        s = sub(s, a, '', 'mx drop ' + a.strip())
    for a in ('add_rms_quant_had32_', 'silu_mul_quant_had32_', 'gdn_norm_quant_had32_'):
        assert s.count(a) == 2 if a != 'gdn_norm_quant_had32_' else s.count(a) == 1, (a, s.count(a))
        s = s.replace(a, a.replace('had32', 'hadi8'))
    for a in ('macaq_add_rms_quant_impl', 'macaq_silu_mul_quant_impl', 'macaq_gdn_norm_quant_impl'):
        s = s.replace(a, a.replace('macaq_', 'macaq_i8_'))
    return HEAD.format(src='crates/saber-kernels/hip/mxfp4_had.hip') + s


I8_TAIL_AG = '''  const float sc = fmaxf(__fdiv_rn(lds[0], 127.f), 1e-30f);
  if (tid == 0) scale[row] = sc;
#pragma unroll
  for (int mg = 0; mg < MAXG; ++mg) {
    const int g = tid + mg * T;
    if (g >= nv) break;
    u32 lo = 0, hi = 0;
#pragma unroll
    for (int j = 0; j < 4; ++j) lo |= macaq_i8_code(sv[mg][j], sc) << (j * 8);
#pragma unroll
    for (int j = 4; j < 8; ++j) hi |= macaq_i8_code(sv[mg][j], sc) << ((j - 4) * 8);
    if (TILED) ((uint2 *)q)[(mt * kst + (g >> 1)) * 32 + lrow + 16 * (g & 1)] = make_uint2(lo, hi);
    else ((uint2 *)q)[g] = make_uint2(lo, hi);
  }
}

'''


def gen_ag():
    s = open(os.path.join(HIP, 'attn_glue_had.hip')).read()
    s = sub(s, '#include "macaq_had.h"\n', '#include "macaq_had.h"\n#include "macaq_i8.h"\n', 'ag include')
    s = cut(s, '  const float sc = fmaxf(lds[0] / 448.f, 1.f / (448.f * 512.f));\n', '#define AGQ(name, TILED)',
            I8_TAIL_AG, 'ag tail')
    s = sub(s, 'AGQ(attn_gate_quant_had32_t256_tiled0, false)\n', '', 'ag drop tiled0')
    s = sub(s, 'AGQ(attn_gate_quant_had32_t256_tiled1, true)', 'AGQ(attn_gate_quant_hadi8_t256_tiled1, true)', 'ag name')
    s = s.replace('macaq_attn_gate_quant_impl', 'macaq_i8_attn_gate_quant_impl')
    return HEAD.format(src='crates/saber-kernels/hip/attn_glue_had.hip') + s


I8_TAIL_AR = '''  const float sc = fmaxf(__fdiv_rn(m, 127.0f), 1e-30f);
  if (tid == 0) scale_out[b] = sc;

  // int8 codes in the A-TILED fragment order (row b, 8-group g = at[i] - row)
  const int mt = b >> 4, lrow = b & 15, kst = k16 >> 1;
#pragma unroll
  for (int i = 0; i < kNqMaxWords; ++i) {
    u32 lo = 0, hi = 0;
#pragma unroll
    for (int j = 0; j < 4; ++j) lo |= macaq_i8_code(v[i][j], sc) << (j * 8);
#pragma unroll
    for (int j = 4; j < 8; ++j) hi |= macaq_i8_code(v[i][j], sc) << ((j - 4) * 8);
    const long g = at[i] - row;
    if (ok[i]) ((uint2*)q_out)[((long)mt * kst + (g >> 1)) * 32 + lrow + 16 * (g & 1)] = make_uint2(lo, hi);
  }
}

'''


def gen_ar():
    s = open(os.path.join(HIP, 'saber_ar_had.hip')).read()
    s = sub(s, '#include "macaq_had.h"\n', '#include "macaq_had.h"\n#include "macaq_i8.h"\n', 'ar include')
    s = cut(s, '  const float sc = fmaxf(m * (1.0f / 448.0f), 1.0f / 229376.0f);\n', '}  // namespace sar',
            I8_TAIL_AR, 'ar tail')
    s = s.replace('nq_row_had(', 'nq_row_hadi8(')
    s = sub(s, 'saber_ar_oneshot_2rank_exact_nq_ssqfma_had32_bf16(', 'saber_ar_oneshot_2rank_exact_nq_ssqfma_hadi8_bf16(',
            'ar name')
    return HEAD.format(src='crates/saber-kernels/hip/saber_ar_had.hip') + s


OUT = {'mxfp4_hadi8.hip': gen_mx, 'attn_glue_hadi8.hip': gen_ag, 'saber_ar_hadi8.hip': gen_ar}


def main():
    check = '--check' in sys.argv[1:]
    bad = 0
    for name, fn in OUT.items():
        text = fn()
        p = os.path.join(HIP, name)
        if check:
            cur = open(p).read() if os.path.exists(p) else None
            if cur != text:
                print(f'{p}: STALE (regenerate with tools/gen_macaq_iu8.py)')
                bad += 1
            else:
                print(f'{p}: up to date')
        else:
            open(p, 'w').write(text)
            print(f'wrote {p} ({len(text)} B)')
    sys.exit(1 if bad else 0)


if __name__ == '__main__':
    main()
